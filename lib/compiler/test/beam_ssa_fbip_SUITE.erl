%% The probe functions and the arguments they are called with. `arg_src'
%% also gets values that are not (well-formed) records so that the exception
%% path is compared as well.
cases() ->
    [{mk,         [0, 42, x, [1,2], {a,b}]},
     {safe,       [0, 42, x, [1,2]]},
     {join,       [true, false, other, 0, [1,2]]},
     {join_used_twice, [true, false, other, 0]},
     {join_arg,   [{r,1,undefined,3}, {r,9,8,7}, {s,1,2,3}, {r,1,2},
                   42, not_a_record]},
     {join_extracted, [{{r,9,8,7},zz}, {{r,1,2,3},[x]}, 42, not_a_tuple]},
     {phi_call,   [true, false, x, other]},
     {nested,     [0, 42, x, [1,2]]},
     {loop_alloc, [0, 1, 3]},
     {phi_lit,    [true, false, x, other]},
     {phi_arg,    [true, false, {r,1,2,3}, {s,1,2,3}]},
     {passed,     [0, 42, x]},
     {second_update, [0, 42, x]},
     {spin,       [0, 1, 3]},
     {looped,     [[], [a,b], [1,2]]},
     {map_upd,    [0, x]},
     {list_upd,   [0, x]},
     {bin_upd,    [0, x]},
