    Config.

%%============================================================================
%% Test cases
%%============================================================================

%% The positive case: the source of the update is the result of a local
%% function that always returns a freshly allocated record, it is used
%% exactly once and is not otherwise observable, so the pass may turn the
%% copying update into an in-place update - but only when it is enabled.
safe_hint_rewritten(Config) ->
    {_Mod, Builds} = build_probe(Config, "beam_ssa_fbip_safe"),

    ?assertEqual({atom,copy}, hint(plain, Builds, safe, 1)),
    ?assertEqual({atom,inplace}, hint(fbip, Builds, safe, 1)),
    ok.

%% The position rule is generalized to "the definition block dominates the
%% update block and no cycle through the update block avoids it". This
%% accepts a fresh source that is defined before an intervening branch/join
%% and updated after it, where the update block's unique predecessor is the
%% join block rather than the definition block. The old rule - "same block,
%% or the definition is the unique predecessor of the update block" -
%% rejected it, so the plain build keeps the copying update while the fbip
%% build turns it into an in-place one.
join_hint_rewritten(Config) ->
    {_Mod, Builds} = build_probe(Config, "beam_ssa_fbip_join"),

    ?assertEqual({atom,copy}, hint(plain, Builds, join, 1)),
    ?assertEqual({atom,inplace}, hint(fbip, Builds, join, 1)),
    ok.

%% The root set of the dominance test is "the function's entry block plus
%% every predecessor-less block", not just the predecessor-less blocks (see
%% roots/3 in beam_ssa_fbip). This probe pins the CFG shape that motivated
%% the entry: its body *starts* with a `receive', so the compiler-generated
%% peek/skip loop is entered directly from the function's entry block, and
%% the entry block leads straight into a cycle of the CFG.
%%
%% The stricter root set may only ever reject more rewrites, so this shape
%% must still be accepted: the fresh source `R0' is defined after the
%% receive and updated after an intervening branch/join, so the definition
%% block dominates the update block (and no cycle through the update block
%% avoids it). The update must therefore be rewritten to `inplace' with the
%% option and stay `copy' without it.
entry_hint_rewritten(Config) ->
    {_Mod, Builds} = build_probe(Config, "beam_ssa_fbip_entry"),

    ?assertEqual({atom,copy}, hint(plain, Builds, entry_recv, 1)),
    ?assertEqual({atom,inplace}, hint(fbip, Builds, entry_recv, 1)),
    ok.

%% The remaining fresh-source clauses of the contract, each with a probe
%% whose source the ordinary destructive-update pass cannot prove unique:
%%
%%   * `phi_call/1' - the source is an all-fresh `phi' (a case with two
%%     branches, each calling the fresh-returning mk/1). The update reads
%%     the phi, so an all-fresh phi is the whole freshness proof here.
%%   * `nested/1' - the source is the result of safe/1. safe/1 is
%%     fresh-returning *only once its own update has been rewritten to
%%     `inplace'*, so this rewrite needs a second module-wide iteration (the
%%     fixpoint in beam_ssa_fbip:iterate/2) and exercises both the
%%     "already-`inplace' `update_record' is fresh" clause and the "call to
%%     a fresh-returning function" clause.
%%   * `loop_alloc/2' - the fresh record is allocated inside the loop and
%%     updated once per allocation, i.e. the position rule accepts a loop as
%%     long as every execution of the update has its own allocation.
fresh_source_shapes_rewritten(Config) ->
    {_Mod, Builds} = build_probe(Config, "beam_ssa_fbip_shapes"),

    ?assertEqual({atom,copy}, hint(plain, Builds, phi_call, 1)),
    ?assertEqual({atom,inplace}, hint(fbip, Builds, phi_call, 1)),

    ?assertEqual({atom,copy}, hint(plain, Builds, nested, 1)),
    ?assertEqual({atom,inplace}, hint(fbip, Builds, nested, 1)),

    ?assertEqual({atom,copy}, hint(plain, Builds, loop_alloc, 2)),
    ?assertEqual({atom,inplace}, hint(fbip, Builds, loop_alloc, 2)),
    ok.

%% The widened position rule on its own must never rewrite an update whose
%% source is not fresh or not uniquely owned; the extra shapes accepted by
%% the rule are only ever accepted together with the freshness and
%% single-use proofs. The `join_*' functions below have exactly the same CFG
%% shape as `join/1' (definition, then a branch/join, then the update), but
%% their source is used twice, is a function argument, or is a sub-term of
%% another term.
join_hints_unchanged(Config) ->
    {_Mod, Builds} = build_probe(Config, "beam_ssa_fbip_join_unsafe"),

    %% The source is used twice, so it has an observable alias after the
    %% update: it is not uniquely owned and the update must copy.
    unchanged(Builds, join_used_twice, 1, {atom,copy}),

    %% The source is a function argument: never fresh.
    unchanged(Builds, join_arg, 1, {atom,reuse}),

    %% The source is a sub-term of another term, extracted with element/1:
    %% not freshly allocated, so it may be shared with whatever the caller
    %% passed in.
    unchanged(Builds, join_extracted, 1, {atom,reuse}),
    ok.

%% The unsafe witnesses. None of them may be rewritten, and - even more
%% importantly - the option must not change their hint at all. The
%% function-argument source is expected to keep the `reuse' that the
%% ordinary destructive-update pass produces (it reuses the argument's
%% frame slot); the value that is sent, captured by a fun or simply used
%% twice must keep the copying update.
unsafe_hints_unchanged(Config) ->
    {_Mod, Builds} = build_probe(Config, "beam_ssa_fbip_unsafe"),

    %% A value that is handed out to another process (`!') is observable
    %% outside this function, so it may never be written in place.
    unchanged(Builds, sent, 1, {atom,copy}),

    %% A value captured by a fun is reachable from the fun object, so the
    %% update must copy.
    unchanged(Builds, captured, 1, {atom,copy}),

    %% A value that is used more than once has an observable alias after the
    %% update, so the update must copy.
    unchanged(Builds, used_twice, 1, {atom,copy}),

    %% The source is a function argument: it is not freshly allocated and
    %% the ordinary destructive-update pass reuses the argument's own frame
    %% slot. The pass must leave that `reuse' untouched (and in particular
    %% must not claim `inplace').
    unchanged(Builds, arg_src, 1, {atom,reuse}),
    ok.

%% The negative half of the freshness rule for the shapes that the other
%% test cases do not already pin:
%%
%%   * `phi_lit/1' - the `phi' has an incoming compile-time literal, and a
%%     literal is never fresh (literals are shared), so the `phi' is not
%%     all-fresh even though its other incoming value comes from mk/1,
%%   * `phi_arg/1' - the `phi' has an incoming function argument,
%%   * `passed/1' - the source is passed to a call, which is a second use,
%%   * `second_update/1' - the allocation is updated twice and the original
%%     is also returned. The two updates are merged into a single
%%     `update_record' (ssa_opt_merge_updates) before this pass runs, so
%%     there is only one hint to check; the returned original makes the
%%     source observable and the update must copy,
%%   * `spin/2' - the value is threaded through a recursive loop, so the
%%     value the update reads is that loop's argument. This is the
%%     source-level shape behind "the update could run more than once per
%%     allocation": a loop can only reach a value defined outside it by
%%     threading it through, which is a second use,
%%   * '-looped/1-fun-0-'/2 - the update runs inside a `foldl' fun and its
%%     source is that fun's argument.
%%
%% Each must keep exactly its hint, and - stronger than the hint alone - the
%% whole function must be unchanged: the pass is a pure hint change and may
%% not disturb anything else.
fresh_source_declines(Config) ->
    {_Mod, Builds} = build_probe(Config, "beam_ssa_fbip_declines"),

    unchanged(Builds, phi_lit, 1, {atom,copy}),
    unchanged(Builds, phi_arg, 1, {atom,reuse}),
    unchanged(Builds, passed, 1, {atom,copy}),
    unchanged(Builds, second_update, 1, {atom,copy}),
    unchanged(Builds, spin, 2, {atom,reuse}),
    unchanged(Builds, '-looped/1-fun-0-', 2, {atom,reuse}),
    ok.

%% In-place reuse of lists and maps is not implemented and cannot be a
%% compiler-only change (no list/map update instruction carries a hint); the
%% pass only ever rewrites `update_record', so a list or map update is not
%% even represented as an updateable instruction. A record update whose
%% source is a binary built by `bs_create_bin' is likewise not an
%% `update_record': the type analysis proves it can never succeed and
%% replaces it with a `{badrecord,_}' raise. All three functions must have no
%% `update_record' at all in either build - in particular the option must not
%% introduce an `inplace' one (see divergence 1 in the header).
no_reuse_for_lists_maps_binaries(Config) ->
    {_Mod, Builds} = build_probe(Config, "beam_ssa_fbip_noreuse"),

    lists:foreach(fun(Fun) ->
                          lists:foreach(fun(Set) ->
                                                ?assertEqual(none, hint(Set, Builds, Fun, 1))
                                        end, [plain,fbip])
                  end, [map_upd,list_upd,bin_upd]),
    ok.

%% Sources that are compile-time literal records (`(#r{a=1})#r{b=2}',
%% `T = #r{a=1}, T#r{b=2}', and a `case' returning literal records) are
%% constant-folded before the SSA passes, so no update_record instruction is
%% emitted for them at all - there is nothing for the pass to rewrite. This
%% is asserted for both builds; note in particular that no `inplace' update
%% may appear here.
literal_sources_not_rewritten(Config) ->
    {_Mod, Builds} = build_probe(Config, "beam_ssa_fbip_literal"),

    lists:foreach(fun(Fun) ->
                          lists:foreach(fun(Set) ->
                                                ?assertEqual(none, hint(Set, Builds, Fun, 1))
                                        end, [plain,fbip])
                  end, [lit_inline,lit_var,lit_case]),
    ok.

%% The pass is opt-in, so it must not perturb a module in which it cannot
%% fire: for a module with no `update_record' at all the eligibility gate is
%% already false and the module must be compiled identically with `fbip_opt'
%% and without it. The whole module is compared, not just one function, so
%% this pins "default off changes nothing" for the default pipeline. The
%% inert `no_ssa_opt_fbip' (see divergence 2 in the header) is included
%% because it must at least not change anything on its own.
default_off_unchanged(Config) ->
    {_Mod, Builds} =
        build_probe(Config, "beam_ssa_fbip_passive",
                    [{plain,[binary]},
                     {fbip,[binary,fbip_opt]},
                     {nofbip,[binary,no_ssa_opt_fbip]}],
                    fun passive_source/1),

    [{_,_,_,Ref} | Rest] = Builds,
    Normalized = normalize(Ref),
    lists:foreach(fun({Set,_,_,Code}) ->
                          ?assertEqual({Set,Normalized}, {Set,normalize(Code)})
                  end, Rest),
    ?assertEqual(3, length(Builds)),
    ok.

%% The kill switch that works: `no_ssa_opt' skips the whole SSA optimization
%% phase - the pass is invoked from inside
%% beam_ssa_destructive_update:opt/2, which is one of its sub-passes - so the
%% record updates are compiled as copying constructions and no
%% `update_record' instruction is generated at all. The pass therefore
%% cannot fire, and the build must still behave exactly like the default
%% one.
%%
%% `no_ssa_opt_fbip' is NOT covered here because it does not disable the
%% pass; see divergence 2 in the suite header.
kill_switches(Config) ->
    {_Mod, Builds} =
        build_probe(Config, "beam_ssa_fbip_kill",
                    [{no_ssa_opt,[binary,fbip_opt,no_ssa_opt]}]),

    lists:foreach(fun(Fun) ->
                          ?assertEqual(none, hint(no_ssa_opt, Builds, Fun, 1))
                  end, [safe,join,nested,phi_call]),
    ?assertEqual(none, hint(no_ssa_opt, Builds, loop_alloc, 2)),

    %% Skipping the SSA optimization phase must not change what the probes
    %% do.
    lists:foreach(fun({Fun, Args}) ->
                          check_calls(Builds, Fun, Args)
                  end, cases()),
    ok.

%% The transform must be behaviour preserving: every probe function must
%% load and return exactly the same values (and the same exceptions) in both
%% builds, and those results must be the expected ones.
behaviour_identical(Config) ->
    {_Mod, Builds} = build_probe(Config, "beam_ssa_fbip_behaviour"),

    lists:foreach(fun({Fun, Args}) ->
                          check_calls(Builds, Fun, Args)
                  end, cases()),
    ok.

