     {lit_var,    [0, ignored]},
     {recv_after, [0, 42, x, [1,2], {a,b}]},
     %% `entry_recv/1' is called with a fresh ref (never sent anywhere), so
     %% that its leading `receive' can never match and its `after 0' branch
     %% always runs.
     {entry_recv, [make_ref(), make_ref()]},
     {lit_case,   [1, 2, other, 0]}].

%% Call `Fun(Arg)' in every build and check that both builds return exactly
%% the expected result or exception, and that they agree with each other.
check_calls(Builds, Fun, Args) ->
    Expected = [expected(Fun, Arg) || Arg <- Args],
    Results = [{Set, [run(Mod, Bin, Fun, Arg) || Arg <- Args]}
               || {Set, Mod, Bin, _Code} <- Builds],
    lists:foreach(fun({Set, Values}) ->
                          ?assertEqual({Set, Expected}, {Set, Values})
                  end, Results),
    ?assertEqual(1, length(lists:usort([Values || {_Set,Values} <- Results]))),
    ok.

%% The expected result of `Fun(Arg)': `{ok,Value}' for a normal return,
%% `{Class,Reason}' for an exception.
expected(mk, X) -> {ok,{r,X,undefined,undefined}};
expected(safe, X) -> {ok,{r,X,1,undefined}};
expected(join, true) -> {ok,{r,true,1,undefined}};
expected(join, X) -> {ok,{r,X,2,undefined}};
expected(join_used_twice, true) ->
    {ok,{{r,true,undefined,undefined},{r,true,1,undefined}}};
expected(join_used_twice, X) ->
    {ok,{{r,X,undefined,undefined},{r,X,2,undefined}}};
expected(join_arg, {r,A,_B,C}) -> {ok,{r,A,2,C}};
expected(join_arg, Other) -> {error,{badrecord,Other}};
expected(join_extracted, {{r,A,_B,C},_}) -> {ok,{r,A,2,C}};
expected(join_extracted, _Other) -> {error,badarg};
expected(phi_call, true) -> {ok,{r,1,1,undefined}};
expected(phi_call, _X) -> {ok,{r,2,1,undefined}};
expected(nested, X) -> {ok,{r,X,1,1}};
expected(loop_alloc, 0) -> {ok,{r,0,undefined,undefined}};
expected(loop_alloc, _N) -> {ok,{r,1,1,undefined}};
expected(phi_lit, true) -> {ok,{r,1,1,undefined}};
expected(phi_lit, X) -> {ok,{r,X,1,undefined}};
expected(phi_arg, true) -> {ok,{r,true,1,undefined}};
expected(phi_arg, {r,A,_B,C}) -> {ok,{r,A,1,C}};
expected(phi_arg, Other) -> {error,{badrecord,Other}};
expected(passed, X) -> {ok,{r,X,1,undefined}};
expected(second_update, X) ->
    {ok,{{r,X,undefined,undefined},{r,X,1,2}}};
expected(spin, 0) -> {ok,{r,0,undefined,undefined}};
expected(spin, _N) -> {ok,{r,1,undefined,undefined}};
expected(looped, []) -> {ok,{r,0,undefined,undefined}};
expected(looped, L) -> {ok,{r,lists:last(L),undefined,undefined}};
expected(map_upd, X) -> {ok,#{a => X, b => 1}};
expected(list_upd, X) -> {ok,[0,X,1,2]};
expected(bin_upd, 0) -> {error,{badrecord,<<0>>}};
expected(bin_upd, _X) -> {error,badarg};
expected(recv_after, X) -> {ok,{r,X,2,undefined}};
expected(entry_recv, Ref) -> {ok,{r,Ref,2,2}};
expected(sent, X) -> {ok,{r,X,1,undefined}};
expected(captured, X) ->
    {ok,{{r,X,1,undefined},{r,X,undefined,undefined}}};
expected(used_twice, X) -> {ok,{{r,X,undefined,undefined},{r,X,1,undefined}}};
expected(arg_src, {r,_A,B,C}) -> {ok,{r,1,B,C}};
expected(arg_src, Other) -> {error,{badrecord,Other}};
expected(lit_inline, _) -> {ok,{r,1,2,undefined}};
expected(lit_var, _) -> {ok,{r,1,2,undefined}};
expected(lit_case, 1) -> {ok,{r,1,2,undefined}};
expected(lit_case, _) -> {ok,{r,2,2,undefined}}.

%% Run `Mod:Fun(Arg)' in the code that was just loaded. The result is
%% `{ok,Value}' for a normal return and `{Class,Reason}' for an exception;
%% the stacktrace is deliberately not part of the comparison.
run(Mod, Bin, Fun, Arg) ->
    _ = code:purge(Mod),
    {module, Mod} = code:load_binary(Mod, atom_to_list(Mod) ++ ".erl", Bin),
    try apply(Mod, Fun, [Arg]) of
        Value ->
            {ok, Value}
    catch
        Class:Reason ->
            {Class, Reason}
    end.

%%============================================================================
%% Helpers
%%============================================================================

tmp_dir(Config) ->
    Base = case proplists:get_value(priv_dir, Config) of
               undefined ->
                   case os:getenv("TMPDIR") of
                       false -> "/tmp";
                       "" -> "/tmp";
                       EnvDir -> EnvDir
                   end;
               PrivDir ->
                   PrivDir
           end,
    Sub = "beam_ssa_fbip_" ++ integer_to_list(erlang:unique_integer([positive])),
    Dir = filename:join(Base, Sub),
    ok = filelib:ensure_path(Dir),
    Dir.

write_probe(Dir, Mod, Source) ->
    File = filename:join(Dir, Mod ++ ".erl"),
    ok = file:write_file(File, Source),
    File.
