%% Tests for the opt-in "FBIP" (functional-but-in-place) pass
%% beam_ssa_fbip/1.
%%
%% The pass is only run when the compile option `fbip_opt' is given; the
%% gating is done by beam_ssa_destructive_update:opt/2, which invokes the
%% pass after the regular alias/destructive-update transforms. Without the
%% option the update_record hint is whatever the ordinary destructive-update
%% pass produced.
%%
%% The pass rewrites a *copying* `update_record' to the `inplace' hint when
%% the update source is a value that is provably
%%
%%   * freshly allocated (a tuple, a writable binary, a call to a local
%%     "fresh returning" function, or a value that is already an inplace
%%     update result),
%%   * uniquely owned (not a function argument, used exactly once), and
%%   * correctly positioned: either the definition is in the same block as
%%     the update, or the definition block D dominates the update block U
%%     and no cycle through U avoids D, so the update runs at most once per
%%     allocation of the source.
%%
%% The position rule strictly generalizes the narrower "same block or unique
%% predecessor block" rule it replaces; the `join_*' probe functions pin
%% both the newly accepted shape (a fresh source that is updated after an
%% intervening branch/join) and the shapes that must still not be rewritten
%% because they are not fresh or not uniquely owned.
%%
%% Everything else must keep its hint, i.e. the transform may never weaken a
%% `copy'/`reuse' that was required for safety. This suite checks both
%% directions:
%%
%%   * a provably safe update gets `inplace' with `fbip_opt' and stays
%%     `copy' without it. The fresh-source clauses are covered one by one:
%%     a local fresh-returning call (`safe/1'), an all-fresh `phi'
%%     (`phi_call/1'), the result of a function that is fresh-returning only
%%     after its own update has been rewritten, i.e. the module-wide fixpoint
%%     (`nested/1'), and a fresh allocation inside a loop that is updated
%%     once per allocation (`loop_alloc/2'),
%%   * unsafe sources (function argument, value sent with `!', value
%%     captured by a fun, value used twice or passed to a call, value
%%     threaded through a loop, value extracted from another term, a `phi'
%%     with a literal or an argument incoming value) keep exactly the same
%%     hint with and without the option, and are never rewritten to
%%     `inplace'; the whole function is asserted to be unchanged, not just
%%     the hint,
%%   * lists and maps never get an in-place update, and
%%   * the two builds behave identically: every probe function is loadable
%%     and returns exactly the same values and exceptions in both builds.
%%
%% The "no cycle through U avoids D" half of the position rule is a
%% defensive guard: a CFG back edge is only ever produced by `receive'
%% (whose loop blocks are generated by the compiler and never contain a
%% user `update_record'), so no Erlang source can turn it into a witness.
%% It is therefore not exercised by a probe here; see the `cycle' comment in
%% beam_ssa_fbip for the argument. The positive half of "at most once per
%% allocation" *is* exercised (`loop_alloc/2' allocates a fresh record on
%% every iteration and updates it once), as is the source-level shape that
%% makes a loop dangerous (`spin/2' threads the value through the loop,
%% which the single-use rule already rejects).
%%
%% The roots of the dominance half are the function's entry block plus every
%% block without predecessors (roots/3 in beam_ssa_fbip). The entry is what
%% keeps condition (1) non-vacuous if the entry block itself is on a cycle -
%% a body that starts with a `receive' leads the entry straight into the
%% peek/skip cycle - and adding it can only ever reject more rewrites. The
%% `entry_recv/1' probe pins that CFG shape and asserts that the stricter
%% root set does not reject an update that is genuinely dominated.
%%
%% The tests operate on a small probe module that is compiled under the
%% option sets in opt_sets/0 and disassembled with beam_disasm: see
%% `update_record' hint assertions below.
%%
%% An update_record instruction is disassembled as
%%
%%     {update_record,{atom,Hint},Size,Src,SrcFun,Dst,{list,Updates}}
%%
%% i.e. the hint is element(2, Instr) and is one of {atom,copy},
%% {atom,inplace} or {atom,reuse}. Functions whose record updates are
%% constant-folded away before the SSA passes contain no update_record
%% instruction at all; that case is exercised (and documented) by the
%% `literal_sources' probe functions.
%%
%% == Divergences from the documented contract ==
%%
%% Two clauses of the contract above cannot be pinned by a test:
%%
%%   1. The freshness rule lists an allocating `bs_create_bin' /
%%      `bs_init_writable' as a fresh source. `update_record' writes a tuple,
%%      and the type analysis proves that an update of a binary source can
%%      never succeed, so such an update is folded into an unconditional
%%      `{badrecord,_}' raise before this pass runs - no Erlang source can
%%      get a `bs_create_bin'/`bs_init_writable' source into an
%%      `update_record' and the clause is unreachable for this pass.
%%      `bin_upd/1' asserts the observable consequence instead: neither
%%      build contains an `update_record' for a binary source.
%%   2. The pass is documented as having the kill switch `no_ssa_opt_fbip',
%%      but that switch does NOT disable it. It is accepted without a
%%      warning, and it is inert: `ssa_opt_fbip' is not a pass of the
%%      `beam_ssa_opt' phase list - the pass is invoked by
%%      `beam_ssa_destructive_update:opt/2' through the `$fbip_opt'
%%      process-dictionary flag, and the name is only declared in
%%      `compile:options/0' for the `--help' text - so `passes_1/2' has no
%%      pass name to derive the negation from. Only `no_ssa_opt' disables the
%%      pass (by skipping the whole `beam_ssa_opt' phase). This suite
%%      therefore asserts the switch that works and does not assert the
%%      documented effect of `no_ssa_opt_fbip'.
%%
-module(beam_ssa_fbip_SUITE).

-include_lib("stdlib/include/assert.hrl").

-export([all/0,suite/0,groups/0,init_per_suite/1,end_per_suite/1,
         init_per_group/2,end_per_group/2]).
-export([safe_hint_rewritten/1,
         join_hint_rewritten/1,
         entry_hint_rewritten/1,
         fresh_source_shapes_rewritten/1,
         join_hints_unchanged/1,
