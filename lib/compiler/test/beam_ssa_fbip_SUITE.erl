%% `Mod' is the module name of the probe; the source is generated, so the
%% same probe can be compiled under several names and thus be used from
%% parallel test cases without them clobbering each other in the code
%% server.
probe_source(Mod) ->
    ["-module(", Mod, ").\n",
     "-export([mk/1,safe/1,sent/1,captured/1,used_twice/1,arg_src/1,\n",
     "         join/1,join_used_twice/1,join_arg/1,join_extracted/1,\n",
     "         recv_after/1,entry_recv/1,\n",
     "         phi_call/1,nested/1,loop_alloc/1,\n",
     "         phi_lit/1,phi_arg/1,passed/1,second_update/1,spin/1,looped/1,\n",
     "         map_upd/1,list_upd/1,bin_upd/1,\n",
     "         lit_inline/1,lit_var/1,lit_case/1]).\n",
     "\n",
     "%% The literal-source probes below update a known-at-compile-time\n",
     "%% record on purpose, which erl_lint warns about.\n",
     "-compile(nowarn_update_literal).\n",
     "\n",
     "%% An ordinary record (a tuple), so that the record access cannot\n",
     "%% interfere with the pass.\n",
     "-record(r, {a, b, c}).\n",
     "\n",
     "%% A local constructor that always returns a freshly allocated record;\n",
     "%% the pass treats it as a 'fresh returning' function.\n",
     "mk(X) -> #r{a=X}.\n",
     "\n",
     "%% A call that just uses its argument, so that a probe can make the\n",
     "%% source of an update observable without changing its value.\n",
     "consume(_) -> ok.\n",
     "\n",
     "%% SAFE: the source is the result of a local fresh call, it is used\n",
     "%% exactly once and it is not otherwise observable.\n",
     "safe(X) ->\n",
     "    R0 = mk(X),\n",
     "    R0#r{b=1}.\n",
     "\n",
     "%% SAFE: the fresh source is defined before an intervening branch/join\n",
     "%% and updated after it, so the update block's unique predecessor is the\n",
     "%% join block, not the definition block. The old position rule rejected\n",
     "%% this shape; the current one accepts it because the definition block\n",
     "%% still dominates the update block and no cycle through the update\n",
     "%% block avoids it.\n",
     "join(X) ->\n",
     "    R0 = mk(X),\n",
     "    Y = case X of true -> 1; _ -> 2 end,\n",
     "    R0#r{b=Y}.\n",
     "\n",
     "%% SAFE: the source is an all-fresh phi - both incoming values are the\n",
     "%% result of a call to the fresh-returning mk/1.\n",
     "phi_call(X) ->\n",
     "    R0 = case X of\n",
     "             true -> mk(1);\n",
     "             _ -> mk(2)\n",
     "         end,\n",
     "    R0#r{b=1}.\n",
     "\n",
     "%% SAFE: the source is the result of safe/1, which is a fresh-returning\n",
     "%% function only once its own update has been rewritten to inplace, so\n",
     "%% the pass needs a second module-wide iteration to accept this one.\n",
     "nested(X) ->\n",
     "    R0 = safe(X),\n",
     "    R0#r{c=1}.\n",
     "\n",
     "%% SAFE: a fresh record is allocated on every iteration of the loop and\n",
     "%% updated once per allocation, so the update can never run twice for the\n",
     "%% same allocation.\n",
     "loop_alloc(N) ->\n",
     "    loop_alloc(N, mk(0)).\n",
     "loop_alloc(N, R) when N =< 0 ->\n",
     "    R;\n",
     "loop_alloc(N, _R) ->\n",
     "    R0 = mk(N),\n",
     "    loop_alloc(N - 1, R0#r{b=N}).\n",
     "\n",
     "%% UNSAFE: same CFG shape as join/1, but the source is used twice, so it\n",
     "%% is not uniquely owned and the update must copy.\n",
     "join_used_twice(X) ->\n",
     "    R0 = mk(X),\n",
     "    Y = case X of true -> 1; _ -> 2 end,\n",
     "    {R0, R0#r{b=Y}}.\n",
     "\n",
     "%% UNSAFE: same CFG shape as join/1, but the source is a function\n",
     "%% argument: never freshly allocated.\n",
     "join_arg(R) ->\n",
     "    Y = case R of true -> 1; _ -> 2 end,\n",
     "    R#r{b=Y}.\n",
     "\n",
     "%% UNSAFE: same CFG shape as join/1, but the source is a sub-term of\n",
     "%% another term (extracted with element/1), which the caller may still\n",
     "%% reference: it is not freshly allocated.\n",
     "join_extracted(T) ->\n",
     "    Y = case T of true -> 1; _ -> 2 end,\n",
     "    R0 = element(1, T),\n",
     "    R0#r{b=Y}.\n",
     "\n",
     "%% SAFE: the source is defined and updated around a `receive' whose\n",
     "%% blocks contain a real CFG cycle (the compiler-generated peek/skip\n",
     "%% loop). The update block itself is off the cycle, so it is dominated by\n",
     "%% the definition block and no cycle through it avoids the definition\n",
     "%% block - the pass must still accept it. The pattern can never match\n",
     "%% (the ref is fresh), so `after 0' always runs and the function is\n",
     "%% deterministic and non-blocking.\n",
     "recv_after(X) ->\n",
     "    Ref = make_ref(),\n",
     "    V = receive {msg, Ref} -> 1 after 0 -> 2 end,\n",
     "    R0 = mk(X),\n",
     "    R0#r{b=V}.\n",
     "\n",
     "%% SAFE: the body *starts* with a `receive', so the compiler-generated\n",
     "%% peek/skip loop is entered directly from the function's entry block,\n",
     "%% which leads straight into a cycle of the CFG - the shape the pass's\n",
     "%% dominance roots (the entry block on top of the predecessor-less\n",
     "%% blocks) have to cope with. The source is defined after the receive and\n",
     "%% updated after an intervening branch/join, so the definition block\n",
     "%% dominates the update block and the update must still be rewritten to\n",
     "%% an in-place one.\n",
     "%%\n",
     "%% Like `recv_after/1', the pattern can never match a message in the\n",
     "%% caller's mailbox: `Ref' is a fresh ref that the caller (see cases/0)\n",
     "%% created and never sent. `after 0' therefore always runs, so the\n",
     "%% function is deterministic and does not block.\n",
     "entry_recv(Ref) ->\n",
     "    V = receive {msg, Ref} -> 1 after 0 -> 2 end,\n",
     "    R0 = mk(Ref),\n",
     "    Y = case Ref of true -> 1; _ -> 2 end,\n",
     "    R0#r{b=V, c=Y}.\n",
     "\n",
     "%% UNSAFE: the value is handed to another process before the update, so\n",
     "%% the update must copy.\n",
     "sent(X) ->\n",
     "    R0 = mk(X),\n",
     "    self() ! R0,\n",
     "    R0#r{b=1}.\n",
     "\n",
     "%% UNSAFE: the value is captured by a fun, so it stays reachable through\n",
     "%% the fun and the update must copy. The fun is applied so that the\n",
     "%% result of the function is comparable between builds.\n",
     "captured(X) ->\n",
     "    R0 = mk(X),\n",
     "    F = fun() -> R0 end,\n",
     "    {R0#r{b=1}, F()}.\n",
     "\n",
     "%% UNSAFE: the value is used twice.\n",
     "used_twice(X) ->\n",
     "    R0 = mk(X),\n",
     "    {R0, R0#r{b=1}}.\n",
     "\n",
     "%% UNSAFE: the source is a function argument, which is never fresh. The\n",
     "%% ordinary destructive-update pass reuses the argument's frame slot.\n",
     "arg_src(R) -> R#r{a=1}.\n",
     "\n",
     "%% UNSAFE: the phi has an incoming compile-time literal, and literals are\n",
     "%% never fresh - the phi is not all-fresh even though the other incoming\n",
     "%% value comes from the fresh-returning mk/1.\n",
     "phi_lit(X) ->\n",
     "    R0 = case X of\n",
     "             true -> #r{a=1};\n",
     "             _ -> mk(X)\n",
     "         end,\n",
     "    R0#r{b=1}.\n",
     "\n",
     "%% UNSAFE: the phi has an incoming function argument.\n",
     "phi_arg(X) ->\n",
     "    R0 = case X of\n",
     "             true -> mk(X);\n",
     "             _ -> X\n",
     "         end,\n",
     "    R0#r{b=1}.\n",
     "\n",
     "%% UNSAFE: the source is passed to a call, which is a second use.\n",
     "passed(X) ->\n",
     "    R0 = mk(X),\n",
     "    consume(R0),\n",
     "    R0#r{b=1}.\n",
     "\n",
     "%% UNSAFE: the allocation is updated twice and the original is returned\n",
     "%% as well. The two updates are merged into one `update_record' before\n",
     "%% the pass runs, and the returned original makes the source observable.\n",
     "second_update(X) ->\n",
     "    R0 = mk(X),\n",
     "    R1 = R0#r{b=1},\n",
     "    R2 = R1#r{c=2},\n",
     "    {R0, R2}.\n",
     "\n",
     "%% UNSAFE: the value is threaded through a recursive loop, so the value\n",
     "%% the update reads is that loop's argument. Threading is what a loop\n",
     "%% needs to reach a value defined outside it, and it is a second use.\n",
     "spin(N) ->\n",
     "    spin(N, mk(0)).\n",
     "spin(0, R) ->\n",
     "    R;\n",
     "spin(N, R) ->\n",
     "    spin(N - 1, R#r{a=N}).\n",
     "\n",
     "%% UNSAFE: the update runs inside a foldl fun, so its source is that\n",
     "%% fun's argument.\n",
     "looped(L) ->\n",
     "    R0 = mk(0),\n",
     "    lists:foldl(fun(E, Acc) -> Acc#r{a=E} end, R0, L).\n",
     "\n",
     "%% No in-place reuse for maps and lists: neither update is represented\n",
     "%% as an updateable instruction, so there is no update_record at all.\n",
     "map_upd(X) ->\n",
     "    M = #{a => X},\n",
     "    M#{b => 1}.\n",
     "\n",
     "list_upd(X) ->\n",
     "    L = [X, 1, 2],\n",
     "    [0 | L].\n",
     "\n",
     "%% No update_record either: the source is a binary, the record update on\n",
     "%% it can never succeed, and the type analysis replaces it with a\n",
     "%% {badrecord,_} raise.\n",
     "bin_upd(X) ->\n",
     "    B = <<X:8>>,\n",
     "    B#r{b=1}.\n",
     "\n",
     "%% Literal sources: the record value is known at compile time, so the\n",
     "%% update is constant-folded before the SSA passes run and no\n",
     "%% update_record instruction is generated at all.\n",
     "lit_inline(_) -> (#r{a=1})#r{b=2}.\n",
     "\n",
     "lit_var(_) ->\n",
     "    T = #r{a=1},\n",
     "    T#r{b=2}.\n",
     "\n",
     "lit_case(X) ->\n",
     "    T = case X of\n",
     "            1 -> #r{a=1};\n",
     "            _ -> #r{a=2}\n",
     "        end,\n",
     "    T#r{b=2}.\n"].

%% The source of a module the pass cannot rewrite at all: it has no record
%% update, so no `update_record' instruction is ever produced and the
%% eligibility gate is false. It deliberately contains no anonymous `fun'
%% either, because the compiler stamps every anonymous fun with a fresh
%% uniqueness number, so two compilations of the same source may differ in
%% it (yet in nothing else).
passive_source(Mod) ->
    ["-module(", Mod, ").\n",
     "-export([sum/1,add/2,build/1,update/2,map2/1]).\n",
     "\n",
     "-record(r, {a, b, c}).\n",
     "\n",
     "sum(L) -> lists:sum(L).\n",
     "\n",
     "add(A, B) -> A + B.\n",
     "\n",
     "%% Only a record *construction*, never an update.\n",
     "build(X) -> #r{a=X}.\n",
     "\n",
     "%% A map update: no update_record, and maps are never written in place.\n",
     "update(M, V) -> M#{k => V}.\n",
     "\n",
     "%% A list comprehension is compiled to a local helper, not to a fun\n",
     "%% object, so it does not carry a per-compilation uniqueness number.\n",
     "map2(L) -> [E*2 || E <- L].\n"].

%%============================================================================
%% Compiling, disassembling and running the probes
%%============================================================================

%% The option sets every probe is compiled with. `fbip' enables the pass,
%% `plain' is the default without it.
opt_sets() ->
    [{plain, [binary]},
     {fbip,  [binary,fbip_opt]}].

%% Write the probe named `Mod' into a fresh scratch directory and compile it
%% with every option set in opt_sets/0. Returns the module name and the list
%% of builds.
build_probe(Config, Mod) ->
    build_probe(Config, Mod, opt_sets(), fun probe_source/1).

build_probe(Config, Mod, OptSets) ->
    build_probe(Config, Mod, OptSets, fun probe_source/1).

build_probe(Config, Mod, OptSets, SourceFun) ->
    Dir = tmp_dir(Config),
    File = write_probe(Dir, Mod, SourceFun(Mod)),
    {Mod, [build(File, Set, Opts) || {Set,Opts} <- OptSets]}.

%% Compile to memory only, so that the builds cannot influence each other.
build(File, Set, Opts) ->
    case compile:file(File, [return_errors,return_warnings|Opts]) of
        {ok, Mod, Bin, []} ->
            {Set, Mod, Bin, disasm(Bin)};
        {ok, _Mod, _Bin, Warnings} ->
            ct:fail({unexpected_warnings, File, Warnings});
        {error, Errors, Warnings} ->
            ct:fail({compile_failed, File, Errors, Warnings})
    end.

%% The hint of the update_record instruction in `Fun/Arity' of one build.
%% Fails if the function defines more than one update_record (the probes are
%% built so that they never do) and returns `none' if there is none at all.
hint(Set, Builds, Fun, Arity) ->
    case lists:keyfind(Set, 1, Builds) of
        {Set, _Mod, _Bin, Code} ->
            case function_code(Code, Fun, Arity) of
                not_found ->
                    ct:fail({missing_function, Set, Fun, Arity});
                Is ->
                    case [element(2,I) || I <- Is, is_update_record(I)] of
                        [Hint] -> Hint;
                        [] -> none;
                        More -> ct:fail({multiple_update_records, Set, Fun, Arity, More})
                    end
            end;
        false ->
            ct:fail({missing_option_set, Set})
    end.

%% Assert that `Fun/Arity' has exactly `Expected' as hint in every build,
%% that the option does not change it (and never makes it `inplace'), and
%% that the whole function is byte-for-byte (modulo the compiler's fun
%% uniqueness numbers) the same in both builds - the pass must be a pure
%% hint change and may not move or disturb anything else.
unchanged(Builds, Fun, Arity, Expected) ->
    Hints = [{Set, hint(Set, Builds, Fun, Arity)} || {Set,_,_,_} <- Builds],
    ?assertEqual([{plain,Expected},{fbip,Expected}], Hints),
    ?assertNotEqual({atom,inplace}, Expected),
    ?assertEqual(1, length(lists:usort([normalize_is(function_code(Code, Fun, Arity))
                                        || {_,_,_,Code} <- Builds]))),
    ok.

is_update_record(I) ->
    is_tuple(I) andalso tuple_size(I) =:= 6 andalso element(1, I) =:= update_record.

function_code(Code, Name, Arity) ->
    case [Is || {function,N,A,_,Is} <- Code, N =:= Name, A =:= Arity] of
        [Is] -> Is;
        [] -> not_found
    end.

%% The code of one build, i.e. the list of `{function,Name,Arity,Label,Is}'
%% entries. beam_disasm:file/1 returns the #beam_file{} record; it is matched
%% as a plain tuple here so that this suite does not have to include the
%% compiler internal beam_disasm.hrl.
disasm(Bin) ->
    case beam_disasm:file(Bin) of
        {beam_file, _Mod, _Exports, _Attrs, _CompileInfo, Code} ->
            Code;
        {error, Mod, Reason} ->
            ct:fail({beam_disasm_failed, Mod, Reason})
    end.

%% Normalize a disassembled module for a build-to-build comparison. The
%% compiler stamps every anonymous fun with a fresh uniqueness number (the
%% 4th element of `make_fun3'/`make_fun2'), so two compilations of the same
%% source do not agree on it even when nothing else differs. It is not part
%% of any optimization and is therefore blanked out.
normalize(Code) ->
    [{Name,Arity,normalize_is(Is)} || {function,Name,Arity,_,Is} <- Code].

normalize_is(Is) ->
    [normalize_i(I) || I <- Is].

normalize_i({make_fun3,_,_,_,_,_}=I) ->
    setelement(4, I, 0);
normalize_i({make_fun2,_,_,_,_}=I) ->
    setelement(3, I, 0);
normalize_i(I) ->
    I.

