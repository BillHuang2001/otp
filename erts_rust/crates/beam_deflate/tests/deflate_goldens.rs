//! Embedded **oracle images** for the compressor — the bytes zlib 1.3.2 produces, pinned so
//! that byte identity is checked on every `cargo test` without an Erlang installation.
//!
//! # Provenance of every literal in this file
//!
//! All values below were produced by the **oracle**: the system `erl` (OTP 29.1.1 /
//! erts-17.1, whose `zlib` module is this repository's own zlib 1.3.2 through
//! `erts/emulator/nifs/common/zlib_nif.c`) running
//!
//! ```text
//! Z = zlib:open(),
//! ok = zlib:deflateInit(Z, Level, deflated, WindowBits, 8, default),
//! O = iolist_to_binary(zlib:deflate(Z, Data, finish))
//! ```
//!
//! — i.e. `deflateInit2` with `memLevel` 8 and `Z_DEFAULT_STRATEGY`, once per (input, level,
//! framing). `windowBits` is `15` for the zlib framings, `-15` for the raw ones and
//! `16 + 15` for the gzip ones (`tests/zsupport/mod.rs`'s `Case::{zlib,raw,gzip}`).
//!
//! The large-input entries are **fingerprints**, not streams: `(stream.len(),
//! crc32(0, stream))` for the 70 000-byte [`zsupport::large_input`] shape, which pins the
//! whole byte string without embedding tens of KiB of literals into this file. (The
//! byte-for-byte check of those same cases lives in `tests/deflate_oracle.rs`, which needs
//! `erl`.)
//!
//! # Regenerating
//!
//! The tables are static text; nothing here calls `erl` at run time. To regenerate them
//! (only when the port or the oracle genuinely changes — a golden is a *contract*, so a
//! mismatch means the port is wrong, not that the number is stale):
//!
//! ```text
//! erts_rust/scripts/cargo.sh test --manifest-path erts_rust/Cargo.toml \
//!     -p beam_deflate --test deflate_goldens -- --ignored --nocapture
//! ```
//!
//! That prints the three tables plus the fingerprint table between `=== NAME ===` markers;
//! paste each block over the corresponding `const` below. It needs `erl` on `PATH` (or
//! `$ERTS_ORACLE`) and prints `SKIP regenerate_goldens: erl not found` without it.
//!
//! The three level-6 zlib goldens for `empty`/`abc`/`zeros16` are additionally pinned
//! against the values the inflate half of this crate has carried since the beginning
//! (`tests/inflate_goldens.rs`) by
//! [`the_level_6_zlib_goldens_are_the_preexisting_ones`], so they cannot drift silently.

mod zsupport;

use beam_deflate::{crc32, Deflate, DeflateConfig};
use zsupport::{corpus_small, hex, unhex};

/// One framing of a `deflateInit2` stream.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Framing {
    /// `windowBits` 15 — RFC 1950 (`zlib:compress/1`).
    Zlib,
    /// `windowBits` -15 — raw RFC 1951 (`zlib:zip/1`).
    Raw,
    /// `windowBits` 16 + 15 — RFC 1952 (`zlib:gzip/1`).
    Gzip,
}

impl Framing {
    /// The `DeflateConfig` matching this framing at `level` (`memLevel` 8, default
    /// strategy — the tuple every golden was captured with).
    fn config(self, level: i8) -> DeflateConfig {
        match self {
            Framing::Zlib => DeflateConfig::zlib(level),
            Framing::Raw => DeflateConfig::raw(level),
            Framing::Gzip => DeflateConfig::gzip(level),
        }
    }

    fn name(self) -> &'static str {
        match self {
            Framing::Zlib => "zlib",
            Framing::Raw => "raw",
            Framing::Gzip => "gzip",
        }
    }
}

/// Check one golden table: every entry must reproduce its oracle image exactly.
///
/// `expected_len` is asserted too, so an accidentally truncated (or emptied) table fails
/// loudly instead of vacuously passing.
fn check_goldens(framing: Framing, goldens: &[(&str, i8, &str)], expected_len: usize) {
    assert_eq!(
        goldens.len(),
        expected_len,
        "the {} golden table lost entries",
        framing.name()
    );
    let inputs = corpus_small();
    for (name, level, want) in goldens {
        let (_, data) = inputs
            .iter()
            .find(|(n, _)| n == name)
            .unwrap_or_else(|| panic!("golden input {name:?} is not in corpus_small()"));
        let got = Deflate::compress_with(framing.config(*level), data)
            .unwrap_or_else(|e| panic!("{} level {level} input {name}: {e:?}", framing.name()));
        assert_eq!(
            hex(&got),
            *want,
            "{} level {level} input {name} ({} bytes in): {} bytes out, oracle image is {}",
            framing.name(),
            data.len(),
            got.len(),
            want.len() / 2
        );
    }
    println!(
        "{} goldens: {} oracle images reproduced byte for byte",
        framing.name(),
        goldens.len()
    );
}

