//! The **end-to-end `erlang:process_info(Pid, binary)` case**.
//!
//! The value-shape cases in [`super::tests`] feed the roster from a hand-registered
//! [`RefcBinary`](beam_alloc::RefcBinary) and the oracle cases there probe the *oracle's*
//! shape. Neither walks the whole path this test does: a real `.beam`, compiled at test time
//! with the system `erlc`, spawned through the real scheduler, **parked while really holding
//! an off-heap refc binary its own run time built**, and its roster compared against the live
//! system `erl` running the **same** fixture.
//!
//! The workload is `offheap:build_and_park/1`: `B = <<0:N/unit:8>>` followed by a
//! `receive stop -> byte_size(B) end`. Two properties make it the right probe:
//!
//! * `N` is a **runtime** parameter (256 here). A constant `<<0:256/unit:8>>` would be folded
//!   into a literal the code chunk carries, so no off-heap payload would ever be allocated at
//!   run time — the engine's bitstring construction is what materializes the refc binary.
//! * 256 bytes is above [`ERL_ONHEAP_BINARY_LIMIT`] (64), so the construction really crosses
//!   into the off-heap family, and `B` stays live across the `receive` (its body reads
//!   `byte_size(B)`), so the payload is reachable from the parked process's root set.
//!
//! **The comparisons are structural.** `Ptr` is a payload address and `Refc` an
//! implementation-specific count, so nothing is compared by `Ptr`/`Refc` value, nor by the
//! exact entry count (an implementation may hold extra off-heap intermediates): the test
//! asserts the roster is non-empty, that every entry is a 3-tuple of integers (by this
//! runtime's own `erlang:is_integer/1` — a pointer exceeds the 60-bit small range and
//! materializes as an exact bignum), and that one entry reports the `Size` the fixture built.
//!
//! Oracle ground truth (OTP 29.1.1 / erts-17.1): the probe below prints `true|true|true`, and
//! the roster for this fixture is `[{Ptr,256,1}]`. The toolchain — `erlc` to build the fixture
//! and `erl` to run the oracle half — is discovered by the filesystem/`PATH` only; when either
//! is absent (or the probe does not finish) the corresponding half skips **loudly**, never
//! silently passing.
//!
//! [`ERL_ONHEAP_BINARY_LIMIT`]: beam_term::refc::ERL_ONHEAP_BINARY_LIMIT

use std::io::Read;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

use beam_engine::terms;
use beam_process::ProcessState;
use beam_term::{make_small, signed_value, Eterm};

use crate::native::test_support::{atom, call, runtime};

/// The fixture source (`erlc` compiles it into the scratch directory at test time).
///
/// `N` must stay a runtime parameter — see the module docs.
const OFFHEAP_ERL: &str = "\
%% Generated by `beam_rt/src/native/memory/binary_e2e.rs` (never committed).
-module(offheap).
-export([build_and_park/1]).
build_and_park(N) ->
    B = <<0:N/unit:8>>,
    receive stop -> byte_size(B) end.
";

/// The oracle half's probe: spawn the fixture, let it park, then report the three
/// structural figures `Has` (a non-empty roster), `Well` (every entry a 3-tuple of
/// non-negative integers) and `Has256` (one entry whose `Size` is the built 256 bytes).
///
/// `-pa <scratch dir>` is load-bearing: `spawn/3`'s `(Module, Function, Args)` form resolves
/// `offheap.beam` through the code path.
const PROBE: &str = concat!(
    "P = spawn(offheap, build_and_park, [256]), timer:sleep(50), ",
    "{_, L} = process_info(P, binary), ",
    "Has = length(L) > 0, ",
    "Well = lists:all(fun(E) -> is_tuple(E) andalso tuple_size(E) =:= 3 andalso ",
    "lists:all(fun(X) -> is_integer(X) andalso X >= 0 end, tuple_to_list(E)) end, L), ",
    "Has256 = lists:any(fun(E) -> element(2, E) =:= 256 end, L), ",
    "io:format(\"~p|~p|~p~n\", [Has, Well, Has256]), halt().",
);

/// What the probe above prints on OTP 29.1.1 / erts-17.1 (measured).
const ORACLE_LINE: &str = "true|true|true";

/// A compiled `offheap.beam` in its own scratch directory.
///
/// The directory is `erlc` output, not source, so it is removed on the way out — a failed
/// removal is a printed note, never a panic (and `Drop` runs even when an assertion unwinds).
struct Fixture {
    /// The scratch directory holding `offheap.erl`/`offheap.beam`.
    dir: PathBuf,
}

impl Fixture {
    /// The compiled `offheap.beam`.
    fn beam(&self) -> PathBuf {
        self.dir.join("offheap.beam")
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        match std::fs::remove_dir_all(&self.dir) {
            Ok(()) => {}
            // The directory is ours and disposable; report rather than hide the failure.
            Err(error) => println!("note: could not remove {}: {error}", self.dir.display()),
        }
    }
}

/// Compiles [`OFFHEAP_ERL`], or `None` when the system `erlc` is unavailable (the caller then
/// skips **loudly**). A missing compiler, a non-zero exit and a missing output are all skips —
/// never a silent pass and never a panic.
fn build_fixture() -> Option<Fixture> {
    let dir = std::env::temp_dir().join(format!("beam_rt_offheap_binary_{}", std::process::id()));
    if let Err(error) = std::fs::create_dir_all(&dir) {
        eprintln!(
            "SKIPPING the `binary` end-to-end test: cannot create {}: {error}",
            dir.display()
        );
        return None;
    }
    let source = dir.join("offheap.erl");
    if let Err(error) = std::fs::write(&source, OFFHEAP_ERL) {
        eprintln!(
            "SKIPPING the `binary` end-to-end test: cannot write {}: {error}",
            source.display()
        );
        return None;
    }
    let output = match Command::new("erlc").arg("-o").arg(&dir).arg(&source).output() {
        Ok(output) => output,
        Err(error) => {
            eprintln!("SKIPPING the `binary` end-to-end test: cannot run `erlc`: {error}");
            return None;
        }
    };
    if !output.status.success() {
        eprintln!(
            "SKIPPING the `binary` end-to-end test: `erlc` exited with {}: {}",
            output.status,
            String::from_utf8_lossy(&output.stderr)
        );
        return None;
    }
    let fixture = Fixture { dir };
    if !fixture.beam().is_file() {
        eprintln!(
            "SKIPPING the `binary` end-to-end test: `erlc` produced no {}",
            fixture.beam().display()
        );
        return None;
    }
    Some(fixture)
}

/// Runs `erl -noshell -pa CODE_DIR -eval EXPR` with a **bounded** poll/kill and returns its
/// trimmed stdout, or `None` when the system `erl` is unavailable or the probe did not finish
/// (the caller then skips **loudly**).
///
/// The near-twin of `tests.rs`'s `oracle_eval` for a probe that needs a
/// **code path**: [`PROBE`]'s `spawn/3` resolves `offheap.beam` through `-pa`, which the
/// plain helper cannot express. Like its twin it has a bound so a probe that hangs (or an
/// `erl` that never starts) can never wedge the suite; `PROBE` itself ends in `halt()`.
fn oracle_eval_pa(code_dir: &Path, expression: &str) -> Option<String> {
    const ORACLE_TIMEOUT: Duration = Duration::from_secs(30);
    let mut child = Command::new("erl")
        .args(["-noshell", "-pa"])
        .arg(code_dir)
        .args(["-eval", expression])
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()
        .ok()?;
    let deadline = Instant::now() + ORACLE_TIMEOUT;
    loop {
        match child.try_wait().ok()? {
            Some(status) => {
                if !status.success() {
                    return None;
                }
                break;
            }
            None if Instant::now() >= deadline => {
                let _ = child.kill();
                let _ = child.wait();
                eprintln!(
                    "SKIPPING the `binary` end-to-end oracle half: `erl` did not exit within \
                     {ORACLE_TIMEOUT:?}"
                );
                return None;
            }
            None => std::thread::sleep(Duration::from_millis(10)),
        }
    }
    let mut text = String::new();
    child.stdout.take()?.read_to_string(&mut text).ok()?;
    Some(text.trim().to_string())
}

/// Looks the item up through the floor's own dispatch (the `erlang:process_info/2` a program
/// would call).
fn info(runtime: &mut crate::Runtime, pid: Eterm, name: &str) -> beam_common::Result<Eterm> {
    let item = atom(runtime, name);
    call(runtime, "erlang", "process_info", &[pid, item])
}

/// The `(key, value)` of a `{Item, Value}` reply.
fn pair(reply: Eterm) -> (Eterm, Eterm) {
    assert_eq!(terms::tuple_arity(reply).expect("a tuple"), 2);
    (
        terms::tuple_element(reply, 0).expect("key"),
        terms::tuple_element(reply, 1).expect("value"),
    )
}

/// Is `term` an integer *by this runtime's own `erlang:is_integer/1`*?
///
/// The check goes through the BIF rather than `beam_term`'s small-int accessors on purpose:
/// a payload pointer exceeds the 60-bit small range, so it materializes as an exact
/// **bignum**, which must still answer `true` here (an `is_small`/`signed_value` predicate
/// would wrongly reject it).
fn is_integer(runtime: &mut crate::Runtime, term: Eterm) -> bool {
    let answer = call(runtime, "erlang", "is_integer", &[term]).expect("erlang:is_integer/1");
    runtime.atom_name_of(answer) == Some("true")
}

/// A process that really builds an off-heap refc binary at run time reports the oracle's
/// `[{Ptr, Size, Refc}, …]` roster for it — the end-to-end companion to `tests.rs`'s
/// `the_binary_item_lists_the_registered_off_heap_payloads`.
///
/// The process is a real `.beam` (`offheap:build_and_park/1`, compiled at test time) spawned
/// through the real scheduler and parked in its `receive` while `B = <<0:256/unit:8>>` stays
/// live, so the roster comes from a payload the **engine** allocated during execution rather
/// than one a test handed the process. The same fixture runs under the live system `erl`, so
/// both runtimes are asked the same question about the same program.
///
/// Structural comparisons only: arity (`3`), each field an integer, and one entry reporting
/// `Size =:= 256`. `Ptr`/`Refc` are this runtime's own address and count, and the entry count
/// is not fixed (extra off-heap intermediates are legitimate).
///
/// Skips **loudly** when `erlc` (the fixture) or `erl` (the oracle half) is unavailable.
#[test]
fn the_binary_item_matches_the_live_oracle_for_an_off_heap_payload() {
    let Some(fixture) = build_fixture() else {
        return;
    };

    // -- the oracle half: the same fixture, under the live system `erl` -------------------
    match oracle_eval_pa(&fixture.dir, PROBE) {
        Some(line) => assert_eq!(
            line, ORACLE_LINE,
            "the oracle must report a non-empty, well-formed roster carrying the built 256 bytes"
        ),
        None => eprintln!(
            "SKIPPING the `binary` end-to-end oracle half: the system `erl` is unavailable \
             (or the probe did not finish)"
        ),
    }

    // -- the runtime half: the same fixture, under this runtime ---------------------------
    let mut runtime = runtime();
    runtime
        .load_module(fixture.beam())
        .expect("the fixture compiles to a loadable module");
    let pid = runtime
        .spawn_process("offheap", "build_and_park", vec![make_small(256)])
        .expect("spawn offheap:build_and_park/1");

    // One slice carries the child into its `receive`: the bitstring construction does not
    // block, so the very first slice ends with the process parked on an empty mailbox.
    assert_eq!(
        runtime.run_one_slice().expect("one slice"),
        1,
        "the child ran in exactly one slice"
    );
    assert_eq!(
        runtime
            .processes()
            .get(pid)
            .expect("the parked child stays in the table")
            .state(),
        ProcessState::Waiting,
        "the child parked in its `receive`, holding the binary it built"
    );

    let reply = info(&mut runtime, pid.to_eterm(), "binary").expect("process_info/2 binary");
    let (key, roster) = pair(reply);
    assert_eq!(runtime.atom_name_of(key), Some("binary"));

    let entries = terms::list_elements(roster).expect("the roster is a list");
    assert!(
        !entries.is_empty(),
        "a process holding an off-heap refc binary must not report `[]`"
    );

    let mut saw_256 = false;
    for entry in &entries {
        assert_eq!(
            terms::tuple_arity(*entry).expect("an entry"),
            3,
            "every roster entry is a {{Ptr, Size, Refc}} 3-tuple"
        );
        for index in 0..3 {
            let field = terms::tuple_element(*entry, index).expect("an entry field");
            assert!(
                is_integer(&mut runtime, field),
                "roster field {index} must be an integer"
            );
        }
        let size = signed_value(terms::tuple_element(*entry, 1).expect("the size"));
        saw_256 |= size == 256;
    }
    assert!(
        saw_256,
        "the roster carries the 256-byte payload the fixture built"
    );
}
