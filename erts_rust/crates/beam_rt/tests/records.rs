//! The **`records:get_definition/2` end-to-end host test** (contract A.7).
//!
//! `records:get_definition/2` answers from the *code server's* native-record table: the
//! `Recs` chunk a `.beam` carries, populated when the declaring module is **loaded**
//! (`erts_record_put`, `erl_record.c:173-178`). That lookup is the seam
//! [`beam_bifs::RecordSource`], which `beam_rt` installs over its
//! [`CodeServer`](beam_rt::CodeServer) in
//! [`RuntimeContext::call_registered`](beam_rt::RuntimeContext); without it the BIF answers
//! the typing-consistent but wrong `badarg`.
//!
//! This test compiles a module declaring two native records with the system `erlc`, loads
//! it through the runtime's code server and asserts the oracle's exact answers:
//!
//! * `records:get_definition(recdefs, rec)` ⇒ `{#{is_exported => false},[a,{b,5},c]}`
//!   (a field without a default contributes its bare name atom, one with a default the
//!   `{Name, Default}` pair — declaration order, never sorted);
//! * `records:get_definition(recdefs, exp)` ⇒ `{#{is_exported => true},[{x,1},y]}`
//!   (`-export_record([exp])`);
//! * an unknown record of a loaded module, and a record of a module that is not loaded,
//!   are both the oracle's plain `error:badarg`.
//!
//! The fixture is compiled at test time with the system `erlc` into a scratch directory, so
//! nothing path-dependent is committed and the source of truth stays the `.erl` in this
//! file. When the compiler is unavailable the test **skips loudly** — it never silently
//! passes.
//!
//! Oracle ground truth (OTP 29 / `erts-17.1`, the differential oracle):
//! `erlc -o … recdefs.erl` then
//! `erl -noshell -pa … -eval 'io:format("~p~n",[recdefs:fields()]),halt(0).'` prints
//! `[a,{b,5},c]`.
use std::path::PathBuf;
use std::process::Command;

use beam_common::BeamError;
use beam_rt::{Runtime, RuntimeConfig};

/// The fixture source: two native records, one exported, plus the lookup wrappers.
///
/// Every wrapper takes the record definition back through the `records:get_definition/2`
/// **BIF** — the module deliberately does not build a record value, because a compile-time
/// `#rec{a = 1}` creation lowers to `put_record`'s create form, which needs the same
/// code-server table through a *different* (unimplemented) path.
const FIXTURE_ERL: &str = r#"%% Generated by `beam_rt/tests/records.rs` (never committed).
-module(recdefs).
-export([fields/0, exported/0, unknown_record/0, unknown_module/0]).

-record #rec{a, b = 5, c}.
-record #exp{x = 1, y}.
-export_record([exp]).

%% The field list of a record this module declares (no default, a default, no default).
fields() ->
    {_, Fs} = records:get_definition(recdefs, rec),
    Fs.

%% The whole definition of the exported record.
exported() ->
    records:get_definition(recdefs, exp).

%% A record name this module does not declare.
unknown_record() ->
    records:get_definition(recdefs, nope).

%% A module this runtime has never loaded.
unknown_module() ->
    records:get_definition(no_such_module, rec).
"#;

/// A compiled fixture in its own scratch directory.
struct Fixture {
    /// The scratch directory holding `recdefs.erl`/`recdefs.beam`.
    dir: PathBuf,
    /// The compiled `recdefs.beam`.
    beam: PathBuf,
}

impl Fixture {
    /// Removes the scratch directory (`erlc` output is not source).
    fn cleanup(self) {
        match std::fs::remove_dir_all(&self.dir) {
            Ok(()) => {}
            // The directory is ours and disposable; a failure is reported, not hidden.
            Err(error) => println!("note: could not remove {}: {error}", self.dir.display()),
        }
    }
}

/// Compiles the fixture, or `None` when the system toolchain is unavailable (the caller
/// then returns early — **loudly**).
fn build_fixture(label: &str) -> Option<Fixture> {
    let dir = std::env::temp_dir().join(format!("beam_rt_records_{label}_{}", std::process::id()));
    if let Err(error) = std::fs::create_dir_all(&dir) {
        println!("SKIP records: cannot create {}: {error}", dir.display());
        return None;
    }
    let source = dir.join("recdefs.erl");
    if let Err(error) = std::fs::write(&source, FIXTURE_ERL) {
        println!("SKIP records: cannot write {}: {error}", source.display());
        return None;
    }
    let output = match Command::new("erlc").arg("-o").arg(&dir).arg(&source).output() {
        Ok(output) => output,
        Err(error) => {
            println!("SKIP records: cannot run `erlc`: {error}");
            return None;
        }
    };
    if !output.status.success() {
        println!(
            "SKIP records: `erlc` exited with {}: {}",
            output.status,
            String::from_utf8_lossy(&output.stderr)
        );
        return None;
    }
    let beam = dir.join("recdefs.beam");
    if !beam.is_file() {
        println!("SKIP records: `erlc` produced no {}", beam.display());
        return None;
    }
    Some(Fixture { dir, beam })
}

/// A runtime over the default configuration.
fn runtime() -> Runtime {
    Runtime::new(RuntimeConfig::default()).expect("the default runtime")
}

/// The field list of a declared record resolves from the loaded module's `Recs` chunk.
///
/// Oracle: `[a,{b,5},c]` (`records:get_definition(recdefs, rec)`).
#[test]
fn a_declared_record_resolves_from_the_loaded_module() {
    let Some(fixture) = build_fixture("declared") else {
        return;
    };
    let mut runtime = runtime();
    let fields = runtime
        .run_function(&fixture.beam, "fields", 0, &[])
        .expect("recdefs:fields/0");
    // The module is loaded under its own name (the `records:get_definition/2` argument),
    // so the lookup really went through the code server's module map.
    assert!(runtime.module("recdefs").is_some(), "recdefs must be loaded");
    assert_eq!(
        runtime.format_term_w(fields, None).expect("printable"),
        "[a,{b,5},c]\n"
    );

    fixture.cleanup();
}

/// The exported flag and the `{Name, Default}` pairs come back in declaration order.
///
/// Oracle: `{#{is_exported => true},[{x,1},y]}` (`-export_record([exp])`).
#[test]
fn an_exported_record_reports_is_exported_true() {
    let Some(fixture) = build_fixture("exported") else {
        return;
    };
    let mut runtime = runtime();
    let definition = runtime
        .run_function(&fixture.beam, "exported", 0, &[])
        .expect("recdefs:exported/0");
    assert_eq!(
        runtime.format_term_w(definition, None).expect("printable"),
        "{#{is_exported => true},[{x,1},y]}\n"
    );

    fixture.cleanup();
}

/// A record a loaded module does not declare is the oracle's plain `error:badarg`.
#[test]
fn an_unknown_record_is_badarg() {
    let Some(fixture) = build_fixture("unknown") else {
        return;
    };
    let mut runtime = runtime();
    let error = runtime
        .run_function(&fixture.beam, "unknown_record", 0, &[])
        .expect_err("no such record");
    assert!(matches!(error, BeamError::BadArg), "{error}");
    assert_eq!(error.as_atom(), Some("badarg"), "{error}");

    fixture.cleanup();
}

/// A module that is not loaded defines nothing, so the lookup is `badarg` too.
#[test]
fn an_unknown_module_is_badarg() {
    let Some(fixture) = build_fixture("module") else {
        return;
    };
    let mut runtime = runtime();
    let error = runtime
        .run_function(&fixture.beam, "unknown_module", 0, &[])
        .expect_err("no such module");
    assert!(matches!(error, BeamError::BadArg), "{error}");
    assert_eq!(error.as_atom(), Some("badarg"), "{error}");

    fixture.cleanup();
}
