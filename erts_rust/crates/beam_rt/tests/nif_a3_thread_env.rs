//! **A.3 end-to-end, part 1 of 3: the process-independent NIF environment.**
//!
//! Loads the real C NIF `../beam_bifs/tests/fixtures/a3_thread_env.c` (compiled in place with
//! the host `cc` against the host `erl_nif.h`) through `erlang:load_nif/2` from interpreted
//! Erlang, drives every probe from a `.beam`, and cross-checks the whole transcript against
//! the live system `erl` running **the same** `.so` and **the same** `.beam`.
//!
//! The question the fixture answers: in real ERTS an `ErlNifEnv` handed out by
//! `enif_alloc_env(void)` is a standalone *message* env (its phony proc has
//! `common.id == ERTS_INVALID_PID`, `erl_nif.c:636-680`), so the idiom
//!
//! ```text
//! env = enif_alloc_env(); … enif_send(NULL, &pid, env, term); enif_free_env(env);
//! ```
//!
//! works verbatim from a thread the NIF itself created — with the atoms it builds landing in
//! the ONE global atom table. This suite pins that end to end on this runtime.
//!
//! # What each probe measures, and what is asserted
//!
//! | probe | the observation |
//! |---|---|
//! | `probe_thread_send/0` | `{{0,1,0},0}`: the message env is non-NULL, `enif_send(NULL, …)` answers `1`, `enif_thread_type()` on a NIF-created thread is `0` (`ERL_NIF_THR_UNDEFINED`), and the thread was created |
//! | the message | the receiver's mailbox holds **exactly** `{from_thread,42,<<"abc">>}` |
//! | `probe_worker_atoms/0` | `{0,1,1,1,0}`: the atom interned on that thread reads back by length *and* text |
//! | the message | `{worker_atom_check, worker_atom}`, and the receiving process matches the atom **against its own literal** (`=:=`, so this is atom-table identity, not a printed name) |
//! | `probe_main_env/0` | `{0,1}` on the call path (the control), message `{from_call,42}` |
//! | `probe_null_env/0` | `{0,1}`: the same send with a `NULL` `env` but from the call path |
//! | `probe_thread_send_to/1` | `{{0,1,0},0}` to a **parked** receiver that was polled to `{status,waiting}` first, and the message `{parked_got,{from_thread_to_target,42}}` really arrives |
//!
//! # The one documented divergence
//!
//! `enif_thread_type()` of the **calling** thread: the oracle answers `1`
//! (`ERL_NIF_THR_NORMAL_SCHEDULER`) because a NIF runs on a scheduler thread; this runtime
//! runs it on its own driver thread, which is not a registered scheduler thread, so the
//! answer is `0` (`ERL_NIF_THR_UNDEFINED` — `beam_abi`'s `enif_thread_type` folds
//! `ERL_NIF_THR_OTHER` into `UNDEFINED`, matching a real ERTS thread that is not one of its
//! own). It is pinned as a divergence, not hidden: `null_env_caller_thread`. The thread type
//! of a thread the **NIF itself created** is `0` on both runtimes, so that slot agrees.
//!
//! # The send that wakes a parked receiver
//!
//! `probe_thread_send_to/1` is only meaningful once the receiver is really parked, so the
//! driver mirrors the fixture's own discipline: it polls `process_info(Pid, status)` until
//! `{status,waiting}` **before** the call. The delivered message then arrives at this
//! runtime's next pump (a NIF-thread `enif_send` queues a complete ETF image and is drained
//! right after the NIF call — `src/nif/thread_env.rs`), which the driver's `receive` absorbs;
//! the ordering is explicit, never a `sleep`.
#[path = "support/nif_a3.rs"]
#[allow(dead_code)]
mod nif_a3;
mod support;

use std::path::{Path, PathBuf};

use nif_a3::Expect;

/// The fixture under test — `beam_bifs`'s own C source, compiled where it lives.
fn fixture_source() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../beam_bifs/tests/fixtures/a3_thread_env.c")
}

/// The NIF module: its name **is** the C's `ERL_NIF_INIT` name, and it declares a stub for
/// every row of the C `ErlNifFunc` table (all five probes) so `load_nif/2`'s table check
/// passes. `init/1` is the explicit load trigger (`-on_load` is not run by this runtime).
const NIF_ERL: &str = r#"%% Generated by `beam_rt/tests/nif_a3_thread_env.rs` (never committed).
-module(a3_thread_env).
-export([init/1, probe_thread_send/0, probe_main_env/0, probe_worker_atoms/0,
         probe_null_env/0, probe_thread_send_to/1]).

init(Path) -> erlang:load_nif(Path, 0).

probe_thread_send() -> erlang:nif_error(nif_not_loaded).
probe_main_env() -> erlang:nif_error(nif_not_loaded).
probe_worker_atoms() -> erlang:nif_error(nif_not_loaded).
probe_null_env() -> erlang:nif_error(nif_not_loaded).
probe_thread_send_to(_Pid) -> erlang:nif_error(nif_not_loaded).
"#;

/// The driver: every call to `a3_thread_env:*` is an **external** call, so it reaches the
/// runtime's NIF dispatch instead of the in-machine stub.
///
/// Each observation is printed as `key=value`; `note_…` lines are recorded but never
/// compared. The mailbox assertions are term comparisons (`=:=`) inside the driver, so they
/// are real identity checks rather than a rendering that happens to look right.
const DRIVER_ERL: &str = r#"%% Generated by `beam_rt/tests/nif_a3_thread_env.rs` (never committed).
-module(a3_thread_env_driver).
-export([go/1]).

go(Path) ->
    ok = a3_thread_env:init(Path),
    R1 = a3_thread_env:probe_thread_send(),
    M1 = recv(),
    p("thread_send", R1),
    p("thread_send_msg_exact", M1 =:= {from_thread, 42, <<"abc">>}),
    R2 = a3_thread_env:probe_worker_atoms(),
    M2 = recv(),
    p("worker_atoms", R2),
    %% `worker_atom` here is THIS module's atom literal: a match proves the atom the worker
    %% interned on its own message env is the same atom, not merely the same printed name.
    p("worker_atom_identity",
      case M2 of
          {worker_atom_check, worker_atom} -> identical;
          _ -> {different, M2}
      end),
    R3 = a3_thread_env:probe_main_env(),
    M3 = recv(),
    p("main_env", R3),
    p("main_env_msg_exact", M3 =:= {from_call, 42}),
    R4 = a3_thread_env:probe_null_env(),
    M4 = recv(),
    p("null_env", {element(1, R4), element(2, R4)}),
    p("null_env_caller_thread", thr(element(3, R4))),
    p("null_env_msg_exact", M4 =:= {from_call_null, 42}),
    %% A receiver parked in `receive` BEFORE the NIF-created thread sends to it.
    Parent = self(),
    Pid = spawn(fun() -> receive Msg -> Parent ! {parked_got, Msg} end end),
    p("parked_status", await_waiting(Pid, 4000)),
    R5 = a3_thread_env:probe_thread_send_to(Pid),
    M5 = recv(),
    p("thread_send_to", {R5, is_pid(Pid)}),
    p("parked_msg_exact", M5 =:= {parked_got, {from_thread_to_target, 42}}),
    ok.

recv() -> receive Msg -> Msg after 5000 -> timeout end.

%% Poll the parked receiver's status instead of sleeping: the precondition is observed.
await_waiting(_Pid, 0) -> {status, unknown};
await_waiting(Pid, N) ->
    case process_info(Pid, status) of
        {status, waiting} -> {status, waiting};
        _ -> receive after 1 -> ok end, await_waiting(Pid, N - 1)
    end.

thr(0) -> undefined; thr(1) -> normal; thr(2) -> dirty_cpu; thr(3) -> dirty_io;
thr(X) -> {unknown, X}.

p(Name, Value) -> io:format("~s=~w~n", [Name, Value]).
"#;

/// The measured transcript. `oracle` is what the system `erl` (OTP 29.1.1 / erts-17.1)
/// prints for the **same** `.so` and the **same** driver; a `diverges` row names this
/// runtime's own answer and the mechanism behind it.
const EXPECTED: &[Expect] = &[
    Expect {
        key: "thread_send",
        oracle: "{{0,1,0},0}",
        diverges: None,
    },
    Expect {
        key: "thread_send_msg_exact",
        oracle: "true",
        diverges: None,
    },
    Expect {
        key: "worker_atoms",
        oracle: "{0,1,1,1,0}",
        diverges: None,
    },
    Expect {
        key: "worker_atom_identity",
        oracle: "identical",
        diverges: None,
    },
    Expect {
        key: "main_env",
        oracle: "{0,1}",
        diverges: None,
    },
    Expect {
        key: "main_env_msg_exact",
        oracle: "true",
        diverges: None,
    },
    Expect {
        key: "null_env",
        oracle: "{0,1}",
        diverges: None,
    },
    Expect {
        key: "null_env_caller_thread",
        oracle: "normal",
        diverges: Some((
            "undefined",
            "`enif_thread_type()` of the CALLING thread: the oracle's NIF runs on a scheduler \
             thread (ERL_NIF_THR_NORMAL_SCHEDULER = 1); this runtime runs it on its own driver \
             thread, which is not a registered scheduler thread, so the answer is \
             ERL_NIF_THR_UNDEFINED (0) — beam_abi/src/nif/enif/threads.rs folds \
             ERL_NIF_THR_OTHER into UNDEFINED",
        )),
    },
    Expect {
        key: "null_env_msg_exact",
        oracle: "true",
        diverges: None,
    },
    Expect {
        key: "parked_status",
        oracle: "{status,waiting}",
        diverges: None,
    },
    Expect {
        key: "thread_send_to",
        oracle: "{{{0,1,0},0},true}",
        diverges: None,
    },
    Expect {
        key: "parked_msg_exact",
        oracle: "true",
        diverges: None,
    },
];

/// Every probe of `a3_thread_env.c` on both runtimes, observation by observation.
#[test]
fn the_thread_env_fixture_agrees_with_the_oracle_probe_by_probe() {
    let Some(tc) = nif_a3::toolchain("nif_a3_thread_env") else {
        return;
    };
    let Some(fixture) = nif_a3::build(
        &tc,
        "thread_env",
        &fixture_source(),
        "a3_thread_env",
        &[
            ("a3_thread_env", NIF_ERL),
            ("a3_thread_env_driver", DRIVER_ERL),
        ],
        "a3_thread_env_driver",
    ) else {
        return;
    };

    let rust = fixture.rust_transcript();
    let oracle = fixture.oracle_transcript(&tc);
    nif_a3::check("nif_a3_thread_env", EXPECTED, &rust, &oracle);
    rust.print_notes("nif_a3_thread_env");

    fixture.cleanup();
}
