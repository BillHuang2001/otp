/// Every scheduling probe on both runtimes, observation by observation.
#[test]
fn the_schedule_fixture_agrees_with_the_oracle_probe_by_probe() {
    let Some(tc) = nif_a3::toolchain("nif_a3_schedule") else {
        return;
    };
    let Some(fixture) = nif_a3::build(
        &tc,
        "schedule",
        &fixture_source(),
        "a3_schedule",
        &[
            ("a3_schedule", NIF_ERL),
            ("a3_schedule_driver", DRIVER_ERL),
        ],
        "a3_schedule_driver",
    ) else {
        return;
    };

    let rust = fixture.rust_transcript();
    let oracle = fixture.oracle_transcript(&tc);
    nif_a3::check("nif_a3_schedule", EXPECTED, &rust, &oracle);
    rust.print_notes("nif_a3_schedule");
    for (probe, why) in UNDRIVEN {
        println!("nif_a3_schedule: {probe} deliberately not driven: {why}");
    }

    fixture.cleanup();
}
