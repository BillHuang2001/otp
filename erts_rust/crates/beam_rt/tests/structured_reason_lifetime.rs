// ---------------------------------------------------------------------------------------
// Test 3 — a deep reason holding a runtime-built off-heap refc binary
// ---------------------------------------------------------------------------------------

/// A reason mixing lists, tuples and a map, with a **100-byte** `binary:copy/1` result — a
/// genuine off-heap refc binary, whose payload lives *outside* the process heap — next to a
/// heap-built list.
///
/// The off-heap half is what makes this case the hardest one: the stabilization must **share**
/// the payload handle (resolving the machine's `refc_binaries`) rather than trip the off-heap
/// valve, or the retained binary would dangle once the machine is dropped. The rendering is
/// asserted byte-identically to the oracle's.
///
/// The `deep/0` control case runs in the same test: a nested reason whose binaries are all
/// small enough to stay on-heap, which rendered correctly before the fix too and must keep
/// doing so.
#[test]
fn a_deep_reason_with_an_off_heap_binary_renders_byte_identically() {
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly("structured reason lifetime", "no `erlc` on $PATH");
        return;
    };
    let Some(oracle) = support::require_oracle("structured reason lifetime") else {
        return;
    };
    let Some(fixture) = build_fixture("deep", &erlc) else {
        return;
    };

    // The off-heap half: `binary:copy(<<0:800>>)` is 100 bytes, above the 64-byte on-heap
    // limit, so the reason holds a real refc payload.
    let Some(run) = run_reason(&fixture, "deep_offheap") else {
        support::skip_loudly(
            "structured reason lifetime",
            "the built `beam_rt` did not answer within the probe bound",
        );
        return;
    };
    assert_reason(&run, "off-heap binary reason", DEEP_OFFHEAP_REASON);
    if let Some(theirs) = oracle_w(
        &oracle,
        &fixture,
        "{badkey, [{bin, binary:copy(<<0:800>>)}, {lst, lists:seq(1, 3)}]}",
    ) {
        assert_eq!(theirs, DEEP_OFFHEAP_REASON, "the system erl's rendering");
    }

    // The control: an on-heap-only deep reason, which must keep rendering as it did.
    let Some(run) = run_reason(&fixture, "deep") else {
        support::skip_loudly(
            "structured reason lifetime",
            "the built `beam_rt` did not answer within the probe bound",
        );
        return;
    };
    assert_reason(
        &run,
        "nested reason",
        "{badkey,[{a,[{b,[<<120,121,122>>,[104,101,108,108,111]]}]},#{k => [1,2,3]}]}",
    );
    if let Some(theirs) = oracle_w(
        &oracle,
        &fixture,
        "{badkey, [{a, [{b, [<<\"xyz\">>, \"hello\"]}]}, #{k => [1, 2, 3]}]}",
    ) {
        assert_eq!(
            theirs,
            "{badkey,[{a,[{b,[<<120,121,122>>,[104,101,108,108,111]]}]},#{k => [1,2,3]}]}",
            "the system erl's rendering"
        );
    }
}

// ---------------------------------------------------------------------------------------
// Test 4 — the `-eval` route
// ---------------------------------------------------------------------------------------

/// The `-eval` route renders the same reason, through the same escape boundary.
///
/// `Runtime::eval` runs its body in a **freshly spawned action process** which it then
/// terminates (`Runtime::as_action_process`), so the reason term the expression built dies with
/// that process's heap. Before the fix the CLI printed the `Display` placeholder
/// `beam_rt: error <structured reason>`; the reason is now stabilized on the way out and
/// rendered with its real term by `reported_reason`.
#[test]
fn the_eval_route_renders_a_structured_reason_with_its_real_term() {
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly("structured reason lifetime", "no `erlc` on $PATH");
        return;
    };
    let Some(oracle) = support::require_oracle("structured reason lifetime") else {
        return;
    };
    let Some(fixture) = build_fixture("eval", &erlc) else {
        return;
    };
    for (expr, reason) in [
        (
            "erlang:error({badkey, binary:copy(<<\"abc\">>)}).",
            "{badkey,<<97,98,99>>}",
        ),
        ("erlang:error({badkey, lists:seq(1, 3)}).", "{badkey,[1,2,3]}"),
        (
            "erlang:error({badkey, [{bin, binary:copy(<<0:800>>)}, {lst, lists:seq(1, 3)}]}).",
            DEEP_OFFHEAP_REASON,
        ),
    ] {
        let Some(run) = run_beam_rt(&fixture, &["-noshell", "-eval", expr]) else {
            support::skip_loudly(
                "structured reason lifetime",
                "the built `beam_rt` did not answer within the probe bound",
            );
            return;
        };
        assert_reason(&run, &format!("-eval {expr}"), reason);
    }
    // The oracle agrees with the `-eval` route's rendering of the same terms.
    if let Some(theirs) = oracle_w(&oracle, &fixture, "{badkey, binary:copy(<<\"abc\">>)}") {
        assert_eq!(theirs, "{badkey,<<97,98,99>>}", "the system erl's rendering");
    }
}

