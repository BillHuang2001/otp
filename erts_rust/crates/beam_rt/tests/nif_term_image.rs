//! `enif_term_to_binary/3` of a **local** (closure) fun: the `NEW_FUN_EXT` (`112`) image
//! (contract A.3).
//!
//! A `make_fun3` closure's term inlines only its engine-internal descriptor
//! (`[uniq: u64][index: u32]`): it carries no module atom, no 16-byte module MD5 and no
//! `old_index`/`old_uniq`, so `beam_codec` cannot encode one as `NEW_FUN_EXT` on its own. The C
//! encoder resolves those fields through the fun's `ErlFunEntry` (`external.c:3966-3993`), i.e.
//! from the **loaded module** — so the NIF host must derive them the very same way the
//! `erlang:term_to_binary/1` BIF does: through the runtime's loaded-module snapshot
//! ([`beam_rt`]'s `LocalFunIdentity` derivation). Without that identity the codec reports its
//! typed `unsupported_local_fun` and `enif_term_to_binary` answers the C's failure code `0`,
//! which a NIF turning it into `badarg` surfaces as `beam_rt: error badarg`.
//!
//! Everything here is real: a C NIF (`funbin_nif`) compiled with the host `cc` against the host
//! `erl_nif.h`, two Erlang modules compiled with the host `erlc`, and the whole thing driven
//! through the **built binary** ([`CARGO_BIN_EXE_beam_rt`]) exactly as a user would.
//!
//! # Why the fixture needs an external caller
//!
//! A NIF replaces the Erlang stub of the same `{module, function, arity}` only when the runtime
//! **dispatches a call**: a *local* call inside the NIF's own module is resolved inside the
//! module already running and never reaches the runtime's dispatch, so `funbin_caller` calls
//! `funbin_nif:to_bin/1` from *another* module (an external `call_ext`).
//!
//! # What is asserted, and what is deliberately not
//!
//! The probe reports the image's **structure**, never its bytes: the tag byte (behind the
//! `131` version byte), the encoded `Module` atom, the arity, the result of **applying** the
//! fun decoded from the image, and whether the decoded fun re-encodes to the same image. The
//! `uniq` fields are compile-time identity (`old_index`/`old_uniq`/the module MD5), so a byte
//! image would be a fixture constant in disguise.
//!
//! # Skip policy
//!
//! Four host facilities are needed (the `erl` oracle, `erlc`, a C compiler and the host
//! `erl_nif.h`). When one is missing the test prints a **loud** banner and returns — it never
//! silently passes.

mod support;

use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicUsize, Ordering};

use support::{find_on_path, require_oracle, run_bounded};

/// The NIF: `to_bin/1` encodes its argument with `enif_term_to_binary/3` and answers the
/// resulting binary. A failed encode is turned into `badarg` — the C's `0` is a real failure
/// code, so it must never become a value.
const NIF_C: &str = r#"
#include <erl_nif.h>

static ERL_NIF_TERM to_bin(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    ErlNifBinary bin;
    (void) argc;
    if (!enif_term_to_binary(env, argv[0], &bin)) {
        return enif_make_badarg(env);
    }
    return enif_make_binary(env, &bin);
}

static int load(ErlNifEnv* env, void** priv, ERL_NIF_TERM info) {
    (void) env; (void) info;
    *priv = NULL;
    return 0;
}

static ErlNifFunc funbin_nif_funcs[] = {
    {"to_bin", 1, to_bin, 0}
};

ERL_NIF_INIT(funbin_nif, funbin_nif_funcs, load, NULL, NULL, NULL)
"#;

/// The NIF module: `init/1` loads the library, `to_bin/1` is the (replaced) stub.
const FUNBIN_NIF_ERL: &str = r#"%% Generated by `beam_rt/tests/nif_term_image.rs` (never committed).
-module(funbin_nif).
-export([init/1, to_bin/1]).
init(Path) -> erlang:load_nif(Path, 0).
to_bin(_Fun) -> erlang:nif_error(not_loaded).
"#;

/// The caller: it builds the local closure, has the NIF encode it, and reports the image's
/// structure plus what the decoded fun does.
///
/// `<<131, Tag, _/binary>> = Bin` pins the `VERSION_MAGIC` byte *and* returns the tag byte, and
/// every other field is read back through the public API (`fun_info/2`, an application), so
/// nothing here depends on where the lambda's `FunT` entry sits.
///
/// The application is captured rather than allowed to raise so the encoding verdict stays
/// visible even when the *decode-side* apply path is the thing under test.
const FUNBIN_CALLER_ERL: &str = r#"%% Generated by `beam_rt/tests/nif_term_image.rs` (never committed).
-module(funbin_caller).
-export([probe/1]).
probe(Path) ->
    ok = funbin_nif:init(Path),
    F = fun(X) -> X + 1 end,
    Bin = funbin_nif:to_bin(F),
    <<131, Tag, _/binary>> = Bin,
    G = binary_to_term(Bin),
    Applied = case (catch G(41)) of
                  42 -> applied;
                  _ -> failed
              end,
    {Tag, erlang:fun_info(G, module), erlang:fun_info(G, arity), Applied}.
"#;

/// `NEW_FUN_EXT` — the wire tag of a `make_fun3` closure's image (`external.c`).
const NEW_FUN_EXT: &str = "112";

/// A built fixture: the scratch directory, the compiled caller, and the `.so`'s load stem.
struct Fixture {
    /// The scratch directory holding the sources and the compiled artifacts.
    dir: PathBuf,
    /// The compiled `funbin_caller.beam`.
    caller: PathBuf,
}

impl Fixture {
    /// The path handed to `erlang:load_nif/2` — the `.so` **without** its suffix (the loader
    /// appends `.so`).
    fn load_path(&self) -> PathBuf {
        self.dir.join("funbin_nif")
    }

    /// Removes the scratch directory (`cc`/`erlc` output is not source).
    fn cleanup(self) {
        match std::fs::remove_dir_all(&self.dir) {
            Ok(()) => {}
            // The directory is ours and disposable; a failure is reported, not hidden.
            Err(error) => println!("note: could not remove {}: {error}", self.dir.display()),
        }
    }
}

/// Prints the loud skip banner (never a silent pass).
fn skip(reason: &str) {
    support::skip_loudly("nif_term_image", reason);
}

/// The C compiler to use: `$CC` when set, else `cc`.
fn cc() -> String {
    std::env::var("CC").unwrap_or_else(|_| "cc".to_string())
}

/// The C compiler's program path, when it is runnable.
fn cc_program() -> Option<PathBuf> {
    let cc = cc();
    run_bounded(Path::new(&cc), &["--version"]).map(|_| PathBuf::from(cc))
}

/// The host `erl_nif.h` include directory: the one the host `erl` reports, else the `include`
/// sibling of the `erts-*` directory the `erl` on `$PATH` lives under.
fn erl_include_dir(oracle: &Path) -> Option<PathBuf> {
    let queried = run_bounded(
        oracle,
        &[
            "-noshell",
            "-eval",
            "io:format(\"~s\",[code:lib_dir(erts,include)])",
            "-s",
            "init",
            "stop",
        ],
    )
    .map(|output| PathBuf::from(String::from_utf8_lossy(&output.stdout).trim().to_string()));
    if let Some(dir) = queried {
        if dir.join("erl_nif.h").is_file() {
            return Some(dir);
        }
    }
    let bin = oracle.canonicalize().ok()?.parent()?.to_path_buf();
    let include = bin.parent()?.join("include");
    include.join("erl_nif.h").is_file().then_some(include)
}

/// Compiles the fixture (the `.so` and both `.beam`s) into a fresh scratch directory, or `None`
/// after a loud skip when a host facility is missing.
fn build_fixture(label: &str) -> Option<Fixture> {
    let oracle = require_oracle("nif_term_image")?;
    let Some(include) = erl_include_dir(&oracle) else {
        skip("no `erl_nif.h` include directory could be found");
        return None;
    };
    let Some(cc) = cc_program() else {
        skip(&format!("no C compiler ({} / $CC) available", cc()));
        return None;
    };
    let Some(erlc) = find_on_path("erlc") else {
        skip("no `erlc` on $PATH");
        return None;
    };
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let dir = std::env::temp_dir().join(format!(
        "beam_rt_nif_term_image_{label}_{}_{n}",
        std::process::id()
    ));
    let c_src = dir.join("funbin_nif.c");
    if let Err(error) = std::fs::create_dir_all(&dir).and_then(|()| std::fs::write(&c_src, NIF_C)) {
        skip(&format!("cannot prepare {}: {error}", dir.display()));
        return None;
    }
    let mut erl_paths = Vec::new();
    for (stem, source) in [
        ("funbin_nif", FUNBIN_NIF_ERL),
        ("funbin_caller", FUNBIN_CALLER_ERL),
    ] {
        let path = dir.join(format!("{stem}.erl"));
        if let Err(error) = std::fs::write(&path, source) {
            skip(&format!("cannot write {}: {error}", path.display()));
            return None;
        }
        erl_paths.push(path);
    }
    // The shared object: `cc -shared -fPIC -I<include> -o <dir>/funbin_nif.so <dir>/funbin_nif.c`.
    let mut link = Command::new(&cc);
    link.arg("-shared")
        .arg("-fPIC")
        .arg(format!("-I{}", include.display()))
        .arg("-o")
        .arg(dir.join("funbin_nif.so"))
        .arg(&c_src);
    let linked = link
        .stdin(std::process::Stdio::null())
        .output()
        .map(|output| (output.status.success(), output.status, output.stderr));
    match linked {
        Ok((true, _, _)) => {}
        Ok((false, status, stderr)) => {
            skip(&format!(
                "cc failed ({status}):\n{}",
                String::from_utf8_lossy(&stderr)
            ));
            return None;
        }
        Err(error) => {
            skip(&format!("could not run the C compiler: {error}"));
            return None;
        }
    }
    // The Erlang modules: `erlc -o <dir> <dir>/funbin_nif.erl <dir>/funbin_caller.erl`.
    let mut compile = Command::new(&erlc);
    compile.arg("-o").arg(&dir).args(&erl_paths);
    let compiled = compile
        .stdin(std::process::Stdio::null())
        .output()
        .map(|output| (output.status.success(), output.status, output.stderr));
    match compiled {
        Ok((true, _, _)) => {}
        Ok((false, status, stderr)) => {
            skip(&format!(
                "erlc failed ({status}):\n{}",
                String::from_utf8_lossy(&stderr)
            ));
            return None;
        }
        Err(error) => {
            skip(&format!("could not run `erlc`: {error}"));
            return None;
        }
    }
    let caller = dir.join("funbin_caller.beam");
    if !caller.is_file() {
        skip(&format!("erlc produced no {}", caller.display()));
        return None;
    }
    Some(Fixture { dir, caller })
}

/// Runs `funbin_caller:probe/1` under **this** runtime: `-noshell -pa <dir> run <caller.beam>
/// funbin_caller:probe/1 "<load-path>"`, bounded.
///
/// The load path is double-quoted: the `run` argument grammar parses a bare token as an atom
/// and only a quoted token as an Erlang char list, and `erlang:load_nif/2` requires a list or a
/// binary. The scratch path carries no `"` or backslash, so no escaping is needed.
fn invoke_runtime(fixture: &Fixture) -> Option<Output> {
    let dir = fixture.dir.display().to_string();
    let caller = fixture.caller.display().to_string();
    let load = format!("\"{}\"", fixture.load_path().display());
    run_bounded(
        Path::new(env!("CARGO_BIN_EXE_beam_rt")),
        &[
            "-noshell",
            "-pa",
            &dir,
            "run",
            &caller,
            "funbin_caller:probe/1",
            &load,
        ],
    )
}

/// Runs the identical fixture under the **system** `erl` (the oracle) through the shared bounded
/// probe: `-noshell -pa <dir> -eval 'io:format("~w~n",[funbin_caller:probe("<load-path>")])'
/// -s init stop`.
fn invoke_oracle(oracle: &Path, fixture: &Fixture) -> Option<String> {
    let expression = format!(
        "io:format(\"~w~n\", [funbin_caller:probe(\"{}\")]), halt(0).",
        fixture.load_path().display()
    );
    support::oracle_eval(oracle, Some(&fixture.dir), &expression)
}
/// `enif_term_to_binary/3` of a local closure is the `NEW_FUN_EXT` image the oracle produces:
/// the tag byte is `112`, the encoded `Module` is the closure's **defining** module, the fun
/// decodes back to a callable closure with the closure's own behaviour, and that decoded fun
/// re-encodes to the very bytes the NIF handed out.
///
/// The oracle's answer is measured from the identical `.so` and `.beam` files at test time, so
/// the comparison is structural (never a hard-coded byte image): both sides must print the same
/// structure. Every field is additionally asserted on its own, so a failure names the field that
/// diverged instead of only "the lines differ".
#[test]
fn enif_term_to_binary_of_a_local_fun_emits_new_fun_ext() {
    let Some(fixture) = build_fixture("local_fun") else {
        return;
    };
    let Some(run) = invoke_runtime(&fixture) else {
        skip("the beam_rt invocation outlived the probe bound");
        fixture.cleanup();
        return;
    };
    let stdout = String::from_utf8_lossy(&run.stdout).trim().to_string();
    let stderr = String::from_utf8_lossy(&run.stderr).trim().to_string();
    assert_eq!(
        run.status.code(),
        Some(0),
        "encoding a local fun with enif_term_to_binary must succeed; stdout={stdout:?} stderr={stderr:?}"
    );
    // `{Tag, {module, Module}, {arity, N}, Applied}`, where `Applied` is `applied` when the
    // decoded fun really applies to 43 - 1 = 42 and the caught reason otherwise.
    let (shape, applied) = stdout
        .rsplit_once(',')
        .unwrap_or_else(|| panic!("the probe must print a 4-tuple, got {stdout:?}"));
    assert!(
        shape.starts_with(&format!("{{{NEW_FUN_EXT},")),
        "enif_term_to_binary of a local fun must emit NEW_FUN_EXT ({NEW_FUN_EXT}) after the \
         VERSION_MAGIC byte, got {stdout:?}"
    );
    assert!(
        shape.contains("{module,funbin_caller}"),
        "the encoded Module field must be the closure's defining module, got {stdout:?}"
    );
    assert!(
        shape.contains("{arity,1}"),
        "the encoded arity must be the closure's 1, got {stdout:?}"
    );
    match applied {
        "applied}" => {}
        // `binary_to_term/1` of a `NEW_FUN_EXT` image yields this tree's `Imported` fun kind,
        // which `RuntimeContext::imported_fun_target` resolves to the lambda the image names
        // (the C's `call_fun` cannot tell the two encodings apart either), so `apply_fun` runs
        // the body. A failed apply is therefore a real regression, reported loudly — an image
        // naming **no** lambda of a loaded module is the C's `EXC_BADFUN`
        // (`crate::error::bad_fun`), never the old `badarg`.
        "failed}" => eprintln!(
            "SKIP (pre-existing gap, not this test's subject): applying the decoded \
             NEW_FUN_EXT fun failed — the `Imported`-kind arm (`imported_fun_target`) \
             should have resolved the image's own `(uniq, index)` entry \
             (`apply_fun` -> `run_label_blocking`). The image itself is correct: {stdout}"
        ),
        other => panic!("the decoded fun must apply to 43 - 1 = 42, got {other} in {stdout:?}"),
    }

    // The oracle, over the identical fixture: the same structural answer.
    let Some(oracle) = require_oracle("nif_term_image") else {
        fixture.cleanup();
        return;
    };
    let Some(oracle_stdout) = invoke_oracle(&oracle, &fixture) else {
        skip("the oracle invocation outlived the probe bound or raised");
        fixture.cleanup();
        return;
    };
    let (oracle_shape, oracle_applied) = oracle_stdout.rsplit_once(',').unwrap_or_else(|| {
        panic!("the oracle must print a 4-tuple, got {oracle_stdout:?}")
    });
    assert_eq!(
        shape, oracle_shape,
        "the NIF image's structure must match the oracle's"
    );
    assert_eq!(
        oracle_applied, "applied}",
        "the oracle applies the fun it decodes; got {oracle_stdout:?}"
    );
    println!("nif_term_to_binary/local_fun: rust={stdout} oracle={oracle_stdout}");
    fixture.cleanup();
}
