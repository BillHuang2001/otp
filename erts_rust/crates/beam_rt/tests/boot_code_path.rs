//! The **`-pa`/`-pz`-on-the-`-boot`-route** suite (contracts A.6 + A.7), cross-checked
//! against the live system Erlang.
//!
//! The oracle applies the command line's `-pa`/`-pz` code-path switches **before** the boot
//! script runs: `init`'s `do_boot/3` hands `path_flags/1`'s `{Pa, Pz}` to `eval_script/2`,
//! whose `{path, …}` clause builds the prim-loader path as `Pa ++ ScriptPath ++ Pz`
//! (`erts/preloaded/src/init.erl:1202,1324-1333,1418`). A `-pa` directory therefore shadows
//! the installed `ebin` directories for every `{primLoad, …}` batch of the script — which is
//! what makes `-pa` usable as an instrumentation hook for the A.9 boot chain.
//!
//! This runtime reaches the same observable end state through a different seam: the CLI
//! parser records the switches ([`beam_rt::cli`], contract A.6), `Runtime::new` seeds them
//! into the code server (`src/runtime.rs`), and `Runtime::boot` adds the system `ebin`
//! directories **after** them, so the `-pa` entries head the path by the time any directive
//! is executed. This suite pins that property from the outside, because it is a
//! *behavioural* contract that no in-crate unit test of the parser can see:
//!
//! 1. a module that exists **only** in a unique `-pa` directory is resolved by the boot
//!    script's **first** directive ([`a_pa_directory_is_on_the_code_path_before_the_boot_script_runs`]) —
//!    the same run without `-pa` cannot resolve it, which is what proves the exit status
//!    came from the added directory ([`without_pa_the_boot_script_cannot_resolve_the_marker`]);
//! 2. a `-pz` directory is on the path too, but **after** a `-pa` one
//!    ([`a_pz_directory_is_on_the_code_path_on_the_boot_route`],
//!    [`pa_precedes_pz_on_the_boot_route`]);
//! 3. the very same directory is honoured on the ordinary `-eval` route, so the two routes
//!    cannot drift apart ([`the_same_pa_directory_is_honoured_on_the_eval_route`]).
//!
//! # How the observable is produced
//!
//! The marker module's `run/0` is `erlang:halt(Status)`, and the two fixture directories
//! hold the *same module name* compiled with two **different** statuses — so the process
//! exit code alone reports **which** directory won the search. The boot script is
//! `[{primLoad,[marker]}, {apply,{marker,run,[]}}]`, written at test time with the system
//! `erl` in exactly the `{script, {Name, Vsn}, Instructions}` shape `init` reads.
//!
//! Every test skips **loudly** — a clear banner and an early `return` — when `erlc` or the
//! oracle is unavailable. Nothing here silently passes.
mod support;

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

/// The exit status the **`-pa`** copy of the marker module halts with.
const PA_STATUS: i32 = 7;
/// The exit status the **`-pz`** copy halts with — deliberately different from
/// [`PA_STATUS`], so the exit code names the directory that won the search.
const PZ_STATUS: i32 = 8;
/// The bare `error undef` exit code of a runtime that cannot resolve a module (contract A.6's
/// `EXIT_RUNTIME`).
const EXIT_RUNTIME: i32 = 1;
/// The marker module's name — the **same** in both directories: only the code path can
/// decide which copy is loaded, never the module's name.
const MARKER: &str = "boot_code_path_marker";
/// The loud-skip banner.
const BANNER: &str = "boot_code_path";

// ---------------------------------------------------------------------------------------
// The fixture
// ---------------------------------------------------------------------------------------

/// The marker module, halting with `status` when the boot script applies it.
fn marker_source(status: i32) -> String {
    format!(
        "%% Generated by `beam_rt/tests/boot_code_path.rs` (never committed).\n\
         -module({MARKER}).\n\
         -export([run/0]).\n\
         run() -> erlang:halt({status}).\n"
    )
}

/// The compiled fixture: one scratch root holding a `-pa` directory, a `-pz` directory and
/// the boot script that loads the marker. Removed on drop.
struct Fixture {
    /// The scratch root.
    root: PathBuf,
    /// The `-pa` directory (holds the [`PA_STATUS`] copy of the marker).
    pa: PathBuf,
    /// The `-pz` directory (holds the [`PZ_STATUS`] copy).
    pz: PathBuf,
    /// The boot script's **stem**: the file is `<stem>.boot`, and `-boot <stem>` is what both
    /// runtimes are handed — each appends the `.boot` suffix exactly as `init`'s `get_boot/2`
    /// does.
    boot: PathBuf,
}

impl Drop for Fixture {
    fn drop(&mut self) {
        if let Err(error) = std::fs::remove_dir_all(&self.root) {
            eprintln!(
                "warning: could not remove the fixture root {}: {error}",
                self.root.display()
            );
        }
    }
}

/// The compiler: a sibling of the resolved oracle first (the same installation), then
/// `$PATH` — the same rule the other compiled-fixture suites use.
fn resolve_erlc() -> Option<PathBuf> {
    if let Some(dir) = support::resolve_oracle().as_deref().and_then(Path::parent) {
        let candidate = dir.join("erlc");
        if support::is_executable(&candidate) {
            return Some(candidate);
        }
    }
    support::find_on_path("erlc")
}

/// Compiles the two marker copies and writes the boot script, or `None` after a loud skip.
fn build_fixture(erlc: &Path, oracle: &Path, label: &str) -> Option<Fixture> {
    let root = std::env::temp_dir().join(format!(
        "beam_rt_boot_code_path_{label}_{}",
        std::process::id()
    ));
    // A stale directory from a killed run must not decide the result: start clean.
    match std::fs::remove_dir_all(&root) {
        Ok(()) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => {
            support::skip_loudly(BANNER, &format!("cannot clear {}: {error}", root.display()));
            return None;
        }
    }
    let pa = root.join("pa");
    let pz = root.join("pz");
    for (dir, status) in [(&pa, PA_STATUS), (&pz, PZ_STATUS)] {
        if let Err(error) = std::fs::create_dir_all(dir) {
            support::skip_loudly(BANNER, &format!("cannot create {}: {error}", dir.display()));
            return None;
        }
        let source = dir.join(format!("{MARKER}.erl"));
        if let Err(error) = std::fs::write(&source, marker_source(status)) {
            support::skip_loudly(BANNER, &format!("cannot write {}: {error}", source.display()));
            return None;
        }
        // `+deterministic` keeps the image path-free, like the committed fixtures.
        let output = match Command::new(erlc)
            .arg("+deterministic")
            .arg("-o")
            .arg(dir)
            .arg(&source)
            .output()
        {
            Ok(output) => output,
            Err(error) => {
                support::skip_loudly(BANNER, &format!("cannot run `erlc`: {error}"));
                return None;
            }
        };
        if !output.status.success() {
            support::skip_loudly(
                BANNER,
                &format!(
                    "`erlc` exited with {}: {}",
                    output.status,
                    String::from_utf8_lossy(&output.stderr)
                ),
            );
            return None;
        }
        if !dir.join(format!("{MARKER}.beam")).is_file() {
            support::skip_loudly(
                BANNER,
                &format!("`erlc` produced no {}/{MARKER}.beam", dir.display()),
            );
            return None;
        }
    }

    // The boot script: one `{primLoad, …}` (the very first directive, so resolution happens
    // before anything else runs) and the `{apply, …}` that makes the loaded copy's identity
    // observable through the exit code.
    let boot = root.join("marker");
    let boot_file = root.join("marker.boot");
    let program = format!(
        "ok = file:write_file(\"{boot}\", term_to_binary({{script,{{\"bcp\",\"1\"}},[\
         {{primLoad,[{MARKER}]}},\
         {{apply,{{{MARKER},run,[]}}}}]}})), halt(0).",
        boot = boot_file.display(),
    );
    let output = match Command::new(oracle)
        .args(["-noshell", "-eval", &program])
        .output()
    {
        Ok(output) => output,
        Err(error) => {
            support::skip_loudly(BANNER, &format!("cannot run `erl`: {error}"));
            return None;
        }
    };
    if !output.status.success() {
        support::skip_loudly(
            BANNER,
            &format!(
                "`erl` exited with {}: {}",
                output.status,
                String::from_utf8_lossy(&output.stderr)
            ),
        );
        return None;
    }
    if !boot_file.is_file() {
        support::skip_loudly(BANNER, &format!("`erl` produced no {}", boot_file.display()));
        return None;
    }
    Some(Fixture {
        root,
        pa,
        pz,
        boot,
    })
}

// ---------------------------------------------------------------------------------------
// Running the two runtimes
// ---------------------------------------------------------------------------------------

/// The built `beam_rt` binary.
fn beam_rt() -> PathBuf {
    PathBuf::from(env!("CARGO_BIN_EXE_beam_rt"))
}

/// Runs `program` with `args`, bounded by [`support::PROBE_TIMEOUT`] (a probe that blocks is
/// killed and reaped rather than hanging the suite).
fn run(program: &Path, args: &[String], what: &str) -> Output {
    let borrowed: Vec<&str> = args.iter().map(String::as_str).collect();
    support::run_bounded(program, &borrowed).unwrap_or_else(|| {
        panic!(
            "{what}: `{}` {args:?} could not be run to completion",
            program.display()
        )
    })
}

/// `<program> -noshell [-pa Pa] [-pz Pz] -boot <stem>` — the boot route, with the code-path
/// switches **before** `-boot` exactly as the recorded invocations give them.
fn boot_route(program: &Path, fixture: &Fixture, pa: bool, pz: bool, what: &str) -> Output {
    let mut args = vec!["-noshell".to_string()];
    if pa {
        args.push("-pa".to_string());
        args.push(fixture.pa.display().to_string());
    }
    if pz {
        args.push("-pz".to_string());
        args.push(fixture.pz.display().to_string());
    }
    args.push("-boot".to_string());
    args.push(fixture.boot.display().to_string());
    run(program, &args, what)
}

/// `<program> -noshell -pa Pa -eval <expr>` — the ordinary route.
fn eval_route(program: &Path, fixture: &Fixture, expr: &str, what: &str) -> Output {
    let args = vec![
        "-noshell".to_string(),
        "-pa".to_string(),
        fixture.pa.display().to_string(),
        "-eval".to_string(),
        expr.to_string(),
    ];
    run(program, &args, what)
}

/// The marker selected by a boot-route run: `(exit status, what the runtime said)`.
fn boot_outcome(output: &Output) -> (Option<i32>, String) {
    let said = if output.stderr.is_empty() {
        String::from_utf8_lossy(&output.stdout).trim().to_string()
    } else {
        String::from_utf8_lossy(&output.stderr).trim().to_string()
    };
    (output.status.code(), said)
}

/// Boots `fixture` with the given switches on **both** runtimes and asserts the two agree on
/// `expected`, returning this runtime's run so the caller can inspect stdout/stderr.
fn assert_boot_agrees(fixture: &Fixture, oracle: &Path, pa: bool, pz: bool, expected: i32, what: &str) -> Output {
    let ours = boot_route(&beam_rt(), fixture, pa, pz, &format!("beam_rt: {what}"));
    let (our_code, our_said) = boot_outcome(&ours);
    assert_eq!(
        our_code,
        Some(expected),
        "beam_rt: {what}: expected exit {expected} (it said {our_said:?})"
    );

    let theirs = boot_route(oracle, fixture, pa, pz, &format!("oracle: {what}"));
    let (their_code, their_said) = boot_outcome(&theirs);
    assert_eq!(
        their_code,
        Some(expected),
        "the system erl: {what}: expected exit {expected} (it said {their_said:?})"
    );
    ours
}

// ---------------------------------------------------------------------------------------
// The tests
// ---------------------------------------------------------------------------------------

/// A `-pa` directory is on the code path **before** the boot script's first directive runs:
/// the marker, which exists only there, is loaded and applied, and the process exits with
/// the status its `-pa` copy halts with. The live oracle does the same.
#[test]
fn a_pa_directory_is_on_the_code_path_before_the_boot_script_runs() {
    let Some(oracle) = support::require_oracle(BANNER) else {
        return;
    };
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly(BANNER, "no `erlc` on $PATH (and none beside the oracle)");
        return;
    };
    let Some(fixture) = build_fixture(&erlc, &oracle, "pa") else {
        return;
    };
    let ours = assert_boot_agrees(&fixture, &oracle, true, false, PA_STATUS, "-pa D -boot S");
    assert!(
        ours.stdout.is_empty(),
        "a resolved marker halts before printing anything; stdout: {:?}",
        String::from_utf8_lossy(&ours.stdout)
    );
}

/// The control for the test above: **without** `-pa` the same invocation cannot resolve the
/// marker, so it fails instead of exiting [`PA_STATUS`] — which is what makes the exit status
/// a faithful witness that the added directory was really searched.
#[test]
fn without_pa_the_boot_script_cannot_resolve_the_marker() {
    let Some(oracle) = support::require_oracle(BANNER) else {
        return;
    };
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly(BANNER, "no `erlc` on $PATH (and none beside the oracle)");
        return;
    };
    let Some(fixture) = build_fixture(&erlc, &oracle, "no_pa") else {
        return;
    };
    let ours = boot_route(&beam_rt(), &fixture, false, false, "beam_rt: -boot S (no -pa)");
    assert_eq!(
        ours.status.code(),
        Some(EXIT_RUNTIME),
        "beam_rt without -pa must fail to resolve the marker: {:?}",
        boot_outcome(&ours)
    );
    let theirs = boot_route(&oracle, &fixture, false, false, "oracle: -boot S (no -pa)");
    assert!(
        !theirs.status.success(),
        "the system erl without -pa must also fail to resolve the marker (exit {:?})",
        theirs.status.code()
    );
}

/// A `-pz` directory is on the code path of the boot route too — it is the **tail**, but it
/// is still searched, which the marker's `-pz` copy proves through its own exit status.
#[test]
fn a_pz_directory_is_on_the_code_path_on_the_boot_route() {
    let Some(oracle) = support::require_oracle(BANNER) else {
        return;
    };
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly(BANNER, "no `erlc` on $PATH (and none beside the oracle)");
        return;
    };
    let Some(fixture) = build_fixture(&erlc, &oracle, "pz") else {
        return;
    };
    assert_boot_agrees(&fixture, &oracle, false, true, PZ_STATUS, "-pz D -boot S");
}

/// `-pa` heads the code path and `-pz` tails it, so with **both** given the `-pa` copy wins —
/// on the boot route exactly as on the ordinary one.
#[test]
fn pa_precedes_pz_on_the_boot_route() {
    let Some(oracle) = support::require_oracle(BANNER) else {
        return;
    };
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly(BANNER, "no `erlc` on $PATH (and none beside the oracle)");
        return;
    };
    let Some(fixture) = build_fixture(&erlc, &oracle, "order") else {
        return;
    };
    assert_boot_agrees(&fixture, &oracle, true, true, PA_STATUS, "-pa D -pz D' -boot S");
}

/// The same `-pa` directory is honoured on the ordinary `-eval` route, and `code:which/1`
/// names the file there — the two routes are the same code path, so neither can drift.
#[test]
fn the_same_pa_directory_is_honoured_on_the_eval_route() {
    let Some(oracle) = support::require_oracle(BANNER) else {
        return;
    };
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly(BANNER, "no `erlc` on $PATH (and none beside the oracle)");
        return;
    };
    let Some(fixture) = build_fixture(&erlc, &oracle, "eval") else {
        return;
    };
    let resolved = fixture.pa.join(format!("{MARKER}.beam"));
    let expected = resolved.display().to_string();
    let expr = format!("io:format(\"~s~n\",[code:which({MARKER})]),halt(0).");

    let ours = eval_route(&beam_rt(), &fixture, &expr, "beam_rt: -eval code:which/1");
    assert_eq!(ours.status.code(), Some(0), "beam_rt: -eval must succeed");
    assert_eq!(
        String::from_utf8_lossy(&ours.stdout).trim(),
        expected,
        "beam_rt: -eval must resolve the marker from the -pa directory"
    );

    match support::oracle_eval(&oracle, Some(&fixture.pa), &expr) {
        Some(theirs) => assert_eq!(
            theirs, expected,
            "the system erl must resolve the marker from the same -pa directory"
        ),
        None => eprintln!("warning: the oracle could not answer `code:which/1` — not compared"),
    }
}
