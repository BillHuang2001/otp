//! `code:load_file/1` (contract A.7) end to end, through the built `beam_rt` binary and
//! cross-checked against the live system Erlang.
//!
//! `code:load_file/1` is a BIF-level load of the module's `.beam`: every route but `-version`
//! drives a boot script, and the booted `kernel_sup` carries a **live `code_server` process**,
//! while the code-path mutators and the read-side queries are served from **one** authoritative
//! store on the native floor (`src/native/code.rs` + `src/native/code/path.rs`) so the path they
//! report and the path the loader searches can never disagree. This suite pins the loader's
//! observable contract, which is the oracle's `{error, Reason}` / `{module, Module}`:
//!
//! 1. a **sticky** module (preloaded, or resolved under a `kernel`/`stdlib`/`compiler`
//!    directory) ⇒ `{error,sticky_directory}`;
//! 2. a module nowhere on the code path ⇒ `{error,nofile}`;
//! 3. a found-but-unloadable image ⇒ `{error,badfile}`;
//! 4. otherwise ⇒ `{module, Module}`, idempotently on a second call.
//!
//! Every expected value below was re-verified against the system `erl`
//! (`erl -noshell -eval '…'`, OTP 29.1.1 / erts-17.1). A non-atom argument *diverges* by
//! design: the oracle raises `{function_clause,…}` for `code:load_file/1` while this
//! runtime's `code:*` floor convention is the bare `badarg` (pinned by the colocated unit
//! test `code_load_file_rejects_a_non_atom_with_badarg`, not here).
//!
//! The user-module fixture is compiled **at test time** with the system `erlc` into a
//! scratch directory (never committed) and handed to both runtimes as a `-pa` entry. Every
//! test skips **loudly** — never silently passes — when the toolchain is unavailable.

mod support;

use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicU64, Ordering};
/// The fixture source: a module that is neither preloaded nor under a sticky directory.
///
/// Kept trivially small and free of library calls so the only thing under test is the
/// load/unload decision, not the loader's opcode coverage.
const FIXTURE_ERL: &str = r#"%% Generated by `beam_rt/tests/code_load_file.rs` (never committed).
-module(mymod).
-export([id/1]).

id(X) -> X.
"#;

// ---------------------------------------------------------------------------------------
// The programs both runtimes are given
// ---------------------------------------------------------------------------------------

/// Three sticky modules: `erlang` is **preloaded** (sticky from boot) and `lists`/`kernel`
/// resolve under the `stdlib`/`kernel` application directories.
const EXPR_STICKY: &str = "\
io:format(\"~p~n\", [{code:load_file(lists), code:load_file(erlang), \
code:load_file(kernel)}]), halt(0).";
const STICKY_EXPECTED: &str =
    "{{error,sticky_directory},{error,sticky_directory},{error,sticky_directory}}";

/// A module no code-path directory holds.
const EXPR_NOFILE: &str = "io:format(\"~p~n\", [code:load_file(no_such_mod_xyz)]), halt(0).";
const NOFILE_EXPECTED: &str = "{error,nofile}";

/// The scratch-dir program: `mymod` loads once and — answered from the code server's cache —
/// again, and a found-but-corrupt `bogus.beam` is the single `badfile` reason.
const EXPR_FIXTURE: &str = "\
io:format(\"~p~n\", [{code:load_file(mymod), code:load_file(mymod), \
code:load_file(bogus)}]), halt(0).";
const FIXTURE_EXPECTED: &str = "{{module,mymod},{module,mymod},{error,badfile}}";

/// The name-mismatch program: `mismatch.beam` is a **well-formed** image of `mymod`, so the
/// loader's expected-name check (the C's `beam_load.c`) is the only thing that can refuse it.
/// `{error,badfile}` — and **nothing** is loaded: neither the requested name nor the image's
/// own (`mymod` is still unloaded when the load_file/1 call has been made, which is why the
/// second element re-asks `mymod`'s own load state); `which/1` stays path-based, so the last
/// element proves the file **was** found (the refusal is the name check, not `{error,nofile}`).
const EXPR_MISMATCH: &str = "\
io:format(\"~p~n\", [{code:load_file(mismatch), erlang:module_loaded(mismatch), \
erlang:module_loaded(mymod), code:is_loaded(mismatch), \
code:which(mismatch) =/= non_existing}]), halt(0).";
const MISMATCH_EXPECTED: &str = "{{error,badfile},false,false,false,true}";

/// The same refusal on the whole-list route: `code:ensure_modules_loaded/1` reports the failed
/// module as `{mismatch,badfile}` (never `nofile`) and still loads the **matching** name.
const EXPR_ENSURE_MISMATCH: &str = "\
io:format(\"~p~n\", [{code:ensure_modules_loaded([mismatch]), \
erlang:module_loaded(mismatch), erlang:module_loaded(mymod), \
code:ensure_modules_loaded([mymod])}]), halt(0).";
const ENSURE_MISMATCH_EXPECTED: &str = "{{error,[{mismatch,badfile}]},false,false,ok}";// ---------------------------------------------------------------------------------------
// Running the two runtimes
// ---------------------------------------------------------------------------------------

/// Runs `program args` bounded by [`support::PROBE_TIMEOUT`] (a probe that blocks is killed
/// and reaped rather than hanging the suite), failing loudly when it cannot run at all.
fn run(program: &Path, args: &[&str]) -> Output {
    support::run_bounded(program, args).unwrap_or_else(|| {
        panic!(
            "`{}` {args:?} could not be run to completion",
            program.display()
        )
    })
}

/// `<beam_rt> -noshell [-pa dir] -eval expr` through the built binary.
///
/// The `-pa` entry comes **before** `-eval`, exactly as the oracle probe does: the runtime
/// evaluates the command line in order, so a code path added afterwards would be too late
/// for the expression.
fn beam_rt_eval(code_dir: Option<&Path>, expr: &str) -> Output {
    let mut argv: Vec<String> = vec!["-noshell".to_string()];
    if let Some(dir) = code_dir {
        argv.push("-pa".to_string());
        argv.push(dir.display().to_string());
    }
    argv.push("-eval".to_string());
    argv.push(expr.to_string());
    let args: Vec<&str> = argv.iter().map(String::as_str).collect();
    run(Path::new(env!("CARGO_BIN_EXE_beam_rt")), &args)
}

/// The trimmed stdout of a finished run, asserting it exited `0` and was silent on stderr.
fn printed(answer: &Output, what: &str) -> String {
    assert_eq!(
        answer.status.code(),
        Some(0),
        "{what}: the run must exit 0 — stderr:\n{}",
        String::from_utf8_lossy(&answer.stderr)
    );
    assert!(
        answer.stderr.is_empty(),
        "{what}: a successful run must be silent on stderr — {}",
        String::from_utf8_lossy(&answer.stderr)
    );
    String::from_utf8_lossy(&answer.stdout).trim().to_string()
}

/// Asserts this runtime prints exactly `expected` for `expr`, and that the live oracle prints
/// `expected` on a line of its own.
///
/// The oracle's refusal paths **also log**: `code:load_file/1` of a sticky module writes
/// `Can't load module '…' that resides in sticky dir` and an unloadable image writes the
/// `beam_load.c` report, both to **standard output** via the default logger handler and
/// asynchronously. This runtime emits no such report (the oracle's is not part of
/// `code:load_file/1`'s return value), so the oracle's answer is compared per **line**
/// rather than over its whole stdout — the value is one complete line, because the probe
/// prints it in a single `io:format("~p~n", …)` call.
fn assert_agrees(oracle: &Path, code_dir: Option<&Path>, expr: &str, expected: &str, what: &str) {
    let ours = printed(&beam_rt_eval(code_dir, expr), &format!("beam_rt: {what}"));
    assert_eq!(ours, expected, "beam_rt: {what}");
    match support::oracle_eval(oracle, code_dir, expr) {
        Some(theirs) => assert!(
            theirs.lines().any(|line| line.trim() == expected),
            "the system erl must print `{expected}` for {what}; it printed:\n{theirs}"
        ),
        None => eprintln!("warning: the oracle could not answer `{what}` — not compared"),
    }
}

