/// Sticky and missing modules: this runtime answers the oracle's `{error,sticky_directory}`
/// and `{error,nofile}` — and the sticky refusal really does not load the module.
#[test]
fn sticky_and_missing_modules_agree_with_the_live_oracle() {
    let Some(oracle) = support::require_oracle("code_load_file") else {
        return;
    };
    assert_agrees(
        &oracle,
        None,
        EXPR_STICKY,
        STICKY_EXPECTED,
        "code:load_file/1 of a sticky module",
    );
    assert_agrees(
        &oracle,
        None,
        EXPR_NOFILE,
        NOFILE_EXPECTED,
        "code:load_file/1 of an absent module",
    );
}

