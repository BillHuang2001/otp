/// Three sticky modules: `erlang` is **preloaded** (sticky from boot) and `lists`/`kernel`
/// resolve under the `stdlib`/`kernel` application directories.
const EXPR_STICKY: &str = "\
io:format(\"~p~n\", [{code:load_file(lists), code:load_file(erlang), \
code:load_file(kernel)}]), halt(0).";
const STICKY_EXPECTED: &str =
    "{{error,sticky_directory},{error,sticky_directory},{error,sticky_directory}}";

/// A module no code-path directory holds.
const EXPR_NOFILE: &str = "io:format(\"~p~n\", [code:load_file(no_such_mod_xyz)]), halt(0).";
const NOFILE_EXPECTED: &str = "{error,nofile}";

/// The scratch-dir program: `mymod` loads once and — answered from the code server's cache —
/// again, and a found-but-corrupt `bogus.beam` is the single `badfile` reason.
const EXPR_FIXTURE: &str = "\
io:format(\"~p~n\", [{code:load_file(mymod), code:load_file(mymod), \
code:load_file(bogus)}]), halt(0).";
const FIXTURE_EXPECTED: &str = "{{module,mymod},{module,mymod},{error,badfile}}";

/// The name-mismatch program: `mismatch.beam` is a **well-formed** image of `mymod`, so the
/// loader's expected-name check (the C's `beam_load.c`) is the only thing that can refuse it.
/// `{error,badfile}` — and **nothing** is loaded: neither the requested name nor the image's
/// own (`mymod` is still unloaded when the load_file/1 call has been made, which is why the
/// second element re-asks `mymod`'s own load state); `which/1` stays path-based, so the last
/// element proves the file **was** found (the refusal is the name check, not `{error,nofile}`).
const EXPR_MISMATCH: &str = "\
io:format(\"~p~n\", [{code:load_file(mismatch), erlang:module_loaded(mismatch), \
erlang:module_loaded(mymod), code:is_loaded(mismatch), \
code:which(mismatch) =/= non_existing}]), halt(0).";
const MISMATCH_EXPECTED: &str = "{{error,badfile},false,false,false,true}";

/// The same refusal on the whole-list route: `code:ensure_modules_loaded/1` reports the failed
/// module as `{mismatch,badfile}` (never `nofile`) and still loads the **matching** name.
const EXPR_ENSURE_MISMATCH: &str = "\
io:format(\"~p~n\", [{code:ensure_modules_loaded([mismatch]), \
erlang:module_loaded(mismatch), erlang:module_loaded(mymod), \
code:ensure_modules_loaded([mymod])}]), halt(0).";
const ENSURE_MISMATCH_EXPECTED: &str = "{{error,[{mismatch,badfile}]},false,false,ok}";

// ---------------------------------------------------------------------------------------
// The **call** route: an on-demand load performs the same expected-name check, but a call
// does not *return* anything — it raises, and the oracle raises the **bare** `error:undef`
// (never the loader's message, which is only what the `code:*` routes fold into `badfile`).
// Measured on OTP 29.1.1 / erts-17.1 with this fixture's `mismatch.beam` (a well-formed image
// of `mymod`) on a `-pa` directory:
//
//   * uncaught `mismatch:id(7)` ⇒ exit 1, empty stdout, and the node's crash report on stderr
//     naming `({undef,[{mismatch,id,[7],[]}, …]})`;
//   * `catch mismatch:id(7)` ⇒ `{'EXIT',{undef,[{mismatch,id,[7],[]}, {erl_eval,…}, …]}}`;
//   * a module with **no file at all** (`nosuchmod_xyz`) behaves identically, byte for byte —
//     which is the whole point: the reason atom is `undef` either way.
// ---------------------------------------------------------------------------------------

/// The uncaught call to the mismatching image: the raise escapes the runtime.
const EXPR_CALL_MISMATCH: &str = "mismatch:id(7).";

/// The control: the very same call against a module no code-path directory holds.
const EXPR_CALL_NOFILE: &str = "nosuchmod_xyz:id(7).";

/// This runtime's one-line diagnostic for the bare `error:undef` raise (the CLI's
/// `beam_rt: error <reason>` with exit code 1, the runtime-error code).
const CALL_UNDEF_STDERR: &str = "beam_rt: error undef";

/// The caught call, pinned exactly: the tree-walker contributes the oracle's innermost
/// `{Module, Function, ArgList, []}` head item and **no** invented `erl_eval`/`init` frames
/// (there is no `erl_eval` port here), so only the head item is comparable with the oracle —
/// which [`EXPR_CALL_MISMATCH_HEAD`] does, oracle-cross-checked.
const EXPR_CALL_MISMATCH_CAUGHT: &str =
    "io:format(\"~p~n\",[catch mismatch:id(7)]), halt(0).";
const CALL_MISMATCH_CAUGHT_EXPECTED: &str = "{'EXIT',{undef,[{mismatch,id,[7],[]}]}}";

/// The **head trace item** of the caught raise, which both runtimes must agree on.
const EXPR_CALL_MISMATCH_HEAD: &str = "\
case catch mismatch:id(7) of {'EXIT',{undef,[Head|_]}} -> io:format(\"~p~n\",[Head]); \
Other -> io:format(\"~p~n\",[Other]) end, halt(0).";
const CALL_MISMATCH_HEAD_EXPECTED: &str = "{mismatch,id,[7],[]}";

/// The same head item for the no-file control (the shape a missing module gets).
const EXPR_CALL_NOFILE_HEAD: &str = "\
case catch nosuchmod_xyz:id(7) of {'EXIT',{undef,[Head|_]}} -> io:format(\"~p~n\",[Head]); \
Other -> io:format(\"~p~n\",[Other]) end, halt(0).";
const CALL_NOFILE_HEAD_EXPECTED: &str = "{nosuchmod_xyz,id,[7],[]}";

/// The matching name still loads on demand and runs — the refusal is the expected-name check,
/// not a blanket refusal of an on-demand load.
const EXPR_CALL_MATCHING: &str = "io:format(\"~p~n\",[mymod:id(7)]), halt(0).";
const CALL_MATCHING_EXPECTED: &str = "7";

/// A compiled caller that catches the raise: the **compiled/scheduled** route performs the same
/// on-demand load (`call_ext` → `resolve_external_call` → `call_bif`), so its `{Class, Reason}`
/// pair must be the oracle's `{error,undef}` too.
const CALLER_ERL: &str = r#"%% Generated by `beam_rt/tests/code_load_file.rs` (never committed).
-module(mismatch_caller).
-export([run/1, run_missing/1]).

run(X) -> try mismatch:id(X) catch C:R -> {C, R} end.
run_missing(X) -> try nosuchmod_xyz:id(X) catch C:R -> {C, R} end.
"#;
const EXPR_CALLER_MISMATCH: &str =
    "io:format(\"~p~n\",[mismatch_caller:run(7)]), halt(0).";
const EXPR_CALLER_NOFILE: &str =
    "io:format(\"~p~n\",[mismatch_caller:run_missing(7)]), halt(0).";
/// The reason the oracle reports from compiled code: class `error`, reason atom `undef`.
const CALLER_EXPECTED: &str = "{error,undef}";
// ---------------------------------------------------------------------------------------
// The **`-s`/`-run` action** and the **export spawn** routes: the same load, the same reason
// ---------------------------------------------------------------------------------------
//
// The two remaining routes that *enter* a `Module:Function/Arity` (rather than returning a
// `code:*` load result) are a `-s`/`-run` action and an `M:F/A` spawn. Both hit
// `CodeServer::load`'s expected-name check, and both must report the call-site classifier's
// reason — the bare `undef` — never the loader's `module name in object code is …` message.
//
// Measured on OTP 29.1.1 / erts-17.1 with this fixture's `mismatch.beam` (a well-formed image
// of `mymod`) on a `-pa` directory:
//
//   * `erl -noshell -pa DIR -s mismatch id 7 -s init stop` ⇒ exit **1**, empty stdout, empty
//     stderr, and a crash dump whose slogan names the reason `undef`
//     (`{undef,[{init,start_it,1,[]},…]}`) — **identical** to the same row against
//     `nosuchmod_xyz` (a module with no file). `-run` behaves the same way;
//   * `erl -noshell -pa DIR -eval 'spawn(mismatch,id,[7])'` ⇒ exit **0** and `true` printed:
//     `spawn/3` does **no** loading at spawn time, so the child dies instead —
//     `spawn_monitor(mismatch,id,[7])` ⇒ `{'DOWN',…,process,Pid,{undef,[{mismatch,id,[7],[]}]}}`.
//     The reason is the same atom `undef`; only *where* it surfaces differs, and that residual is
//     documented on `Runtime::resolve_export_entry` (a lazy, dead-on-arrival export entry plus
//     the ERTS error-class exit reason are both needed to reproduce it).

/// The `-s`/`-run` row for the name-mismatched image.
const ACTION_MISMATCH: [&str; 3] = ["mismatch", "id", "7"];

/// The `-s`/`-run` control: the same call against a module no code-path directory holds.
const ACTION_NOFILE: [&str; 3] = ["nosuchmod_xyz", "id", "7"];

/// The `-s`/`-run` regression control: the module the image really names still runs (exit 0).
const ACTION_MATCHING: [&str; 3] = ["mymod", "id", "7"];

/// The spawn row: `spawn/3` of the mismatching image.
const EXPR_SPAWN_MISMATCH: &str =
    "P = spawn(mismatch,id,[7]), io:format(\"~p~n\",[is_pid(P)]), halt(0).";

/// The spawn control: the same call against a module no code-path directory holds.
const EXPR_SPAWN_NOFILE: &str =
    "P = spawn(nosuchmod_xyz,id,[7]), io:format(\"~p~n\",[is_pid(P)]), halt(0).";

/// What the **oracle** prints for [`EXPR_SPAWN_MISMATCH`] / [`EXPR_SPAWN_NOFILE`]: the spawn
/// really returns a pid (the child dies afterwards).
const SPAWN_ORACLE_EXPECTED: &str = "true";

/// The oracle's *reason* for that dead child, extracted through `spawn_monitor/3`: the
/// `'DOWN'` reason is `{undef, [{M,F,Args,[]}]}`, so the head item is what both runtimes can
/// agree on (this runtime raises the same atom at the spawn instead of after it).
const EXPR_SPAWN_DOWN_HEAD: &str = "\
case spawn_monitor(mismatch,id,[7]) of \
{P, R} when is_pid(P) -> receive {'DOWN',R,process,P,{undef,[Head|_]}} -> \
io:format(\"~p~n\",[Head]); M -> io:format(\"other ~p~n\",[M]) end end, halt(0).";
const SPAWN_DOWN_HEAD_EXPECTED: &str = "{mismatch,id,[7],[]}";// ---------------------------------------------------------------------------------------
