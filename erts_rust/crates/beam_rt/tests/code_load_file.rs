/// The loader's expected-name check (the C's `beam_load.c`) on the **file** route: a
/// well-formed `mismatch.beam` whose object code declares `mymod` is `{error,badfile}` and
/// loads under **neither** name, while `which/1` still finds the file — so the refusal is
/// provably the name check rather than `{error,nofile}`. `code:ensure_modules_loaded/1` folds
/// the same refusal into `{error,[{mismatch,badfile}]}`, and the **matching** name still loads
/// (`ok`). Both answers are the oracle's own, re-measured on every run.
#[test]
fn an_image_whose_object_code_names_another_module_is_refused_on_both_file_routes() {
    let Some(oracle) = support::require_oracle("code_load_file") else {
        return;
    };
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly("code_load_file", "no `erlc` on $PATH");
        return;
    };
    let Some(fixture) = build_fixture(&erlc) else {
        return;
    };
    assert_agrees(
        &oracle,
        Some(&fixture.dir),
        EXPR_MISMATCH,
        MISMATCH_EXPECTED,
        "code:load_file/1 of an image whose object code names another module",
    );
    assert_agrees(
        &oracle,
        Some(&fixture.dir),
        EXPR_ENSURE_MISMATCH,
        ENSURE_MISMATCH_EXPECTED,
        "code:ensure_modules_loaded/1 of an image whose object code names another module",
    );
}

/// A **call** to a module whose `.beam` image names another module raises the oracle's
/// **bare `error:undef`** (exit 1, empty stdout) — never the loader's
/// `module name in object code is …` diagnostic, which only the `code:*` routes see and fold
/// into `{error,badfile}`. The same call against a module with **no file at all** is
/// indistinguishable from it here, which is the contract: at a call site the reason names
/// nothing, and the callee identity lives in the stacktrace.
///
/// Measured on OTP 29.1.1 / erts-17.1 for this fixture (re-probed on every run): both rows
/// exit 1 with empty stdout, the mismatch row's crash report naming
/// `({undef,[{mismatch,id,[7],[]}, …]})`, and the caught rows agreeing on the reason atom and
/// on the innermost trace item. The compiled-caller rows prove the **scheduled/compiled** route
/// performs the very same on-demand load and reports `{error,undef}` as well, and the last row
/// re-pins the **explicit file** route's `{error,badfile}` (unchanged by this mapping).
#[test]
fn a_call_to_an_image_whose_object_code_names_another_module_raises_the_bare_undef() {
    let Some(oracle) = support::require_oracle("code_load_file") else {
        return;
    };
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly("code_load_file", "no `erlc` on $PATH");
        return;
    };
    let Some(fixture) = build_fixture(&erlc) else {
        return;
    };

    // (a) The uncaught call raises the bare `undef` from this runtime: exit 1, empty stdout,
    // one diagnostic line on stderr naming exactly the atom — no loader message.
    let mismatch = beam_rt_eval(Some(&fixture.dir), EXPR_CALL_MISMATCH);
    assert_eq!(
        mismatch.status.code(),
        Some(1),
        "an uncaught `undef` is a genuine runtime error (exit 1) — stderr:\n{}",
        diagnosed(&mismatch)
    );
    assert!(
        mismatch.stdout.is_empty(),
        "the raise prints nothing on stdout: {}",
        String::from_utf8_lossy(&mismatch.stdout)
    );
    assert_eq!(
        diagnosed(&mismatch),
        CALL_UNDEF_STDERR,
        "the reason must be the bare atom `undef`, never the loader's name-check message"
    );
    assert!(
        !diagnosed(&mismatch).contains("module name in object code"),
        "the loader's diagnostic must not be the *call* site's reason"
    );

    // (b) A module with no `.beam` anywhere is the same shape — byte for byte.
    let missing = beam_rt_eval(Some(&fixture.dir), EXPR_CALL_NOFILE);
    assert_eq!(
        missing.status.code(),
        Some(1),
        "the no-file control must also be a runtime error — stderr:\n{}",
        diagnosed(&missing)
    );
    assert!(
        missing.stdout.is_empty(),
        "the no-file control prints nothing on stdout: {}",
        String::from_utf8_lossy(&missing.stdout)
    );
    assert_eq!(
        diagnosed(&missing),
        diagnosed(&mismatch),
        "a name-mismatch refusal and a missing module are the same raise at a call site"
    );

    // … and the oracle's own two rows agree with each other in exactly the same way: exit 1,
    // empty stdout, and a crash report whose reason is `undef` (naming the callee in the
    // trace, where the oracle puts it too).
    for (what, expr, head) in [
        (
            "the name-mismatch image",
            EXPR_CALL_MISMATCH,
            "{undef,[{mismatch,id,[7],[]}",
        ),
        (
            "the absent module",
            EXPR_CALL_NOFILE,
            "{undef,[{nosuchmod_xyz,id,[7],[]}",
        ),
    ] {
        let theirs = oracle_probe(&oracle, &fixture.dir, expr);
        assert_eq!(
            theirs.status.code(),
            Some(1),
            "the oracle must exit 1 for {what} — stderr:\n{}",
            diagnosed(&theirs)
        );
        assert!(
            theirs.stdout.is_empty(),
            "the oracle prints nothing on stdout for {what}: {}",
            String::from_utf8_lossy(&theirs.stdout)
        );
        assert!(
            diagnosed(&theirs).contains(head),
            "the oracle's reason for {what} must be `undef` — it said:\n{}",
            diagnosed(&theirs)
        );
    }

    // The caught form: this runtime's reason is the bare atom `undef` and the one trace item it
    // can honestly contribute is the callee head (`{mismatch,id,[7],[]}`); the oracle's
    // trailing `erl_eval` frames need an `erl_eval` port this runtime does not have, so only the
    // head item is oracle-cross-checked (next), and this row pins our own exact shape.
    let caught = beam_rt_eval(Some(&fixture.dir), EXPR_CALL_MISMATCH_CAUGHT);
    assert_eq!(
        printed(&caught, "the caught name-mismatch call"),
        CALL_MISMATCH_CAUGHT_EXPECTED
    );
    assert_agrees(
        &oracle,
        Some(&fixture.dir),
        EXPR_CALL_MISMATCH_HEAD,
        CALL_MISMATCH_HEAD_EXPECTED,
        "the head trace item of a caught call to an image naming another module",
    );
    assert_agrees(
        &oracle,
        Some(&fixture.dir),
        EXPR_CALL_NOFILE_HEAD,
        CALL_NOFILE_HEAD_EXPECTED,
        "the head trace item of a caught call to a module with no file",
    );

    // (c) No regression: the **matching** name still loads on demand and runs.
    assert_agrees(
        &oracle,
        Some(&fixture.dir),
        EXPR_CALL_MATCHING,
        CALL_MATCHING_EXPECTED,
        "an on-demand call to the module the image really names",
    );

    // The compiled/scheduled route: a `.beam` caller whose own body performs the external call
    // catches the very same reason — `{error,undef}` — for both rows.
    assert_agrees(
        &oracle,
        Some(&fixture.dir),
        EXPR_CALLER_MISMATCH,
        CALLER_EXPECTED,
        "a compiled caller catching the refusal of an image naming another module",
    );
    assert_agrees(
        &oracle,
        Some(&fixture.dir),
        EXPR_CALLER_NOFILE,
        CALLER_EXPECTED,
        "a compiled caller catching a call to a module with no file",
    );

    // (d) The **explicit** load routes keep their oracle-exact values: the call-site mapping
    // touches only the raise, never `code:load_file/1`'s `{error,badfile}`.
    assert_agrees(
        &oracle,
        Some(&fixture.dir),
        EXPR_MISMATCH,
        MISMATCH_EXPECTED,
        "code:load_file/1 of an image whose object code names another module",
    );
}

/// The **`-s`/`-run` action** and the **`M:F/A` spawn**: both *enter* a module rather than
/// returning a load result, so both report the call-site classifier's reason — the bare
/// `undef` — for the name-mismatched image, exactly as they do for a module with no file.
///
/// Measured (OTP 29.1.1 / erts-17.1, re-probed on every run):
///
/// * `-s`/`-run`: both rows exit **1** with empty stdout and the two are indistinguishable;
///   this runtime's one diagnostic line is the CLI convention `beam_rt: error undef` — never
///   the loader's `module name in object code is …`, which only the `code:*` routes see (and
///   fold into `badfile`);
/// * `spawn/3`: the oracle's spawn **succeeds** (it does no loading then) and the child dies
///   with a `{undef, [{mismatch,id,[7],[]}]}` reason; this runtime resolves the entry eagerly,
///   so the same atom surfaces at the spawn. The two agree on the **reason atom** — asserted
///   against the oracle's own `'DOWN'` head — and the residual (where it surfaces) is the
///   documented typed gap on `Runtime::resolve_export_entry`.
#[test]
fn the_action_and_spawn_routes_report_the_same_undef_as_a_call_site() {
    let Some(oracle) = support::require_oracle("code_load_file") else {
        return;
    };
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly("code_load_file", "no `erlc` on $PATH");
        return;
    };
    let Some(fixture) = build_fixture(&erlc) else {
        return;
    };

    // (a) `-s` / `-run` of the mismatching image: exit 1, empty stdout, and the bare `undef`.
    for switch in ["-s", "-run"] {
        let mismatch = beam_rt_action(&fixture.dir, switch, &ACTION_MISMATCH);
        assert_eq!(
            mismatch.status.code(),
            Some(1),
            "beam_rt {switch} of a mismatched image is a runtime error (exit 1) — stderr:\n{}",
            diagnosed(&mismatch)
        );
        assert!(
            mismatch.stdout.is_empty(),
            "beam_rt {switch} of a mismatched image prints nothing on stdout: {}",
            String::from_utf8_lossy(&mismatch.stdout)
        );
        assert_eq!(
            diagnosed(&mismatch),
            CALL_UNDEF_STDERR,
            "the {switch} route's reason must be the bare atom `undef`, never the loader's \
             name-check message"
        );

        // The control: a module with no file at all is the same row, byte for byte.
        let missing = beam_rt_action(&fixture.dir, switch, &ACTION_NOFILE);
        assert_eq!(missing.status.code(), Some(1), "beam_rt {switch} no-file control");
        assert!(
            missing.stdout.is_empty(),
            "beam_rt {switch} no-file control prints nothing on stdout"
        );
        assert_eq!(
            diagnosed(&missing),
            diagnosed(&mismatch),
            "a name-mismatch refusal and a missing module are the same raise on the {switch} \
             route too"
        );

        // The oracle's own two rows agree with each other in exactly the same way: exit 1 and
        // no stdout for both (its crash dump, not stdout, carries the reason).
        let theirs_mismatch = oracle_action(&oracle, &fixture.dir, switch, &ACTION_MISMATCH);
        let theirs_missing = oracle_action(&oracle, &fixture.dir, switch, &ACTION_NOFILE);
        for (what, theirs) in [
            ("the name-mismatch image", &theirs_mismatch),
            ("the absent module", &theirs_missing),
        ] {
            assert_eq!(
                theirs.status.code(),
                Some(1),
                "the oracle must exit 1 for the {switch} row of {what} — stderr:\n{}",
                diagnosed(theirs)
            );
            assert!(
                theirs.stdout.is_empty(),
                "the oracle prints nothing on stdout for the {switch} row of {what}: {}",
                String::from_utf8_lossy(&theirs.stdout)
            );
        }

        // No regression: the module the image really names still runs (its result is
        // discarded, so a successful row is silent on both runtimes and exits 0).
        let matching = beam_rt_action(&fixture.dir, switch, &ACTION_MATCHING);
        assert_eq!(
            matching.status.code(),
            Some(0),
            "beam_rt {switch} of the matching module must succeed — stderr:\n{}",
            diagnosed(&matching)
        );
        let theirs_matching = oracle_action(&oracle, &fixture.dir, switch, &ACTION_MATCHING);
        assert_eq!(
            theirs_matching.status.code(),
            Some(0),
            "the oracle must exit 0 for the {switch} row of the matching module"
        );
    }

    // (b) `spawn(M, F, A)` of the mismatching image: this runtime's reason is the bare `undef`
    // (the same as the no-file control's)…
    let spawn_mismatch = beam_rt_eval(Some(&fixture.dir), EXPR_SPAWN_MISMATCH);
    assert_eq!(
        spawn_mismatch.status.code(),
        Some(1),
        "beam_rt spawn of a mismatched image raises `undef` (exit 1) — stderr:\n{}",
        diagnosed(&spawn_mismatch)
    );
    assert!(
        spawn_mismatch.stdout.is_empty(),
        "the refused spawn prints nothing on stdout: {}",
        String::from_utf8_lossy(&spawn_mismatch.stdout)
    );
    assert_eq!(diagnosed(&spawn_mismatch), CALL_UNDEF_STDERR);
    let spawn_missing = beam_rt_eval(Some(&fixture.dir), EXPR_SPAWN_NOFILE);
    assert_eq!(
        diagnosed(&spawn_missing),
        diagnosed(&spawn_mismatch),
        "a name-mismatch refusal and a missing module are the same raise for an export spawn"
    );

    // … and the oracle's two rows agree with each other too: the spawn succeeds and prints
    // `true` (exit 0) for **both** — the child, not the spawn, carries the `undef`.
    for (what, expr) in [
        ("the name-mismatch image", EXPR_SPAWN_MISMATCH),
        ("the absent module", EXPR_SPAWN_NOFILE),
    ] {
        let theirs = oracle_probe(&oracle, &fixture.dir, expr);
        assert_eq!(
            theirs.status.code(),
            Some(0),
            "the oracle's spawn of {what} must succeed — stderr:\n{}",
            diagnosed(&theirs)
        );
        assert!(
            String::from_utf8_lossy(&theirs.stdout)
                .lines()
                .any(|line| line.trim() == SPAWN_ORACLE_EXPECTED),
            "the oracle's spawn of {what} prints `{SPAWN_ORACLE_EXPECTED}`; it printed:\n{}",
            String::from_utf8_lossy(&theirs.stdout)
        );
    }

    // The reason the oracle's dead child exits with is `{undef, [{M,F,Args,[]}]}` — the same
    // atom this runtime raises, so the **reason** (never the place) is cross-checked here.
    match support::oracle_eval(&oracle, Some(&fixture.dir), EXPR_SPAWN_DOWN_HEAD) {
        Some(theirs) => assert!(
            theirs
                .lines()
                .any(|line| line.trim() == SPAWN_DOWN_HEAD_EXPECTED),
            "the oracle's 'DOWN' reason head must be `{SPAWN_DOWN_HEAD_EXPECTED}`; it printed:\n{theirs}"
        ),
        None => eprintln!("warning: the oracle could not answer the 'DOWN' probe — not compared"),
    }

    // The residual, pinned as *this runtime's* own truthful shape: the entry point is resolved
    // eagerly, so the raise happens **at the spawn** (the oracle's child dies afterwards
    // instead), with the trace head naming the `erlang:spawn/3` call it was.
    let caught = |what: &[&str; 3]| {
        printed(
            &beam_rt_eval(
                Some(&fixture.dir),
                &format!(
                    "io:format(\"~p~n\",[catch spawn({},{},[7])]), halt(0).",
                    what[0], what[1]
                ),
            ),
            "the caught mismatched spawn",
        )
    };
    let mismatch_spawn = caught(&["mismatch", "id", "7"]);
    assert_eq!(
        mismatch_spawn,
        "{'EXIT',{undef,[{erlang,spawn,[mismatch,id,[7]],[]}]}}",
        "the refused spawn's reason is the bare atom `undef`"
    );
    // The control is the same raise — `undef`, class `error`, the callee's own args in the one
    // trace item — and differs only in the module name the call mentioned.
    assert_eq!(
        caught(&["nosuchmod_xyz", "id", "7"]),
        "{'EXIT',{undef,[{erlang,spawn,[nosuchmod_xyz,id,[7]],[]}]}}",
        "a module with no file is the same raise at an export spawn"
    );
}