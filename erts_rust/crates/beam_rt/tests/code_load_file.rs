/// The compiled fixture in one scratch directory (removed on drop).
struct Fixture {
    /// Holds `mymod.erl`/`mymod.beam` and the corrupt `bogus.beam`; a safe single `-pa` (it
    /// contains no `lists.beam`).
    dir: PathBuf,
}

impl Drop for Fixture {
    fn drop(&mut self) {
        if let Err(error) = std::fs::remove_dir_all(&self.dir) {
            eprintln!(
                "warning: could not remove the fixture dir {}: {error}",
                self.dir.display()
            );
        }
    }
}

/// The compiler: a sibling of the resolved oracle first (the same installation), then
/// `$PATH`.
fn resolve_erlc() -> Option<PathBuf> {
    if let Some(dir) = support::resolve_oracle().as_deref().and_then(Path::parent) {
        let candidate = dir.join("erlc");
        if support::is_executable(&candidate) {
            return Some(candidate);
        }
    }
    support::find_on_path("erlc")
}

/// The scratch directory of **one** `build_fixture` call.
///
/// Unique per call: two tests in this suite can hold their own fixtures at the same time, and a
/// shared `{pid}`-only name would let one test's `Drop` delete the other's directory mid-run
/// (which surfaces as a spurious `{error,nofile}`).
fn fixture_dir() -> PathBuf {
    static SEQUENCE: AtomicU64 = AtomicU64::new(0);
    let sequence = SEQUENCE.fetch_add(1, Ordering::Relaxed);
    std::env::temp_dir().join(format!(
        "beam_rt_code_load_file_{}_{sequence}",
        std::process::id()
    ))
}

/// Compiles the fixture (and writes the corrupt `bogus.beam`) into a fresh scratch
/// directory, or `None` after a loud skip when the toolchain cannot do it.
fn build_fixture(erlc: &Path) -> Option<Fixture> {
    let dir = fixture_dir();
    // A stale directory from a killed run must not decide the result: start clean.
    match std::fs::remove_dir_all(&dir) {
        Ok(()) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => {
            support::skip_loudly(
                "code_load_file",
                &format!("cannot clear {}: {error}", dir.display()),
            );
            return None;
        }
    }
    if let Err(error) = std::fs::create_dir_all(&dir) {        support::skip_loudly(
            "code_load_file",
            &format!("cannot prepare {}: {error}", dir.display()),
        );
        return None;
    }
    let source = dir.join("mymod.erl");
    if let Err(error) = std::fs::write(&source, FIXTURE_ERL) {
        support::skip_loudly(
            "code_load_file",
            &format!("cannot write {}: {error}", source.display()),
        );
        return None;
    }
    // The caller whose own body calls the two absent modules: the **compiled** route's proof
    // that an on-demand load refusal is the oracle's `{error,undef}` there too. `erlc` warns
    // (undefined function) and still compiles — the call is exactly what must be measured.
    let caller = dir.join("mismatch_caller.erl");
    if let Err(error) = std::fs::write(&caller, CALLER_ERL) {
        support::skip_loudly(
            "code_load_file",
            &format!("cannot write {}: {error}", caller.display()),
        );
        return None;
    }
    let output = match Command::new(erlc)
        .arg("-o")
        .arg(&dir)
        .arg(&source)
        .arg(&caller)
        .output()
    {
        Ok(output) => output,
        Err(error) => {
            support::skip_loudly("code_load_file", &format!("cannot run `erlc`: {error}"));
            return None;
        }
    };
    if !output.status.success() {
        support::skip_loudly(
            "code_load_file",
            &format!("`erlc` exited with {}", output.status),
        );
        return None;
    }
    if !dir.join("mymod.beam").is_file() {
        support::skip_loudly("code_load_file", "`erlc` produced no mymod.beam");
        return None;
    }
    if !dir.join("mismatch_caller.beam").is_file() {
        support::skip_loudly("code_load_file", "`erlc` produced no mismatch_caller.beam");
        return None;
    }
    // A found-but-corrupt image: `code:load_file/1` must answer the oracle's `{error,badfile}`
    // rather than the `{error,nofile}` of a missing file or a fabricated reason.
    if let Err(error) = std::fs::write(dir.join("bogus.beam"), b"garbage-not-a-beam") {
        support::skip_loudly(
            "code_load_file",
            &format!("cannot write bogus.beam: {error}"),
        );
        return None;
    }
    // A **well-formed** image under a name its object code does not carry: `mismatch.beam` is
    // `mymod`'s own bytes, so the loader's expected-name check is the only thing that can
    // refuse it (never a malformed container, never a missing file).
    match std::fs::read(dir.join("mymod.beam")) {
        Ok(image) => {
            if let Err(error) = std::fs::write(dir.join("mismatch.beam"), &image) {
                support::skip_loudly(
                    "code_load_file",
                    &format!("cannot write mismatch.beam: {error}"),
                );
                return None;
            }
        }
        Err(error) => {
            support::skip_loudly(
                "code_load_file",
                &format!("cannot read mymod.beam back: {error}"),
            );
            return None;
        }
    }
    Some(Fixture { dir })
}
