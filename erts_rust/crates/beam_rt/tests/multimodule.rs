//! The **multi-module** end-to-end host test: a compiled fixture that calls *other*
//! modules.
//!
//! `tests/slice.rs` runs one self-contained module; this test exercises the part of
//! `beam_rt` that only exists because a real BEAM is not one module: the load-on-demand
//! dispatch of [`RuntimeContext`](beam_rt::RuntimeContext), which serves
//!
//! 1. the **runtime-native floor** (`halt`, `display`, `io:put_chars`, `apply`,
//!    `init:get_argument`) — `native.rs`,
//! 2. the **`beam_bifs` registry** (the `bif.tab` surface: `lists:reverse/1`,
//!    `maps:get/2`, `io:format/2`, …), and
//! 3. a **real system stdlib module**, loaded on demand from the code path and executed
//!    on the *same* heap and the *same* atom table.
//!
//! The fixture is compiled at test time with the system `erlc` into a scratch directory,
//! so nothing path-dependent is committed and the source of truth stays the `.erl` in
//! this file. It needs a system Erlang twice over (the compiler, and the stdlib module
//! the fixture calls), so when either is unavailable the test **skips loudly** — it never
//! silently passes.
//!
//! Ground truth for the expected output is the real system ERTS (`erl`/`erlc`, OTP 29 /
//! `erts-17.1`, the differential oracle): `multimod:reverse/0` is `[3,2,1]`,
//! `multimod:lookup/0` is `7`, `multimod:binpart/0` is `<<2,3>>` and `multimod:demo/0`
//! prints `[3,2,1]\n7\n`.
use std::path::PathBuf;
use std::process::Command;

use beam_bifs::BytesSink;
use beam_loader::load_file;
use beam_rt::{ArgTerm, CodeServer, Runtime, RuntimeConfig};
use beam_term::signed_value;

/// The fixture source.
///
/// Every export is a thin wrapper around a *different* kind of callee, so one run
/// proves all three dispatch routes:
///
/// * `reverse/0` → `lists:reverse/1`, a **`beam_bifs` registry BIF**;
/// * `lookup/0` → `maps:get/2` on a **map literal** (so the module's `LitT` area is
///   decoded and reached);
/// * `sorted/1` → `ordsets:from_list/1` + `ordsets:to_list/1`, a **real system stdlib
///   module** (not a BIF) that must be loaded from the code path and executed;
/// * `binpart/0` → `binary:part/3`, a **real system stdlib module** operation over a
///   binary literal, proving binary-term dispatch across the module boundary;
/// * `demo/0` → the registered `io:format/2` printer, whose output this test captures.
const FIXTURE_ERL: &str = r#"%% Generated by `beam_rt/tests/multimodule.rs` (never committed).
-module(multimod).
-export([reverse/0, lookup/0, sorted/1, binpart/0, demo/0]).
reverse() -> lists:reverse([1, 2, 3]).
lookup() -> maps:get(a, #{a => 7}).
sorted(L) -> ordsets:to_list(ordsets:from_list(L)).
binpart() -> binary:part(<<1, 2, 3, 4>>, 1, 2).
demo() ->
    io:format("~w~n", [reverse()]),
    io:format("~w~n", [lookup()]),
    ok.
"#;

/// A compiled fixture in its own scratch directory.
struct Fixture {
    /// The scratch directory holding `multimod.erl`/`multimod.beam`.
    dir: PathBuf,
    /// The compiled `multimod.beam`.
    beam: PathBuf,
}

impl Fixture {
    /// Removes the scratch directory (`erlc` output is not source).
    fn cleanup(self) {
        match std::fs::remove_dir_all(&self.dir) {
            Ok(()) => {}
            // The directory is ours and disposable; a failure is reported, not hidden.
            Err(error) => println!("note: could not remove {}: {error}", self.dir.display()),
        }
    }
}

/// Compiles the fixture, or `None` when the system toolchain is unavailable (the caller
/// then returns early — **loudly**).
fn build_fixture(label: &str) -> Option<Fixture> {
    let dir = std::env::temp_dir().join(format!(
        "beam_rt_multimodule_{label}_{}",
        std::process::id()
    ));
    if let Err(error) = std::fs::create_dir_all(&dir) {
        println!("SKIP multimodule: cannot create {}: {error}", dir.display());
        return None;
    }
    let source = dir.join("multimod.erl");
    if let Err(error) = std::fs::write(&source, FIXTURE_ERL) {
        println!("SKIP multimodule: cannot write {}: {error}", source.display());
        return None;
    }
    let output = match Command::new("erlc").arg("-o").arg(&dir).arg(&source).output() {
        Ok(output) => output,
        Err(error) => {
            println!("SKIP multimodule: cannot run `erlc`: {error}");
            return None;
        }
    };
    if !output.status.success() {
        println!(
            "SKIP multimodule: `erlc` exited with {}: {}",
            output.status,
            String::from_utf8_lossy(&output.stderr)
        );
        return None;
    }
    let beam = dir.join("multimod.beam");
    if !beam.is_file() {
        println!("SKIP multimodule: `erlc` produced no {}", beam.display());
        return None;
    }
    Some(Fixture { dir, beam })
}

/// Whether the system stdlib is resolvable; prints the reason (and returns `false`)
/// when it is not.
///
/// The fixture's `sorted/1` needs the real `<stdlib>/ebin/ordsets.beam`, so the whole
/// test is meaningless without it.
fn system_stdlib_available() -> bool {
    let mut server = CodeServer::new();
    match server.add_system_paths() {
        Ok(()) if server.find_file("lists").is_some() => true,
        Ok(()) => {
            println!("SKIP multimodule: the system code path holds no lists.beam");
            false
        }
        Err(error) => {
            println!("SKIP multimodule: no system stdlib ({error})");
            false
        }
    }
}

/// A runtime over the default configuration (no code path: resolution falls back to the
/// system stdlib, which is what proves the load-on-demand path).
fn runtime() -> Runtime {
    Runtime::new(RuntimeConfig::default()).expect("the default runtime")
}

#[test]
fn a_compiled_module_runs_across_modules() {
    if !system_stdlib_available() {
        return;
    }
    let Some(fixture) = build_fixture("runs") else {
        return;
    };
    let mut runtime = runtime();

    // 1. A `beam_bifs` BIF: `lists:reverse([1,2,3])`.
    let reversed = runtime
        .run_function(&fixture.beam, "reverse", 0, &[])
        .expect("multimod:reverse/0");
    assert_eq!(
        runtime.format_term_w(reversed, None).expect("printable"),
        "[3,2,1]\n"
    );

    // 2. `maps:get(a, #{a => 7})`, with the map coming from the module's literal area.
    let seven = runtime
        .run_function(&fixture.beam, "lookup", 0, &[])
        .expect("multimod:lookup/0");
    assert_eq!(signed_value(seven), 7);

    // 3. A real system stdlib module (`ordsets`), loaded on demand and executed.
    let unsorted = runtime
        .materialize_args(&[ArgTerm::List(vec![
            ArgTerm::Int(3),
            ArgTerm::Int(1),
            ArgTerm::Int(2),
        ])])
        .expect("materialize [3,1,2]");
    let sorted = runtime
        .run_function(&fixture.beam, "sorted", 1, &unsorted)
        .expect("multimod:sorted/1");
    assert_eq!(
        runtime.format_term_w(sorted, None).expect("printable"),
        "[1,2,3]\n"
    );

    fixture.cleanup();
}

/// A `binary`-module operation over a binary literal, dispatched across the module
/// boundary onto the same atom table and heap.
///
/// Oracle: `erl -noshell -eval 'io:format("~w~n",[binary:part(<<1,2,3,4>>,1,2)]),halt(0).'`
/// prints `<<2,3>>`.
#[test]
fn a_compiled_module_calls_the_binary_module() {
    if !system_stdlib_available() {
        return;
    }
    let Some(fixture) = build_fixture("binary") else {
        return;
    };
    let mut runtime = runtime();
    let part = runtime
        .run_function(&fixture.beam, "binpart", 0, &[])
        .expect("multimod:binpart/0");
    assert_eq!(
        runtime.format_term_w(part, None).expect("printable"),
        "<<2,3>>\n"
    );

    fixture.cleanup();
}

#[test]
fn the_module_prints_through_the_registered_io_format() {
    if !system_stdlib_available() {
        return;
    }
    let Some(fixture) = build_fixture("prints") else {
        return;
    };
    let mut runtime = runtime();
    // An explicitly loaded image with a caller-owned output sink: `io:format` output is
    // captured instead of going to stdout.
    let image = load_file(&fixture.beam).expect("load multimod.beam");
    let mut sink = BytesSink::new();
    runtime
        .run_module(&image, "demo", 0, &[], &mut sink)
        .expect("multimod:demo/0");
    // The oracle: `io:format("~w~n",[lists:reverse([1,2,3])])` then
    // `io:format("~w~n",[maps:get(a,#{a => 7})])`.
    assert_eq!(sink.as_str(), "[3,2,1]\n7\n");

    fixture.cleanup();
}

#[test]
fn a_missing_export_in_the_fixture_raises_undef() {
    if !system_stdlib_available() {
        return;
    }
    let Some(fixture) = build_fixture("missing") else {
        return;
    };
    let mut runtime = runtime();
    let error = runtime
        .run_function(&fixture.beam, "nope", 0, &[])
        .expect_err("not exported");
    // The oracle raises `exception error undef` for a missing function, not a message.
    assert_eq!(error.as_atom(), Some("undef"), "{error}");

    fixture.cleanup();
}