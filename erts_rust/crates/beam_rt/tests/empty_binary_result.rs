//! A program whose result is a **zero-length binary** must print `<<>>` (contract A.6:
//! the `run` action prints its result with `~w~n`).
//!
//! Whether it does depends on the binary's **representation**, not on its value:
//!
//! * An empty binary built **on-heap** works. A `<<>>` literal (`lit/0`),
//!   `binary:copy(<<7>>, 0)` (`copied/0`) and `binary:part(<<1,2,3>>, 0, 0)` (`part/0`) are
//!   all plain on-heap binaries, and `beam_rt run … emptybinres:<f>/0` prints `<<>>\n`
//!   with exit `0` — exactly the oracle. **Test A** below pins this (it passes today).
//! * An empty binary produced by a **`bs_init_writable` accumulator** is an **off-heap
//!   refc binary** (`[BinRef][ErlSubBits]`), which is what `base64:encode/1` returns even
//!   for its zero-length input. `beam_rt run … emptybinres:b64reported/1 7` prints
//!   `beam_rt: badarg` with exit `1`, where the oracle prints `<<>>\n` with exit `0`.
//!   **Test B** is that defect, and it is `#[ignore]`d — see the note on it.
//!
//! # Why Test B is ignored (root cause — it is in READ-ONLY sibling crates)
//!
//! The CLI renders a `run` result through `beam_rt/src/runtime.rs::stabilize_term`, which
//! copies the returned term onto the pointer-stable arena with
//! `beam_message::copy_struct_simple`. That shared entry copies against **empty** off-heap
//! tables, so `beam_message/src/copy.rs::copy_refc_binary` cannot resolve the refc
//! payload's backing store (`binary_by_data_ptr` misses) and returns `bad_term()`
//! (`BeamError::BadArg`) — the `badarg` the CLI prints.
//!
//! The fix is a self-contained ("flatten") copy mode in `beam_message` plus a one-line
//! adoption in `beam_rt/src/runtime.rs::stabilize_term`. The `beam_message` half is read-only
//! to this node, and the adopting call cannot compile until that entry point exists, so the
//! test is marked `#[ignore]` with that reason and must be un-ignored when the fix lands
//! (the `beam_rt` half is the single `copy_struct_simple` call in `stabilize_term`).
//!
//! The fixture is compiled **at test time** with the system `erlc` into a scratch directory
//! under the system temp dir (never committed), and every test **skips loudly** — never
//! silently passes — when the compiler or the oracle is unavailable.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

mod support;

/// The fixture source: three on-heap empty-binary builders, plus the two `base64:encode/1`
/// ones whose result is an off-heap refc binary (`b64reported/1` is parameterized so its
/// zero-length input is built at run time, never folded to a literal).
const FIXTURE_ERL: &str = r#"%% Generated by `beam_rt/tests/empty_binary_result.rs` (never committed).
-module(emptybinres).
-export([lit/0, copied/0, part/0, b64empty/0, b64reported/1]).

lit()         -> <<>>.
copied()      -> binary:copy(<<7>>, 0).
part()        -> binary:part(<<1, 2, 3>>, 0, 0).
b64empty()    -> base64:encode(<<>>).
b64reported(A)-> base64:encode(binary:copy(<<A>>, 0)).
"#;

/// The on-heap fixtures: `(label, function, oracle expression)`.
///
/// Each oracle expression builds the **same** value the fixture returns and prints it with
/// `io:format("~w~n", …)`, then halts — the exact rendering the `run` action performs.
const ON_HEAP: [(&str, &str, &str); 3] = [
    (
        "a <<>> literal",
        "lit",
        "io:format(\"~w~n\", [<<>>]), halt(0).",
    ),
    (
        "binary:copy(<<7>>, 0)",
        "copied",
        "io:format(\"~w~n\", [binary:copy(<<7>>, 0)]), halt(0).",
    ),
    (
        "binary:part(<<1,2,3>>, 0, 0)",
        "part",
        "io:format(\"~w~n\", [binary:part(<<1, 2, 3>>, 0, 0)]), halt(0).",
    ),
];

/// The oracle expression for `b64reported(7)` — it needs the fixture on the code path.
const B64_REPORTED_EXPR: &str = "io:format(\"~w~n\", [emptybinres:b64reported(7)]), halt(0).";

// ---------------------------------------------------------------------------------------
// The compiled fixture
// ---------------------------------------------------------------------------------------

/// The compiled fixture in one scratch directory (removed on drop).
struct Fixture {
    /// The scratch directory holding `emptybinres.erl`/`emptybinres.beam`; a safe single
    /// `-pa` for the oracle (it contains no `lists.beam`).
    dir: PathBuf,
    /// The compiled `emptybinres.beam`.
    beam: PathBuf,
}

impl Drop for Fixture {
    fn drop(&mut self) {
        if let Err(error) = std::fs::remove_dir_all(&self.dir) {
            eprintln!(
                "warning: could not remove the fixture dir {}: {error}",
                self.dir.display()
            );
        }
    }
}

/// The compiler: a sibling of the resolved oracle first (the same installation), then
/// `$PATH`.
fn resolve_erlc() -> Option<PathBuf> {
    if let Some(dir) = support::resolve_oracle().as_deref().and_then(Path::parent) {
        let candidate = dir.join("erlc");
        if support::is_executable(&candidate) {
            return Some(candidate);
        }
    }
    support::find_on_path("erlc")
}

/// Compiles the fixture into a fresh scratch directory, or `None` after a loud skip when the
/// system toolchain cannot do it.
fn build_fixture(label: &str, erlc: &Path) -> Option<Fixture> {
    let dir = std::env::temp_dir().join(format!(
        "beam_rt_empty_binary_{label}_{}",
        std::process::id()
    ));
    if let Err(error) = std::fs::create_dir_all(&dir) {
        support::skip_loudly(
            "empty binary result",
            &format!("cannot prepare {}: {error}", dir.display()),
        );
        return None;
    }
    let source = dir.join("emptybinres.erl");
    if let Err(error) = std::fs::write(&source, FIXTURE_ERL) {
        support::skip_loudly(
            "empty binary result",
            &format!("cannot write {}: {error}", source.display()),
        );
        return None;
    }
    let output = match Command::new(erlc).arg("-o").arg(&dir).arg(&source).output() {
        Ok(output) => output,
        Err(error) => {
            support::skip_loudly(
                "empty binary result",
                &format!("cannot run `erlc`: {error}"),
            );
            return None;
        }
    };
    if !output.status.success() {
        support::skip_loudly(
            "empty binary result",
            &format!("`erlc` exited with {}", output.status),
        );
        return None;
    }
    let beam = dir.join("emptybinres.beam");
    if !beam.is_file() {
        support::skip_loudly("empty binary result", "`erlc` produced no emptybinres.beam");
        return None;
    }
    Some(Fixture { dir, beam })
}

// ---------------------------------------------------------------------------------------
// Running the two runtimes
// ---------------------------------------------------------------------------------------

/// Runs the built `beam_rt` binary with `args`.
fn beam_rt(args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_beam_rt"))
        .args(args)
        .output()
        .unwrap_or_else(|error| panic!("spawning beam_rt {args:?} failed: {error}"))
}

/// Runs `emptybinres:<function>/<arity>` (with `args`) through the built binary's `run`
/// action.
fn run_fixture(beam: &Path, spec: &str, args: &[&str]) -> Output {
    let beam = beam.to_str().expect("the fixture path is UTF-8");
    let mut argv: Vec<&str> = vec!["run", beam, spec];
    argv.extend_from_slice(args);
    beam_rt(&argv)
}

/// The stdout of a finished run, as text.
fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

/// The stderr of a finished run, as text.
fn stderr(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).into_owned()
}

/// Asserts `output` is a **successful** rendering of `<<>>` and returns nothing: exit `0`,
/// stdout exactly `"<<>>\n"` and an empty stderr.
fn assert_prints_empty_binary(output: &Output, what: &str) {
    assert_eq!(
        output.status.code(),
        Some(0),
        "{what}: `beam_rt run …` must exit 0, stderr — {}",
        stderr(output)
    );
    assert_eq!(stdout(output), "<<>>\n", "{what}: beam_rt's stdout");
    assert!(
        output.stderr.is_empty(),
        "{what}: successful `run` must be silent on stderr — {}",
        stderr(output)
    );
}

// ---------------------------------------------------------------------------------------
// Test A — the on-heap empty binary (passes today)
// ---------------------------------------------------------------------------------------

/// A `<<>>` literal, `binary:copy(<<7>>, 0)` and `binary:part(<<1,2,3>>, 0, 0)` all print
/// `<<>>` — through this runtime's CLI **and** the system oracle.
#[test]
fn an_on_heap_empty_binary_prints_as_a_binary() {
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly("empty binary result", "no `erlc` on $PATH");
        return;
    };
    let Some(oracle) = support::require_oracle("empty binary result") else {
        return;
    };
    let Some(fixture) = build_fixture("on_heap", &erlc) else {
        return;
    };

    for (label, function, expr) in ON_HEAP {
        let spec = format!("emptybinres:{function}/0");
        let output = run_fixture(&fixture.beam, &spec, &[]);
        assert_prints_empty_binary(&output, label);

        // `support::oracle_eval` **trims** the probe's stdout, so the oracle's `"<<>>\n"` is
        // compared as `"<<>>"`.
        let Some(theirs) = support::oracle_eval(&oracle, Some(&fixture.dir), expr) else {
            eprintln!("warning: the oracle could not answer `{label}` — not compared");
            continue;
        };
        assert_eq!(theirs, "<<>>", "{label}: the system erl's rendering");
    }
}

// ---------------------------------------------------------------------------------------
// Test B — the off-heap refc empty binary (the reported defect, ignored)
// ---------------------------------------------------------------------------------------

/// An empty binary that is an **off-heap refc binary** — `base64:encode/1`'s result — is
/// rejected by the CLI (`beam_rt: badarg`, exit 1) instead of printing `<<>>`.
///
/// The oracle prints `<<>>` for it. `beam_rt` cannot, because
/// `beam_rt/src/runtime.rs::stabilize_term` copies the result with
/// `beam_message::copy_struct_simple`, whose empty off-heap tables make
/// `beam_message/src/copy.rs::copy_refc_binary` return `bad_term()`. The fix (a
/// self-contained flatten copy in `beam_message` + a one-line adoption in `runtime.rs`) is
/// outside this crate's scope, so this test is ignored until it lands.
#[test]
#[ignore = "beam_message::copy_struct_simple cannot copy an off-heap refc binary (beam_message/src/copy.rs:487) — a self-contained flatten copy + the one-line adoption in beam_rt/src/runtime.rs::stabilize_term are needed; un-ignore when they land"]
fn an_off_heap_refc_empty_binary_prints_as_a_binary() {
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly("empty binary result", "no `erlc` on $PATH");
        return;
    };
    let Some(oracle) = support::require_oracle("empty binary result") else {
        return;
    };
    let Some(fixture) = build_fixture("refc", &erlc) else {
        return;
    };

    // `base64:encode(binary:copy(<<7>>, 0))` — an off-heap refc binary holding no bytes.
    let output = run_fixture(&fixture.beam, "emptybinres:b64reported/1", &["7"]);
    assert_prints_empty_binary(&output, "base64:encode/1 of an empty binary");

    // The oracle needs the fixture on the code path (`-pa <scratch dir>`) so it can call
    // `emptybinres:b64reported/1` itself; its rendering is compared as `"<<>>"` because
    // `support::oracle_eval` trims the probe's stdout.
    let Some(theirs) = support::oracle_eval(&oracle, Some(&fixture.dir), B64_REPORTED_EXPR) else {
        eprintln!("warning: the oracle could not answer the refc binary — not compared");
        return;
    };
    assert_eq!(
        theirs, "<<>>",
        "base64:encode/1: the system erl's rendering"
    );
}
