//! **`enif_binary_to_term`'s consumed-byte count**, end to end through a real C NIF.
//!
//! The C entry point ends in `return bp - data` (`erts/emulator/beam/erl_nif.c:1543`): it decodes
//! the **first** term of the image and answers how many **source bytes** that term occupied. An
//! External Term Format image is allowed to carry bytes after the encoded term, so the answer for
//! `term_to_binary(42)` with four junk bytes appended is `3` — *smaller* than the slice the NIF is
//! handed.
//!
//! That count is the `used` out-parameter's only observer, so it can only be pinned through the
//! `enif_*` ABI: a hook returning the slice length looks identical in every other respect. The
//! fixture below is a NIF function that takes a binary, calls
//! `enif_binary_to_term(env, bytes, len, &term, 0)` and answers `{Used, Term}`; `used == 0` is the
//! C's failure answer, so a host whose decoder strict-checks trailing bytes answers `{0, undefined}`
//! where the oracle answers `{3, 42}`.
//!
//! Everything is real: the `.c` is compiled with the host C compiler against the host `erl_nif.h`,
//! the `.erl` with the host `erlc`, and both are driven through **the built binary**
//! ([`CARGO_BIN_EXE_beam_rt`]) exactly as a user would. The *same* `.so`/`.beam` are then run under
//! the system `erl`, and its answer is the asserted reference.
//!
//! # Skip policy
//!
//! The three host facilities (the C compiler, the host `erl_nif.h`, the host `erlc`) are needed for
//! the Rust-side run; the system `erl` additionally for the cross-check. A missing facility prints a
//! **loud** banner and returns — never a silent pass.
//!
//! # Why the fixture needs an external caller
//!
//! A NIF replaces the Erlang stub only when the runtime **dispatches an external call**
//! (`call_ext`), so `bin_caller` calls `bin_nif:used/1` from another module; a local call inside
//! `bin_nif` itself would never reach the runtime's NIF dispatch.
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::{Duration, Instant};

/// The NIF fixture: `used/1` decodes an image and answers `{ConsumedBytes, Term}`.
///
/// `enif_inspect_binary` refuses a term that is not a binary, and both failure modes answer the C's
/// own sentinel (`{0, undefined-related atom}`) so a divergence is visible in stdout rather than as a
/// crash. The tuple is built through `enif_make_tuple_from_array` — `enif_make_tuple2` is a
/// **variadic** `enif_make_tuple` in the header, and this ABI implements the array form only.
const BIN_NIF_C: &str = r#"
#include <erl_nif.h>
static ERL_NIF_TERM used(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    ErlNifBinary bin;
    ERL_NIF_TERM term, out[2];
    size_t consumed;
    (void) argc;
    out[0] = enif_make_int(env, 0);
    if (!enif_inspect_binary(env, argv[0], &bin)) {
        out[1] = enif_make_atom(env, "not_a_binary");
        return enif_make_tuple_from_array(env, out, 2);
    }
    consumed = enif_binary_to_term(env, bin.data, bin.size, &term, 0);
    if (consumed == 0) {
        out[1] = enif_make_atom(env, "undecodable");
        return enif_make_tuple_from_array(env, out, 2);
    }
    out[0] = enif_make_ulong(env, (unsigned long) consumed);
    out[1] = term;
    return enif_make_tuple_from_array(env, out, 2);
}
static int load(ErlNifEnv* env, void** priv, ERL_NIF_TERM info) {
    (void) env; (void) info;
    *priv = NULL;
    return 0;
}
static ErlNifFunc bin_nif_funcs[] = {
    {"used", 1, used, 0}
};
ERL_NIF_INIT(bin_nif, bin_nif_funcs, load, NULL, NULL, NULL)
"#;

/// The NIF module whose stub `used/1` the library replaces.
const BIN_NIF_ERL: &str = r#"%% Generated by `beam_rt/tests/nif_binary_to_term_used.rs` (never committed).
-module(bin_nif).
-export([init/1, used/1]).
init(Path) -> erlang:load_nif(Path, 0).
used(_Image) -> erlang:nif_error(not_loaded).
"#;

/// The caller: every export reaches the NIF through an **external** call.
///
/// `trailing/1` is the discriminating case — an image with four junk bytes after a complete term
/// (`++` concatenates **lists**, not binaries, so the image is spliced with a segment).
/// `exact/1` is its control: the same 3-byte image with nothing appended, so the count and the slice
/// length coincide and only the trailing case can reveal a strict decoder.
/// `truncated/1` is the failure half: a term whose byte is missing must answer `0` (never a partial
/// term), which the oracle does too.
const BIN_CALLER_ERL: &str = r#"%% Generated by `beam_rt/tests/nif_binary_to_term_used.rs` (never committed).
-module(bin_caller).
-export([trailing/1, exact/1, truncated/1]).
trailing(Path) -> ok = bin_nif:init(Path), bin_nif:used(<<(term_to_binary(42))/binary, "junk">>).
exact(Path) -> ok = bin_nif:init(Path), bin_nif:used(term_to_binary(42)).
truncated(Path) -> ok = bin_nif:init(Path), bin_nif:used(<<131, 97>>).
"#;

/// The bound on one child run (the runtime boots (~0.35 s) and runs one NIF call).
const RUN_TIMEOUT: Duration = Duration::from_secs(60);

/// Print a loud skip banner (never a silent pass).
fn skip(reason: &str) {
    println!("================================================================");
    println!("SKIP: {reason}");
    println!("================================================================");
}

// ---------------------------------------------------------------------------------------------
// Locating the host `erl_nif.h`
// ---------------------------------------------------------------------------------------------
/// The header the include-directory search keys on.
const HEADER: &str = "erl_nif.h";

/// True when `dir` holds a readable `erl_nif.h`.
fn has_header(dir: &Path) -> bool {
    dir.join(HEADER).is_file()
}

/// The first `erl` executable on `PATH` (filesystem discovery only — the tool is never run to find
/// itself).
fn which_erl() -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|dir| dir.join("erl"))
        .find(|candidate| candidate.is_file())
}

/// The first `erlc` executable on `PATH`.
fn which_erlc() -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|dir| dir.join("erlc"))
        .find(|candidate| candidate.is_file())
}

/// Canonicalize the `erl` on `PATH` and take the sibling `include` of its `erts-*` directory.
fn from_path_erl() -> Option<PathBuf> {
    let erl = which_erl()?.canonicalize().ok()?;
    let bin = erl.parent()?;
    let erts = bin.parent()?;
    if bin.file_name()? != "bin" || !erts.file_name()?.to_string_lossy().starts_with("erts-") {
        return None;
    }
    let include = erts.join("include");
    has_header(&include).then_some(include)
}

/// Search one installation root for an include directory holding `erl_nif.h`.
fn search_root(root: &Path) -> Option<PathBuf> {
    let direct = root.join("include");
    if has_header(&direct) {
        return Some(direct);
    }
    let lib_erlang = root.join("lib").join("erlang");
    for base in [root.to_path_buf(), lib_erlang.clone()] {
        let Ok(entries) = std::fs::read_dir(&base) else {
            continue;
        };
        for entry in entries.flatten() {
            if !entry.file_name().to_string_lossy().starts_with("erts-") {
                continue;
            }
            let include = entry.path().join("include");
            if has_header(&include) {
                return Some(include);
            }
        }
    }
    let include = lib_erlang.join("include");
    has_header(&include).then_some(include)
}

/// Locate the host `erl_nif.h` include directory, robustly; `None` if unavailable.
///
/// Resolution order (the first directory that actually contains a readable `erl_nif.h` wins): the
/// `erts-*` sibling of the `erl` on `PATH`; then `$ERL_TOP`; then the standard installation roots.
fn erl_include_dir() -> Option<PathBuf> {
    from_path_erl().or_else(|| {
        let mut roots = Vec::new();
        if let Some(top) = std::env::var_os("ERL_TOP") {
            roots.push(PathBuf::from(top));
        }
        for base in [
            "/usr/lib/erlang",
            "/usr/local/lib/erlang",
            "/usr/lib64/erlang",
            "/opt/erlang",
        ] {
            roots.push(PathBuf::from(base));
        }
        roots.into_iter().find_map(|root| search_root(&root))
    })
}

// ---------------------------------------------------------------------------------------------
// The compiled fixture
// ---------------------------------------------------------------------------------------------
/// The C compiler to use: `$CC` when set, else `cc`.
fn cc() -> String {
    std::env::var("CC").unwrap_or_else(|_| "cc".to_string())
}

/// Whether a C compiler is available.
fn cc_available() -> bool {
    Command::new(cc())
        .arg("--version")
        .output()
        .map(|output| output.status.success())
        .unwrap_or(false)
}

/// A compiled NIF module + its caller, in one scratch directory that is removed on cleanup.
struct Fixture {
    /// The scratch directory holding the sources and the compiled artifacts.
    dir: PathBuf,
    /// The compiled `bin_caller.beam` (the `run` file argument).
    caller: PathBuf,
}

impl Fixture {
    /// Removes the scratch directory (`cc`/`erlc` output is not source).
    fn cleanup(self) {
        match std::fs::remove_dir_all(&self.dir) {
            Ok(()) => {}
            // The directory is ours and disposable; a failure is reported, not hidden.
            Err(error) => println!("note: could not remove {}: {error}", self.dir.display()),
        }
    }

    /// The path handed to `erlang:load_nif/2` (the `.so` **without** its suffix — the loader
    /// appends `.so`).
    fn load_path(&self) -> PathBuf {
        self.dir.join("bin_nif")
    }
}

/// Compiles the fixture (`bin_nif.so` + `bin_nif.beam` + `bin_caller.beam`) into a scratch
/// directory, or `None` when a host facility is missing (the caller then returns early —
/// **loudly**).
fn build_fixture() -> Option<Fixture> {
    let Some(include) = erl_include_dir() else {
        skip("binary_to_term_used: no erl_nif.h include directory found");
        return None;
    };
    if !cc_available() {
        skip(&format!(
            "binary_to_term_used: no C compiler ({} / $CC) available",
            cc()
        ));
        return None;
    }
    let Some(erlc) = which_erlc() else {
        skip("binary_to_term_used: no `erlc` on PATH");
        return None;
    };
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let dir = std::env::temp_dir().join(format!("beam_rt_nif_bin_used_{}_{n}", std::process::id()));
    let c_src = dir.join("bin_nif.c");
    let erl_nif = dir.join("bin_nif.erl");
    let erl_caller = dir.join("bin_caller.erl");
    if let Err(error) = std::fs::create_dir_all(&dir)
        .and_then(|()| std::fs::write(&c_src, BIN_NIF_C))
        .and_then(|()| std::fs::write(&erl_nif, BIN_NIF_ERL))
        .and_then(|()| std::fs::write(&erl_caller, BIN_CALLER_ERL))
    {
        skip(&format!(
            "binary_to_term_used: cannot prepare {}: {error}",
            dir.display()
        ));
        return None;
    }
    // The shared object: `cc -shared -fPIC -I<include> -o <dir>/bin_nif.so <dir>/bin_nif.c`.
    let output = Command::new(cc())
        .arg("-shared")
        .arg("-fPIC")
        .arg(format!("-I{}", include.display()))
        .arg("-o")
        .arg(dir.join("bin_nif.so"))
        .arg(&c_src)
        .output();
    match output {
        Ok(output) if output.status.success() => {}
        Ok(output) => {
            skip(&format!(
                "binary_to_term_used: cc failed ({}):\n{}",
                output.status,
                String::from_utf8_lossy(&output.stderr)
            ));
            return None;
        }
        Err(error) => {
            skip(&format!(
                "binary_to_term_used: could not run the C compiler: {error}"
            ));
            return None;
        }
    }
    // The Erlang modules: `erlc -o <dir> <dir>/bin_nif.erl <dir>/bin_caller.erl`.
    let output = Command::new(&erlc)
        .arg("-o")
        .arg(&dir)
        .arg(&erl_nif)
        .arg(&erl_caller)
        .output();
    match output {
        Ok(output) if output.status.success() => {}
        Ok(output) => {
            skip(&format!(
                "binary_to_term_used: erlc failed ({}):\n{}",
                output.status,
                String::from_utf8_lossy(&output.stderr)
            ));
            return None;
        }
        Err(error) => {
            skip(&format!(
                "binary_to_term_used: could not run `erlc`: {error}"
            ));
            return None;
        }
    }
    let caller = dir.join("bin_caller.beam");
    if !caller.is_file() {
        skip(&format!(
            "binary_to_term_used: erlc produced no {}",
            caller.display()
        ));
        return None;
    }
    Some(Fixture { dir, caller })
}

// ---------------------------------------------------------------------------------------------
// Running a child (bounded)
// ---------------------------------------------------------------------------------------------
/// The outcome of one child invocation: its exit status and its stdout/stderr.
struct Run {
    /// The process exit code (`-1` when it was killed by a signal or the timeout).
    status: i32,
    /// Everything the run wrote to stdout.
    stdout: String,
    /// Everything the run wrote to stderr.
    stderr: String,
}

/// Runs `command` to completion within [`RUN_TIMEOUT`], capturing its streams.
///
/// A spawn failure or a timeout is a **reported** outcome (`status` `-1`), never a panic: the
/// timeout bound is what keeps a hung runtime from wedging the suite.
fn run_command(command: &mut Command) -> Run {
    let child = command
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn();
    let mut child = match child {
        Ok(child) => child,
        Err(error) => {
            return Run {
                status: -1,
                stdout: String::new(),
                stderr: format!("could not spawn {:?}: {error}", command.get_program()),
            };
        }
    };
    let deadline = Instant::now() + RUN_TIMEOUT;
    loop {
        match child.try_wait() {
            Ok(Some(_)) => break,
            Ok(None) if Instant::now() < deadline => std::thread::sleep(Duration::from_millis(10)),
            // The bound is spent: kill and report, so the assertion below sees a real failure.
            Ok(None) => {
                let _ = child.kill();
                let _ = child.wait();
                return Run {
                    status: -1,
                    stdout: String::new(),
                    stderr: format!("timed out after {RUN_TIMEOUT:?}"),
                };
            }
            Err(error) => {
                return Run {
                    status: -1,
                    stdout: String::new(),
                    stderr: format!("could not wait for the child: {error}"),
                };
            }
        }
    }
    let output = child.wait_with_output();
    match output {
        Ok(output) => Run {
            status: output.status.code().unwrap_or(-1),
            stdout: String::from_utf8_lossy(&output.stdout).into_owned(),
            stderr: String::from_utf8_lossy(&output.stderr).into_owned(),
        },
        Err(error) => Run {
            status: -1,
            stdout: String::new(),
            stderr: format!("could not collect the child's output: {error}"),
        },
    }
}

/// Runs `bin_caller:<function>/1` on the **built** `beam_rt` binary.
///
/// The fixture directory is added with `-pa` (before the `run` action, as the CLI requires), so
/// `bin_nif`/`bin_caller` resolve there, and the load path is **double-quoted** because the `run`
/// argument grammar parses a bare token as an atom while `erlang:load_nif/2` needs a char list.
fn invoke_rust(fixture: &Fixture, function: &str) -> Run {
    let mut command = Command::new(env!("CARGO_BIN_EXE_beam_rt"));
    command.args([
        "-noshell",
        "-pa",
        &fixture.dir.display().to_string(),
        "run",
        &fixture.caller.display().to_string(),
        &format!("bin_caller:{function}/1"),
        &format!("\"{}\"", fixture.load_path().display()),
    ]);
    run_command(&mut command)
}

/// Runs the identical `.so`/`.beam` on the system `erl` — the oracle reference.
fn invoke_oracle(fixture: &Fixture, function: &str, erl: &Path) -> Run {
    let load_path = fixture.load_path().display().to_string();
    let eval = format!("io:format(\"~w~n\",[bin_caller:{function}(\"{load_path}\")]), halt(0).");
    let mut command = Command::new(erl);
    command.args([
        "-noshell",
        "-pa",
        &fixture.dir.display().to_string(),
        "-eval",
        &eval,
    ]);
    run_command(&mut command)
}

// ---------------------------------------------------------------------------------------------
// The tests
// ---------------------------------------------------------------------------------------------
/// **`enif_binary_to_term` reports the first term's consumed byte count, not the slice length.**
///
/// The fixture hands `term_to_binary(42)` followed by four junk bytes (7 bytes) to
/// `enif_binary_to_term(env, bytes, len, &term, 0)`; the answer must be `{3, 42}`. A host hook that
/// strict-decodes the whole slice answers the C's failure sentinel instead — the divergence this
/// test exists to close (`beam_rt`'s `NifHostImpl::binary_to_term` really is strict; the used-count
/// hook is a *separate* hook precisely so that the two disciplines can coexist).
///
/// Oracle: the very same `.so`/`.beam` under the system `erl` answer `{3,42}`.
#[test]
fn enif_binary_to_term_reports_the_consumed_byte_count() {
    let Some(fixture) = build_fixture() else {
        return;
    };
    let run = invoke_rust(&fixture, "trailing");
    assert_eq!(
        run.stdout, "{3,42}\n",
        "enif_binary_to_term must count the first term's bytes (3), not the slice (7); \
         status={} stderr={}",
        run.status, run.stderr
    );
    assert_eq!(run.status, 0, "stderr={}", run.stderr);
    fixture.cleanup();
}

/// The **control**: an image with nothing appended is fully consumed, so the count equals the slice
/// length (`3`) and both the fixed and the strict behaviour agree on it. Asserting it keeps the
/// trailing-byte case from being satisfiable by a coincidence.
#[test]
fn enif_binary_to_term_consumes_a_complete_image_exactly() {
    let Some(fixture) = build_fixture() else {
        return;
    };
    let run = invoke_rust(&fixture, "exact");
    assert_eq!(
        run.stdout, "{3,42}\n",
        "a complete 3-byte image is consumed exactly; status={} stderr={}",
        run.status, run.stderr
    );
    assert_eq!(run.status, 0, "stderr={}", run.stderr);
    fixture.cleanup();
}

/// A truncated image is the C's `0` — the count is never fabricated from a partial term. The
/// fixture maps `0` to `undecodable`, so the answer is `{0,undecodable}`.
#[test]
fn enif_binary_to_term_answers_zero_for_a_truncated_image() {
    let Some(fixture) = build_fixture() else {
        return;
    };
    let run = invoke_rust(&fixture, "truncated");
    assert_eq!(
        run.stdout, "{0,undecodable}\n",
        "a truncated image must answer the C's 0; status={} stderr={}",
        run.status, run.stderr
    );
    assert_eq!(run.status, 0, "stderr={}", run.stderr);
    fixture.cleanup();
}

/// **The oracle cross-check**: the identical `.so`/`.beam` under the system `erl` are the reference
/// for all three answers above — `{3,42}`, `{3,42}` and `{0,undecodable}`.
#[test]
fn the_oracle_answers_the_same_consumed_counts() {
    let Some(fixture) = build_fixture() else {
        return;
    };
    let Some(erl) = which_erl() else {
        skip("binary_to_term_used: no `erl` on PATH for the oracle cross-check");
        fixture.cleanup();
        return;
    };
    for (function, expected) in [
        ("trailing", "{3,42}\n"),
        ("exact", "{3,42}\n"),
        ("truncated", "{0,undecodable}\n"),
    ] {
        let oracle = invoke_oracle(&fixture, function, &erl);
        assert_eq!(
            oracle.stdout, expected,
            "the oracle `bin_caller:{function}/1` answer is the reference; \
             status={} stderr={}",
            oracle.status, oracle.stderr
        );
        assert_eq!(
            oracle.status, 0,
            "the oracle run must succeed; stderr={}",
            oracle.stderr
        );
        // The Rust side must answer the very same value — the comparison the differential gate
        // would make, at the executable boundary.
        let rust = invoke_rust(&fixture, function);
        assert_eq!(
            rust.stdout, oracle.stdout,
            "`bin_caller:{function}/1` must agree with the oracle; status={} stderr={}",
            rust.status, rust.stderr
        );
    }
    fixture.cleanup();
}
