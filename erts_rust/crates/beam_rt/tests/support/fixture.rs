//! The shared two-VM **fixture** (contract A.5): the one Erlang module both two-VM suites
//! compile at test time with the system `erlc` and run as their **peer**.
//!
//! | suite | the peer that runs this module |
//! |---|---|
//! | [`tests/dist_two_vm.rs`](../../dist_two_vm.rs) | the system `erl` (the oracle) |
//! | [`tests/dist_two_rust.rs`](../../dist_two_rust.rs) | this runtime, `beam_rt` itself |
//!
//! One source, two peers — which is why the module is a **protocol** rather than a script:
//! a *responder* (run by this runtime on the `run` route) and an *actor* (run by the peer)
//! exchange numbered steps, and each side prints what it observed. Sections 1-3 are the
//! peers-observing-us families and the remote-victim families the oracle suite drives;
//! section 4 is the **rust↔rust** family, whose one extra constraint is the reason it is a
//! separate section at all; section 5 is the **inbound-signal** family, where the peer is
//! the one that links/monitors/exits and the assertion is what *our* process received.
//!
//! The one responder that reports a piece of **our own** state rather than the peer's
//! observation is `peer_drives_links/1`, whose barrier answers carry the *shape* of the
//! victim's `process_info(Victim, links)` item (see its own docs; the pids in it can be
//! rendered by neither VM, so the shape is the whole claim).
//!
//! # A `beam_rt` peer cannot render a *remote* identifier
//!
//! `erlang:pid_to_list/1` (and `erlang:ref_to_list/1`) of an identifier that arrived from
//! another node is the typed capability gap `error:unsupported_bif`
//! (`beam_bifs`'s `external_channel_gap`: an external identifier's leading component is the
//! receiving VM's *node-table index*, which no term carries), and `~p`/`~w` of one has no
//! external arm in this runtime's printer either. A capability gap is **uncatchable** — it
//! is deliberately given a reason atom nothing interns, so a program's own
//! `try … catch` cannot swallow the runtime's honest gap — which means the `try … catch`
//! in [`FIXTURE_ERL`]'s `pid_text/1`/`ref_text/1` does **not** rescue a rust peer: it would
//! terminate the actor with exit 3.
//!
//! So every actor and responder in section 4 asserts identity by **pattern match and
//! `=:=`** against the handle it was handed, and prints only booleans, atoms and reasons.
//! That is *equal in strength* to the oracle suite's canonical-text comparisons and
//! *different in shape*: the oracle suite compares `<node.number.serial>` strings, the
//! rust↔rust suite compares the terms themselves.
//!
//! Every wait in the fixture is deadline-bounded, and that is load-bearing rather than
//! defensive: a bare `receive` leaves the run action's scheduler pump with an empty run
//! queue, nothing to poll and no pending timer, so `Runtime::run_scheduled` stops with its
//! honest `blocked` diagnostic before the peer's message can arrive (`tests/dist.rs` and
//! `tests/live_inbound.rs` pin the same rule).

