//! **A local pid and a local reference survive an External Term Format round trip**
//! — the runtime-level end-to-end regression coverage for the local-node / internal-ref
//! decode path.
//!
//! # The bug this suite pins
//!
//! `binary_to_term(term_to_binary(self()))` used to yield a pid that was **not**
//! `=:= self()`: the encoded `NEW_PID_EXT` carries the node *atom*, and the decode built a
//! pid bound to whatever node identity it had at hand instead of **demoting** a pid that
//! names *this* node back to a local pid. The sibling shape
//! `binary_to_term(term_to_binary(make_ref()))` did not even get that far — a local
//! reference is an internal, node-tagged reference, and the encoder refused it outright with
//! the typed `unsupported: external_term`, so the whole call died as a capability gap
//! (exit `3`).
//!
//! Both halves are fixed in `beam_codec` (local-node demotion on decode + internal-reference
//! encoding) and wired in `beam_bifs` (`decode_term_bif` installs `ctx.local_node()`; the
//! encoder threads the node identity). This suite is the **runtime-level** witness: the
//! workload runs as a real scheduled process through the built `beam_rt` binary, not against
//! the codec in isolation.
//!
//! # What each half pins
//!
//! 1. [`a_local_pid_survives_the_etf_round_trip`] — `d:g/0` must print `{true,true}` (the
//!    decoded value *is* a pid and *is* `=:= self()`), cross-checked against the live oracle.
//!    A truncated `-eval`-free variant past the on-heap limit — a **compressed** payload
//!    carrying both a pid and a reference — pins the same identity across the other encoder
//!    mode.
//! 2. [`a_local_reference_round_trips_identically`] — `d:selfref/0` must print `true`: the
//!    reference that came back is the one that went in, again cross-checked against the live
//!    oracle.
//! 3. [`a_local_reference_encodes_without_a_capability_gap`] — `d:ref/0` must **succeed**
//!    (exit `0`) and print a reference rendering (`#Ref<…>`). Its text is deliberately *not*
//!    compared with the oracle's: a reference is printed with a VM-unique node/creation/
//!    number triple, so only the rendering and the successful exit are pinned — but the exit
//!    must not be the `unsupported: external_term` capability gap it used to be.
//!
//! # Conventions
//!
//! The fixture is compiled **at test time** with the system `erlc` into a scratch directory
//! (never committed — the source of truth is the `.erl` below), driven through the **built
//! binary** (`beam_rt run`, the same executable a user would run) and cross-checked against
//! the live system `erl` running the **same** call. A missing `erl`/`erlc` is a **loud** skip,
//! never a silent pass (`tests/support/mod.rs`). The scratch directory holds only the fixture
//! module, so it is safe to hand to the oracle as a single `-pa` (unlike this crate's
//! `tests/fixtures/`, which contains a `lists.beam`).
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::{Duration, Instant};

#[allow(dead_code)]
mod support;

/// The fixture's module name.
const MODULE: &str = "d";

/// The suite's name in the loud-skip banner.
const SUITE: &str = "etf_roundtrip_pid_ref";

/// The fixture source (compiled at test time — never committed as a `.beam`).
///
/// Every export is one round-trip shape; the comments are the `.erl` file's own record of
/// what each one proves.
const FIXTURE_ERL: &str = r#"%% Generated by `beam_rt/tests/etf_roundtrip_pid_ref.rs` (never committed).
-module(d).
-export([g/0, big/0, selfref/0, ref/0]).

%% --- The local pid -------------------------------------------------------------------
%% The decoded pid must be the very pid the runtime is running as: equal to self().
g() -> P = binary_to_term(term_to_binary(self())), {is_pid(P), P =:= self()}.

%% The other encoder mode over the same identity, plus a reference in the same payload: a
%% compressed term past the 64-byte on-heap limit carrying a pid and a reference must bring
%% both back unchanged.
big() -> P = self(), R = make_ref(),
         {P2, R2, Tail} =
             binary_to_term(term_to_binary({P, R, lists:seq(1, 64)}, [compressed])),
         {P2 =:= P, R2 =:= R, length(Tail)}.

%% --- The local reference -------------------------------------------------------------
%% A round trip must be *encodable at all* (this used to be `unsupported: external_term`) ...
ref() -> R = make_ref(), binary_to_term(term_to_binary(R)).

%% ... and it must come back identical to the reference that went in.
selfref() -> R = make_ref(), R =:= binary_to_term(term_to_binary(R)).
"#;

// ---------------------------------------------------------------------------------------
// Toolchain discovery + the loud skip
// ---------------------------------------------------------------------------------------

/// The compiler: a sibling of the resolved oracle first (the same installation), then `$PATH`.
///
/// `$ERTS_ORACLE`/`$PATH` discovery is `tests/support/mod.rs`'s (filesystem only — a probe
/// must never *run* `erl` to find out whether it exists).
fn resolve_erlc() -> Option<PathBuf> {
    if let Some(dir) = support::resolve_oracle().as_deref().and_then(Path::parent) {
        let candidate = dir.join("erlc");
        if support::is_executable(&candidate) {
            return Some(candidate);
        }
    }
    support::find_on_path("erlc")
}

/// The live oracle and a compiled fixture, or `None` after a **loud** skip.
fn setup(label: &str) -> Option<(PathBuf, Fixture)> {
    let oracle = support::require_oracle(SUITE)?;
    let Some(erlc) = resolve_erlc() else {
        support::skip_loudly(SUITE, "no `erlc` available (and none beside $ERTS_ORACLE)");
        return None;
    };
    let fixture = build_fixture(&erlc, label)?;
    Some((oracle, fixture))
}

// ---------------------------------------------------------------------------------------
// The compiled fixture
// ---------------------------------------------------------------------------------------

/// A compiled fixture in its own scratch directory (removed on drop).
struct Fixture {
    /// The scratch directory holding `d.erl` and `d.beam`.
    dir: PathBuf,
    /// The compiled `d.beam`.
    beam: PathBuf,
}

impl Fixture {
    /// The compiled image as a `str`, for the CLI's argv.
    fn beam_str(&self) -> &str {
        self.beam
            .to_str()
            .unwrap_or_else(|| panic!("the fixture path is not UTF-8: {}", self.beam.display()))
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        // Best effort, but never silent: a leftover scratch dir must not fail the test, yet a
        // cleanup failure is reported rather than swallowed.
        if let Err(error) = std::fs::remove_dir_all(&self.dir) {
            eprintln!(
                "warning: could not remove the fixture dir {}: {error}",
                self.dir.display()
            );
        }
    }
}

/// Writes [`FIXTURE_ERL`] into a fresh scratch directory and compiles it there, or `None`
/// when it cannot be compiled (the caller then returns early — **loudly**).
///
/// `erlc` runs **with the scratch directory as cwd** and the bare argument, exactly as
/// `tests/engine_off_heap_transport.rs` does, so the module is self-contained and the scratch
/// dir is a safe single `-pa` for the oracle.
fn build_fixture(erlc: &Path, label: &str) -> Option<Fixture> {
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let dir = std::env::temp_dir().join(format!(
        "beam_rt_etf_rt_{label}_{}_{n}",
        std::process::id()
    ));
    if let Err(error) = std::fs::create_dir_all(&dir)
        .and_then(|()| std::fs::write(dir.join("d.erl"), FIXTURE_ERL))
    {
        support::skip_loudly(SUITE, &format!("cannot prepare {}: {error}", dir.display()));
        return None;
    }
    let output = match Command::new(erlc)
        .arg("-o")
        .arg(&dir)
        .arg("d.erl")
        .current_dir(&dir)
        .stdin(Stdio::null())
        .output()
    {
        Ok(output) => output,
        Err(error) => {
            support::skip_loudly(SUITE, &format!("cannot run `erlc`: {error}"));
            return None;
        }
    };
    if !output.status.success() {
        support::skip_loudly(
            SUITE,
            &format!(
                "`erlc` exited with {}: {}",
                output.status,
                String::from_utf8_lossy(&output.stderr)
            ),
        );
        return None;
    }
    let beam = dir.join("d.beam");
    if !beam.is_file() {
        support::skip_loudly(SUITE, &format!("`erlc` produced no {}", beam.display()));
        return None;
    }
    Some(Fixture { dir, beam })
}

// ---------------------------------------------------------------------------------------
// The bounded probe
// ---------------------------------------------------------------------------------------

/// One finished probe: its exit code and trimmed stdout/stderr.
struct Run {
    code: i32,
    out: String,
    err: String,
}

/// Runs `program args` with `/dev/null` as stdin, polling so a probe that blocks is killed and
/// reaped at [`support::PROBE_TIMEOUT`] instead of hanging the suite.
///
/// `beam_rt run` is itself bounded by a wall-clock deadline and every fixture entry either
/// returns or raises, so the polling guard is the belt to that suspenders (the same local
/// runner `tests/engine_off_heap_transport.rs` keeps, for the same reason).
fn run_bounded(program: &Path, args: &[&str]) -> Run {
    let mut child = Command::new(program)
        .args(args)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap_or_else(|error| panic!("cannot spawn `{}`: {error}", program.display()));
    let deadline = Instant::now() + support::PROBE_TIMEOUT;
    let output: Output = loop {
        match child.try_wait() {
            Ok(Some(_)) => break child
                .wait_with_output()
                .unwrap_or_else(|error| panic!("cannot collect the probe's output: {error}")),
            Ok(None) => {
                assert!(
                    Instant::now() < deadline,
                    "`{}` outlived the {}s probe bound",
                    program.display(),
                    support::PROBE_TIMEOUT.as_secs()
                );
                std::thread::sleep(Duration::from_millis(10));
            }
            Err(error) => panic!("cannot poll `{}`: {error}", program.display()),
        }
    };
    Run {
        code: output.status.code().unwrap_or(-1),
        out: String::from_utf8_lossy(&output.stdout).trim().to_string(),
        err: String::from_utf8_lossy(&output.stderr).trim().to_string(),
    }
}

// ---------------------------------------------------------------------------------------
// The shared assertions
// ---------------------------------------------------------------------------------------

/// The Erlang call both runtimes are given: `d:<function>(<args…>)`.
fn call(function: &str, args: &[&str]) -> String {
    format!("{MODULE}:{function}({})", args.join(","))
}

/// Builds the `beam_rt -noshell run <beam> <Module>:<Function>/<Arity> [args…]` argv.
///
/// The `run` action drives the **default boot script** (contract A.9), exactly as the oracle's
/// `init:boot` does, but it is **banner-free by construction** — it records the `noshell` init
/// argument — so the booted node prints no OTP banner and the asserted stdout is the workload's
/// own line. `-noshell` is kept to mirror the oracle side, which probes with `erl -noshell …`.
fn run_argv<'a>(beam: &'a str, spec: &'a str, args: &[&'a str]) -> Vec<&'a str> {
    let mut argv = vec!["-noshell", "run", beam, spec];
    argv.extend_from_slice(args);
    argv
}

/// Asserts `run d:<function>/<arity>` prints exactly `expected` with exit code `0` and
/// an empty stderr, **and** that the live oracle prints the same line for the same call.
fn assert_return_matches_the_oracle(
    oracle: &Path,
    fixture: &Fixture,
    label: &str,
    function: &str,
    args: &[&str],
    expected: &str,
) {
    let spec = format!("{MODULE}:{function}/{}", args.len());
    let argv = run_argv(fixture.beam_str(), &spec, args);
    let ours = run_bounded(Path::new(env!("CARGO_BIN_EXE_beam_rt")), &argv);
    assert_eq!(
        ours.code, 0,
        "{label}: `beam_rt run {} {spec} {args:?}` exited {}: {}",
        fixture.beam_str(),
        ours.code,
        ours.err
    );
    assert!(
        !ours.err.contains("unsupported"),
        "{label}: not a capability gap: {}",
        ours.err
    );
    assert!(ours.err.is_empty(), "{label}: stderr: {}", ours.err);
    assert_eq!(ours.out, expected, "{label}: beam_rt's answer");

    let expr = format!("io:format(\"~w~n\", [{}]), halt(0).", call(function, args));
    let theirs = support::oracle_eval(oracle, Some(&fixture.dir), &expr)
        .unwrap_or_else(|| panic!("{label}: the live oracle could not answer"));
    assert_eq!(
        theirs.lines().next().unwrap_or_default(),
        expected,
        "{label}: the expected line must be the live oracle's"
    );
}

/// Asserts `run d:<function>/<arity>` **succeeds** (exit `0`, empty stderr) and prints a
/// reference rendering.
///
/// A reference's `~w` form embeds this VM's node identity, creation and a per-VM reference
/// number, so the exact text is deliberately *not* compared with the oracle's — the pinned
/// properties are the successful exit (`unsupported: external_term` was the recorded defect)
/// and the `#Ref<…>` rendering.
fn assert_ref_round_trips(fixture: &Fixture, label: &str, function: &str, args: &[&str]) {
    let spec = format!("{MODULE}:{function}/{}", args.len());
    let argv = run_argv(fixture.beam_str(), &spec, args);
    let ours = run_bounded(Path::new(env!("CARGO_BIN_EXE_beam_rt")), &argv);
    assert_eq!(
        ours.code, 0,
        "{label}: `beam_rt run {} {spec}` exited {}: {}",
        fixture.beam_str(),
        ours.code,
        ours.err
    );
    assert!(
        !ours.err.contains("unsupported"),
        "{label}: a round trip is not a capability gap: {}",
        ours.err
    );
    assert!(ours.err.is_empty(), "{label}: stderr: {}", ours.err);
    assert!(
        ours.out.starts_with("#Ref<") && ours.out.ends_with('>'),
        "{label}: a reference renders as `#Ref<…>`, got `{}`",
        ours.out
    );
}

// ---------------------------------------------------------------------------------------
// 1. The local pid
// ---------------------------------------------------------------------------------------

/// **The exact reproducer: a local pid round-trips to `self()`.**
///
/// `d:g/0` decodes `term_to_binary(self())` and answers `{is_pid(P), P =:= self()}` — before
/// the fix the decoded pid named a *different* node, so the pair was `{true,false}`. The
/// second entry reaches the same identity through the **compressed** encoder over a payload
/// past the 64-byte on-heap limit that carries a pid and a reference side by side. Both lines
/// are cross-checked against the live oracle.
#[test]
fn a_local_pid_survives_the_etf_round_trip() {
    let Some((oracle, fixture)) = setup("pid") else {
        return;
    };

    assert_return_matches_the_oracle(
        &oracle,
        &fixture,
        "binary_to_term(term_to_binary(self())) (the exact regression repro)",
        "g",
        &[],
        "{true,true}",
    );
    assert_return_matches_the_oracle(
        &oracle,
        &fixture,
        "a compressed payload past the on-heap limit carrying a pid and a reference",
        "big",
        &[],
        "{true,true,64}",
    );
}

// ---------------------------------------------------------------------------------------
// 2. The local reference
// ---------------------------------------------------------------------------------------

/// **The reference that comes back is the one that went in.**
///
/// `d:selfref/0` compares the reference it minted with the one decoded from its ETF image,
/// cross-checked against the live oracle. This is the pair that used to be `unsupported:
/// external_term` (a capability gap, exit `3`) rather than a false answer — the guard that
/// the internal-reference encode path really completed.
#[test]
fn a_local_reference_round_trips_identically() {
    let Some((oracle, fixture)) = setup("selfref") else {
        return;
    };

    assert_return_matches_the_oracle(
        &oracle,
        &fixture,
        "R = make_ref(), R =:= binary_to_term(term_to_binary(R))",
        "selfref",
        &[],
        "true",
    );
}

/// **A local reference is encodable and printable at all.**
///
/// `d:ref/0` returns the decoded reference itself, so the CLI prints it. The run must exit
/// `0` (never `unsupported: external_term`, never an `error:badarg`) and print the `#Ref<…>`
/// rendering.
#[test]
fn a_local_reference_encodes_without_a_capability_gap() {
    let Some((_oracle, fixture)) = setup("ref") else {
        return;
    };

    assert_ref_round_trips(&fixture, "make_ref() through term_to_binary/1", "ref", &[]);
}
