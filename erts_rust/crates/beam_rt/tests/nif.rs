/// The `enif_alloc_env` C fixture (never committed — compiled at test time under the stem/module
/// `env_nif`).
///
/// `alloc_env_ok/0` calls `enif_alloc_env()`, frees the environment again and answers the atom
/// `live` when the env was non-NULL, `null` otherwise. The C never returns `NULL` from
/// `enif_alloc_env` (an allocation failure aborts the emulator), so a `null` answer would be a
/// real divergence — this pins the runtime's `enif_alloc_env` hook reaching its host and handing
/// out a live env.
///
/// `alloc_env_copy/0` is the full **message-env round trip**, exactly the gate's
/// `nif_res/alloc_env_roundtrip`: build the atom `ok` on a fresh `enif_alloc_env` env, copy it
/// back into the call env with `enif_make_copy`, free the message env, and answer the copy. It
/// pins the counterpart hook ([`NifHost::make_copy`], which `NifHostImpl` implements as the
/// identity because both envs share its heap) — without it `enif_make_copy` answers the ABI's
/// `THE_NON_VALUE` — a bare header word, not a term.
///
/// Both are **separate** sources from `beam_abi`'s `test_nif.c` (which cannot be edited by this
/// crate); the crate's [`NifHostImpl`] overrides the `alloc_env`/`free_env`/`make_copy` hooks the
/// shared fixture does not exercise.
const ENV_NIF_C: &str = r#"
#include <erl_nif.h>

static ERL_NIF_TERM alloc_env_ok(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    ErlNifEnv* e;
    (void) argc; (void) argv;
    e = enif_alloc_env();
    if (e == NULL) return enif_make_atom(env, "null");
    enif_free_env(e);
    return enif_make_atom(env, "live");
}

static ERL_NIF_TERM alloc_env_copy(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    ErlNifEnv* e;
    ERL_NIF_TERM t, c;
    (void) argc; (void) argv;
    e = enif_alloc_env();
    if (e == NULL) return enif_make_atom(env, "unsupported_enif_alloc_env");
    t = enif_make_atom(e, "ok");
    c = enif_make_copy(env, t);
    enif_free_env(e);
    return c;
}

static int load(ErlNifEnv* env, void** priv, ERL_NIF_TERM info) {
    (void) env; (void) info;
    *priv = NULL;
    return 0;
}

static ErlNifFunc env_nif_funcs[] = {
    {"alloc_env_ok", 0, alloc_env_ok, 0},
    {"alloc_env_copy", 0, alloc_env_copy, 0}
};

ERL_NIF_INIT(env_nif, env_nif_funcs, load, NULL, NULL, NULL)
"#;

