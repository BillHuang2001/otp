const TEST_NIF_ERL: &str = r#"%% Generated by `beam_rt/tests/nif.rs` (never committed).
-module(test_nif).
-export([init/1, add/2, hello/0]).
init(Path) -> erlang:load_nif(Path, 0).
add(_, _) -> erlang:nif_error(not_loaded).
hello() -> erlang:nif_error(not_loaded).
"#;

/// The caller: every export reaches the NIF through an **external** call.
///
/// `precached/1` differs from `go/1` in exactly one way: `code:ensure_loaded(test_nif)` puts the
/// callee's module in the code server **before** the first `test_nif:*` call, so the engine's
/// cross-module seam takes its *already-cached* arm for `test_nif:init/1` instead of its
/// on-demand-load arm. That arm must apply the module-observer guard as well (the callee imports
/// `erlang:load_nif/2`), or the call is entered in-machine under the **caller's** module identity
/// and the library load reports the oracle's `bad_lib`.
const CALLER_ERL: &str = r#"%% Generated by `beam_rt/tests/nif.rs` (never committed).
-module(caller).
-export([go/1, bad/1, reload/1, precached/1]).
go(Path) -> ok = test_nif:init(Path), test_nif:add(2, 3).
bad(Path) -> case test_nif:init(Path) of ok -> ok; {error, {Reason, _}} -> Reason end.
reload(Path) -> ok = test_nif:init(Path), case test_nif:init(Path) of ok -> ok; {error, {Reason, _}} -> Reason end.
precached(Path) -> {module, test_nif} = code:ensure_loaded(test_nif), ok = test_nif:init(Path), test_nif:add(2, 3).
"#;

