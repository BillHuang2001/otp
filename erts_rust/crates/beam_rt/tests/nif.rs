/// The caller: a real `cat` port is opened, probed, written to, closed and probed again — each
/// probe through an **external** call so it reaches the runtime's NIF dispatch.
///
/// The answer tuple is `{Live0, Ok, Live1, Dead, NotAPort}`: `1, 1, 1, 0, 0` is the oracle's own
/// answer (`enif_is_port_alive` is `!!erts_port_lookup`, `erl_nif.c:2344`; `enif_port_command` is
/// the port's input direction, `:1097-1133`).
const PORT_CALLER_ERL: &str = r#"%% Generated by `beam_rt/tests/nif.rs` (never committed).
-module(port_caller).
-export([probe/1]).
probe(Path) ->
    ok = port_nif:init(Path),
    P = open_port({spawn, "cat"}, []),
    Live0 = port_nif:is_alive(P),
    Ok = port_nif:command(P, "hello"),
    Live1 = port_nif:is_alive(P),
    true = port_close(P),
    Dead = port_nif:is_alive(P),
    NotAPort = port_nif:is_alive(not_a_port),
    {Live0, Ok, Live1, Dead, NotAPort}.
"#;

