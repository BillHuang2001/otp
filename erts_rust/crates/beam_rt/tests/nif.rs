//! The **NIF** end-to-end test (contract A.3): a real Erlang module loads a real C NIF `.so`
//! through `erlang:load_nif/2` and calls its functions from interpreted Erlang.
//!
//! Everything here is real: the C source is the same fixture `beam_abi`'s own end-to-end test
//! compiles (so the two layers are pinned against *one* NIF), it is compiled with the host C
//! compiler against the host `erl_nif.h`, the Erlang modules are compiled with the host `erlc`,
//! and the whole thing is driven through the **built binary** ([`CARGO_BIN_EXE_beam_rt`]) exactly
//! as a user would.
//!
//! # Why the fixture needs an external caller
//!
//! A NIF replaces the Erlang stub of the same `{module, function, arity}` at the moment the
//! **runtime dispatches a call**. A *local* call inside the NIF's own module is compiled to the
//! `call` opcode and the engine resolves it inside the module it is already running — it never
//! reaches [`RuntimeContext::call_bif`](beam_rt::RuntimeContext), so such a call keeps running the
//! stub. `caller.erl` therefore calls `test_nif:add/2` from *another* module, which the engine
//! compiles to an **external** call (`call_ext`) and routes through the runtime's dispatch. This
//! is honest about the seam: the interception is at external dispatch, which is the same place the
//! BEAM's own NIF lookup happens for a cross-module call.
//!
//! # Skip policy
//!
//! Three host facilities are needed (the C compiler, the host `erl_nif.h`, the host `erlc`). When
//! one is missing the test prints a **loud** banner and returns — it never silently passes. The
//! oracle values below were verified against the system runtime (OTP 29 / `erts-17.1`).
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::{AtomicUsize, Ordering};

/// The `beam_abi` NIF fixture, reused verbatim so both layers are pinned against one `.so`.
const NIF_C: &str = include_str!("../../beam_abi/tests/fixtures/test_nif.c");

/// The NIF module: the stub bodies are replaced by the library's `add/2`/`hello/0` once
/// `init/1` loads it.
const TEST_NIF_ERL: &str = r#"%% Generated by `beam_rt/tests/nif.rs` (never committed).
-module(test_nif).
-export([init/1, add/2, hello/0]).
init(Path) -> erlang:load_nif(Path, 0).
add(_, _) -> erlang:nif_error(not_loaded).
hello() -> erlang:nif_error(not_loaded).
"#;

/// The caller: every export reaches the NIF through an **external** call (see the module docs).
const CALLER_ERL: &str = r#"%% Generated by `beam_rt/tests/nif.rs` (never committed).
-module(caller).
-export([go/1, bad/1, reload/1]).
go(Path) -> ok = test_nif:init(Path), test_nif:add(2, 3).
bad(Path) -> case test_nif:init(Path) of ok -> ok; {error, {Reason, _}} -> Reason end.
reload(Path) -> ok = test_nif:init(Path), case test_nif:init(Path) of ok -> ok; {error, {Reason, _}} -> Reason end.
"#;

/// The six `enif_*` symbols the fixture `.so` imports — the runtime must export every one of them
/// as a **dynamic** symbol for `dlopen(RTLD_NOW)` to bind the library.
const NIF_IMPORTS: &[&str] = &[
    "enif_get_int",
    "enif_make_int",
    "enif_make_atom",
    "enif_make_reverse_list",
    "enif_make_tuple_from_array",
    "enif_make_badarg",
];

/// Print a loud skip banner (never a silent pass).
fn skip(reason: &str) {
    println!("================================================================");
    println!("SKIP: {reason}");
    println!("================================================================");
}

// ---------------------------------------------------------------------------------------------
// Locating the host `erl_nif.h`
// ---------------------------------------------------------------------------------------------
/// The header the include-directory search keys on.
const HEADER: &str = "erl_nif.h";

/// Locate the host `erl_nif.h` include directory, robustly; `None` if unavailable.
///
/// Resolution order (the first directory that actually contains a readable `erl_nif.h` wins):
/// ask the host `erl`; then canonicalize the `erl` on `PATH`; then probe the standard roots.
fn erl_include_dir() -> Option<PathBuf> {
    from_erl_eval()
        .or_else(from_path_erl)
        .or_else(|| standard_roots().into_iter().find_map(|root| search_root(&root)))
}

/// True when `dir` holds a readable `erl_nif.h`.
fn has_header(dir: &Path) -> bool {
    dir.join(HEADER).is_file()
}

/// Ask the host `erl` for `code:lib_dir(erts, include)`.
fn from_erl_eval() -> Option<PathBuf> {
    let output = Command::new("erl")
        .args([
            "-noshell",
            "-eval",
            "io:format(\"~s\",[code:lib_dir(erts,include)])",
            "-s",
            "init",
            "stop",
        ])
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let text = String::from_utf8(output.stdout).ok()?;
    let dir = PathBuf::from(text.trim());
    has_header(&dir).then_some(dir)
}

/// Canonicalize the `erl` on `PATH` and take the sibling `include` of its `erts-*` directory.
fn from_path_erl() -> Option<PathBuf> {
    let erl = which_erl()?.canonicalize().ok()?;
    let bin = erl.parent()?;
    let erts = bin.parent()?;
    if bin.file_name()? != "bin" || !erts.file_name()?.to_string_lossy().starts_with("erts-") {
        return None;
    }
    let include = erts.join("include");
    has_header(&include).then_some(include)
}

/// The first `erl` executable on `PATH`.
fn which_erl() -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|dir| dir.join("erl"))
        .find(|candidate| candidate.is_file())
}

/// The standard installation roots to probe.
fn standard_roots() -> Vec<PathBuf> {
    let mut roots = Vec::new();
    if let Some(top) = std::env::var_os("ERL_TOP") {
        roots.push(PathBuf::from(top));
    }
    for base in [
        "/usr/lib/erlang",
        "/usr/local/lib/erlang",
        "/usr/lib64/erlang",
        "/opt/erlang",
    ] {
        roots.push(PathBuf::from(base));
    }
    roots
}

/// Search one installation root for an include directory holding `erl_nif.h`.
fn search_root(root: &Path) -> Option<PathBuf> {
    let direct = root.join("include");
    if has_header(&direct) {
        return Some(direct);
    }
    let lib_erlang = root.join("lib").join("erlang");
    for base in [root.to_path_buf(), lib_erlang.clone()] {
        let Ok(entries) = std::fs::read_dir(&base) else {
            continue;
        };
        for entry in entries.flatten() {
            if !entry.file_name().to_string_lossy().starts_with("erts-") {
                continue;
            }
            let include = entry.path().join("include");
            if has_header(&include) {
                return Some(include);
            }
        }
    }
    let include = lib_erlang.join("include");
    has_header(&include).then_some(include)
}

// ---------------------------------------------------------------------------------------------
// The compiled fixture
// ---------------------------------------------------------------------------------------------
/// The C compiler to use: `$CC` when set, else `cc`.
fn cc() -> String {
    std::env::var("CC").unwrap_or_else(|_| "cc".to_string())
}

/// Whether a C compiler is available.
fn cc_available() -> bool {
    Command::new(cc())
        .arg("--version")
        .output()
        .map(|output| output.status.success())
        .unwrap_or(false)
}

/// A compiled NIF module + its caller, in one scratch directory.
struct Fixture {
    /// The scratch directory holding the sources and the compiled artifacts.
    dir: PathBuf,
    /// The compiled `caller.beam` (the `run` file argument).
    caller: PathBuf,
    /// The NIF module name (the `.so` is `<dir>/<module>.so`).
    module: String,
}

impl Fixture {
    /// Removes the scratch directory (`cc`/`erlc` output is not source).
    fn cleanup(self) {
        match std::fs::remove_dir_all(&self.dir) {
            Ok(()) => {}
            // The directory is ours and disposable; a failure is reported, not hidden.
            Err(error) => println!("note: could not remove {}: {error}", self.dir.display()),
        }
    }

    /// The path handed to `erlang:load_nif/2` (the `.so` **without** its suffix — the loader
    /// appends `.so`).
    fn load_path(&self, stem: &str) -> PathBuf {
        self.dir.join(stem)
    }
}

/// Compiles the C library and both Erlang modules, or `None` when a host facility is missing
/// (the caller then returns early — **loudly**).
fn build_fixture(label: &str) -> Option<Fixture> {
    let Some(include) = erl_include_dir() else {
        skip(&format!("nif/{label}: no erl_nif.h include directory found"));
        return None;
    };
    if !cc_available() {
        skip(&format!(
            "nif/{label}: no C compiler ({} / $CC) available",
            cc()
        ));
        return None;
    }
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let dir = std::env::temp_dir().join(format!(
        "beam_rt_nif_{label}_{}_{n}",
        std::process::id()
    ));
    let module = "test_nif".to_string();
    let c_src = dir.join("test_nif.c");
    let erl_src = dir.join("test_nif.erl");
    let caller_src = dir.join("caller.erl");
    let write = std::fs::create_dir_all(&dir)
        .and_then(|()| std::fs::write(&c_src, NIF_C))
        .and_then(|()| std::fs::write(&erl_src, TEST_NIF_ERL))
        .and_then(|()| std::fs::write(&caller_src, CALLER_ERL));
    if let Err(error) = write {
        skip(&format!("nif/{label}: cannot prepare {}: {error}", dir.display()));
        return None;
    }
    // The shared object: `cc -shared -fPIC -I<include> -o <dir>/test_nif.so <dir>/test_nif.c`.
    let output = Command::new(cc())
        .arg("-shared")
        .arg("-fPIC")
        .arg(format!("-I{}", include.display()))
        .arg("-o")
        .arg(dir.join(format!("{module}.so")))
        .arg(&c_src)
        .output();
    match output {
        Ok(output) if output.status.success() => {}
        Ok(output) => {
            skip(&format!(
                "nif/{label}: cc failed ({}):\n{}",
                output.status,
                String::from_utf8_lossy(&output.stderr)
            ));
            return None;
        }
        Err(error) => {
            skip(&format!("nif/{label}: could not run the C compiler: {error}"));
            return None;
        }
    }
    // The Erlang modules: `erlc -o <dir> <dir>/test_nif.erl <dir>/caller.erl`.
    let output = Command::new("erlc")
        .arg("-o")
        .arg(&dir)
        .arg(&erl_src)
        .arg(&caller_src)
        .output();
    match output {
        Ok(output) if output.status.success() => {}
        Ok(output) => {
            skip(&format!(
                "nif/{label}: erlc failed ({}):\n{}",
                output.status,
                String::from_utf8_lossy(&output.stderr)
            ));
            return None;
        }
        Err(error) => {
            skip(&format!("nif/{label}: could not run `erlc`: {error}"));
            return None;
        }
    }
    let caller = dir.join("caller.beam");
    if !caller.is_file() {
        skip(&format!("nif/{label}: erlc produced no {}", caller.display()));
        return None;
    }
    Some(Fixture {
        dir,
        caller,
        module,
    })
}

/// The outcome of one `beam_rt` invocation: its exit status and its stdout/stderr.
struct Run {
    /// The process exit code (`-1` when it was killed by a signal).
    status: i32,
    /// Everything the run wrote to stdout.
    stdout: String,
    /// Everything the run wrote to stderr.
    stderr: String,
}

/// Runs the built `beam_rt` binary with `args` and captures its streams.
///
/// The fixture directory is added with `-pa` (before the `run` action, as the CLI requires), so
/// `test_nif`/`caller` resolve there. It is **never** passed to the oracle in the same way — the
/// crate's own fixtures directory can carry a shadowing module.
fn run_binary(args: &[String]) -> Run {
    let output = Command::new(env!("CARGO_BIN_EXE_beam_rt"))
        .args(args)
        .output()
        .expect("the beam_rt binary runs");
    Run {
        status: output.status.code().unwrap_or(-1),
        stdout: String::from_utf8_lossy(&output.stdout).into_owned(),
        stderr: String::from_utf8_lossy(&output.stderr).into_owned(),
    }
}

/// The `-noshell -pa <dir> run <caller.beam> caller:<function>/1 "<load-path>"` invocation.
fn invoke(fixture: &Fixture, function: &str, load_path: &Path) -> Run {
    let args = vec![
        "-noshell".to_string(),
        "-pa".to_string(),
        fixture.dir.display().to_string(),
        "run".to_string(),
        fixture.caller.display().to_string(),
        format!("caller:{function}/1"),
        load_path.display().to_string(),
    ];
    run_binary(&args)
}

