//! The **NIF** end-to-end test (contract A.3): a real Erlang module loads a real C NIF `.so`
//! through `erlang:load_nif/2` and calls its functions from interpreted Erlang.
//!
//! Everything here is real: the C source is the same fixture `beam_abi`'s own end-to-end test
//! compiles (so the two layers are pinned against *one* NIF), it is compiled with the host C
//! compiler against the host `erl_nif.h`, the Erlang modules are compiled with the host `erlc`,
//! and the whole thing is driven through the **built binary** ([`CARGO_BIN_EXE_beam_rt`]) exactly
//! as a user would.
//!
//! # Why the fixture needs an external caller
//!
//! A NIF replaces the Erlang stub of the same `{module, function, arity}` at the moment the
//! **runtime dispatches a call**. A *local* call inside the NIF's own module is compiled to the
//! `call` opcode and the engine resolves it inside the module it is already running — it never
//! reaches [`RuntimeContext::call_bif`](beam_rt::RuntimeContext), so such a call keeps running the
//! stub. `caller.erl` therefore calls `test_nif:add/2` from *another* module, which the engine
//! compiles to an **external** call (`call_ext`) and routes through the runtime's dispatch. This
//! is honest about the seam: the interception is at external dispatch, which is the same place the
//! BEAM's own NIF lookup happens for a cross-module call.
//!
//! # Skip policy
//!
//! Three host facilities are needed (the C compiler, the host `erl_nif.h`, the host `erlc`). When
//! one is missing the test prints a **loud** banner and returns — it never silently passes. The
//! oracle values below were verified against the system runtime (OTP 29 / `erts-17.1`).
//!
//! # The failure-reason atom
//!
//! A `load_nif/2` failure is reported as `{error, {Reason, Text}}`, whose `Reason` atom
//! (`load_failed`, `bad_lib`, `reload`, …) the runtime interns on demand — exactly as the oracle
//! builds it with `mkatom` → `am_atom_put` (`erl_nif.c:4479-4482`). The fixture therefore needs no
//! pre-interning: `caller.erl` merely pattern-matches the reason and returns it.
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::{AtomicUsize, Ordering};

/// The `beam_abi` NIF fixture, reused verbatim so both layers are pinned against one `.so`.
const NIF_C: &str = include_str!("../../beam_abi/tests/fixtures/test_nif.c");

/// The NIF module: the stub bodies are replaced by the library's `add/2`/`hello/0` once
