/// Compiles `c_source` into `<scratch>/<module>.so` (its `ERL_NIF_INIT` must name `module`) and
/// every `(stem, source)` in `erl_sources` into `<scratch>/<stem>.beam`, or `None` when a host
/// facility is missing (the caller returns early — **loudly**).
///
/// The returned [`Fixture`]'s `caller` is `<scratch>/<caller_stem>.beam`. Nothing is committed: the
/// C and Erlang sources are written to a `$TMPDIR` scratch directory that the fixture's `cleanup`
/// removes.
fn build_nif_fixture(
    label: &str,
    c_source: &str,
    module: &str,
    erl_sources: &[(&str, &str)],
    caller_stem: &str,
) -> Option<Fixture> {
    let Some(include) = erl_include_dir() else {
        skip(&format!("nif/{label}: no erl_nif.h include directory found"));
        return None;
    };
    if !cc_available() {
        skip(&format!(
            "nif/{label}: no C compiler ({} / $CC) available",
            cc()
        ));
        return None;
    }
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let dir = std::env::temp_dir().join(format!(
        "beam_rt_nif_{label}_{}_{n}",
        std::process::id()
    ));
    let c_src = dir.join(format!("{module}.c"));
    if let Err(error) = std::fs::create_dir_all(&dir).and_then(|()| std::fs::write(&c_src, c_source))
    {
        skip(&format!("nif/{label}: cannot prepare {}: {error}", dir.display()));
        return None;
    }
    let mut erl_paths = Vec::with_capacity(erl_sources.len());
    for (stem, source) in erl_sources {
        let path = dir.join(format!("{stem}.erl"));
        if let Err(error) = std::fs::write(&path, source) {
            skip(&format!("nif/{label}: cannot write {}: {error}", path.display()));
            return None;
        }
        erl_paths.push(path);
    }
    // The shared object: `cc -shared -fPIC -I<include> -o <dir>/<module>.so <dir>/<module>.c`.
    let output = Command::new(cc())
        .arg("-shared")
        .arg("-fPIC")
        .arg(format!("-I{}", include.display()))
        .arg("-o")
        .arg(dir.join(format!("{module}.so")))
        .arg(&c_src)
        .output();
    match output {
        Ok(output) if output.status.success() => {}
        Ok(output) => {
            skip(&format!(
                "nif/{label}: cc failed ({}):\n{}",
                output.status,
                String::from_utf8_lossy(&output.stderr)
            ));
            return None;
        }
        Err(error) => {
            skip(&format!("nif/{label}: could not run the C compiler: {error}"));
            return None;
        }
    }
    // The Erlang modules: `erlc -o <dir> <dir>/<stem>.erl …`.
    let output = Command::new("erlc")
        .arg("-o")
        .arg(&dir)
        .args(&erl_paths)
        .output();
    match output {
        Ok(output) if output.status.success() => {}
        Ok(output) => {
            skip(&format!(
                "nif/{label}: erlc failed ({}):\n{}",
                output.status,
                String::from_utf8_lossy(&output.stderr)
            ));
            return None;
        }
        Err(error) => {
            skip(&format!("nif/{label}: could not run `erlc`: {error}"));
            return None;
        }
    }
    let caller = dir.join(format!("{caller_stem}.beam"));
    if !caller.is_file() {
        skip(&format!("nif/{label}: erlc produced no {}", caller.display()));
        return None;
    }
    Some(Fixture {
        dir,
        caller,
        module: module.to_string(),
    })
}

/// The outcome of one `beam_rt` invocation: its exit status and its stdout/stderr.
struct Run {
    /// The process exit code (`-1` when it was killed by a signal).
    status: i32,
    /// Everything the run wrote to stdout.
    stdout: String,
    /// Everything the run wrote to stderr.
    stderr: String,
}

/// Runs `command` to completion and captures its exit status and streams.
fn run_command(command: &mut Command) -> Run {
    let output = command.output().expect("the beam_rt binary runs");
    Run {
        status: output.status.code().unwrap_or(-1),
        stdout: String::from_utf8_lossy(&output.stdout).into_owned(),
        stderr: String::from_utf8_lossy(&output.stderr).into_owned(),
    }
}

/// Runs the built `beam_rt` binary with `args` and captures its streams, letting the child
/// inherit the test process's `BEAM_RT_TIER`.
///
/// The fixture directory is added with `-pa` (before the `run` action, as the CLI requires), so
/// `test_nif`/`caller` resolve there. It is **never** passed to the oracle in the same way — the
/// crate's own fixtures directory can carry a shadowing module.
fn run_binary(args: &[String]) -> Run {
    run_command(Command::new(env!("CARGO_BIN_EXE_beam_rt")).args(args))
}

/// As [`run_binary`], but forcing the child's `BEAM_RT_TIER` to `tier`; `None` **removes** the
/// variable, so that case is the unset (default) tier rather than whatever the test process
/// carries. Used by the tier-consistency test to make each run's tier explicit — the crate is
/// `#![deny(unsafe_code)]`, so the test process's own environment is never mutated (`set_var`
/// is `unsafe` in edition 2024).
fn run_binary_tier(args: &[String], tier: Option<&str>) -> Run {
    let mut command = Command::new(env!("CARGO_BIN_EXE_beam_rt"));
    command.args(args);
    match tier {
        Some(tier) => {
            command.env("BEAM_RT_TIER", tier);
        }
        None => {
            command.env_remove("BEAM_RT_TIER");
        }
    }
    run_command(&mut command)
}

/// The `-noshell -pa <dir> run <caller.beam> <module>:<function>/1 "<load-path>"` argument vector
/// for a [`Fixture`]. `module` is the fixture's caller module (`caller`, `env_caller`,
/// `port_caller`), which differs between the fixtures.
///
/// The load path is **double-quoted**: the `run` argument grammar parses a bare token as an atom
/// and only a quoted token as an Erlang char list, and `erlang:load_nif/2` requires a list or a
/// binary (an atom is `badarg`). The scratch path carries no `"` or backslash, so no escaping is
/// needed.
fn invoke_args(fixture: &Fixture, module: &str, function: &str, load_path: &Path) -> Vec<String> {
    vec![
        "-noshell".to_string(),
        "-pa".to_string(),
        fixture.dir.display().to_string(),
        "run".to_string(),
        fixture.caller.display().to_string(),
        format!("{module}:{function}/1"),
        format!("\"{}\"", load_path.display()),
    ]
}

/// The `-noshell -pa <dir> run <caller.beam> caller:<function>/1 "<load-path>"` invocation.
fn invoke(fixture: &Fixture, function: &str, load_path: &Path) -> Run {
    run_binary(&invoke_args(fixture, "caller", function, load_path))
}

/// As [`invoke`], but with the child's `BEAM_RT_TIER` pinned to `tier` (`None` = unset).
fn invoke_tier(fixture: &Fixture, function: &str, load_path: &Path, tier: Option<&str>) -> Run {
    run_binary_tier(&invoke_args(fixture, "caller", function, load_path), tier)
}

/// The `-noshell -pa <dir> run <env_caller.beam> env_caller:<function>/1 "<load-path>"` invocation
/// for the [`build_env_fixture`] pair (its caller module is `env_caller`, not `caller`).
fn invoke_env(fixture: &Fixture, function: &str, load_path: &Path) -> Run {
    run_binary(&invoke_args(fixture, "env_caller", function, load_path))
}

/// The `-noshell -pa <dir> run <port_caller.beam> port_caller:<function>/1 "<load-path>"`
/// invocation for the [`build_port_fixture`] pair (its caller module is `port_caller`).
fn invoke_port(fixture: &Fixture, function: &str, load_path: &Path) -> Run {
    run_binary(&invoke_args(fixture, "port_caller", function, load_path))
}

