// The tests
// ---------------------------------------------------------------------------------------------
/// `erlang:load_nif/2` loads the `.so` and the NIF's `add/2` is called from interpreted Erlang.
///
/// Oracle: `test_nif:add(2, 3)` is `5` (the C computes `A + B` with `enif_get_int`/
/// `enif_make_int`).
#[test]
fn a_real_nif_library_loads_and_its_function_is_callable() {
    let Some(fixture) = build_fixture("call") else {
        return;
    };
    let run = invoke(&fixture, "go", &fixture.load_path(&fixture.module));
    assert_eq!(
        run.stdout, "5\n",
        "caller:go/1 must print the NIF's 2 + 3; status={} stderr={}",
        run.status, run.stderr
    );
    assert_eq!(run.status, 0, "stderr={}", run.stderr);

    fixture.cleanup();
}

/// A load that fails is the oracle's `{error, {Reason, Text}}` — here `load_failed`, because the
/// path names no library. The reason is never swallowed and never a placeholder.
#[test]
fn a_failed_load_reports_the_oracle_reason_atom() {
    let Some(fixture) = build_fixture("bad") else {
        return;
    };
    let run = invoke(&fixture, "bad", &fixture.load_path("does_not_exist"));
    // `caller:bad/1` returns the atom `load_failed` when `init/1` answers `{error, {Reason, _}}`,
    // so the `~w` printer renders exactly the reason. (The `{error, {Reason, Text}}` term itself
    // embeds an OS message long enough to hit a documented `beam_bifs` printer width gap.)
    assert_eq!(
        run.stdout, "load_failed\n",
        "status={} stderr={}",
        run.status, run.stderr
    );
    assert_eq!(run.status, 0, "stderr={}", run.stderr);

    fixture.cleanup();
}

/// A second `load_nif` for a module that already has a library is the oracle's `reload` (the rule
/// since OTP 20).
#[test]
fn a_second_load_nif_is_a_reload() {
    let Some(fixture) = build_fixture("reload") else {
        return;
    };
    let run = invoke(&fixture, "reload", &fixture.load_path(&fixture.module));
    assert_eq!(
        run.stdout, "reload\n",
        "status={} stderr={}",
        run.status, run.stderr
    );
    assert_eq!(run.status, 0, "stderr={}", run.stderr);

    fixture.cleanup();
}

/// The built binary **exports** every `enif_*` symbol the fixture imports, as a dynamic symbol.
///
/// This is the other half of the link-time seam (contract A.3): `build.rs` passes
/// `-Wl,--export-dynamic` for the binary and test targets, and
/// `NifRegistry::new` anchors `beam_abi`'s `enif_*` codegen unit with a `black_box` reference —
/// without either, `dlopen(RTLD_NOW)` of a real NIF would fail on an unresolved symbol. Skips
/// loudly when neither `nm` nor `readelf` is installed.
#[test]
fn the_binary_exports_the_enif_symbols_a_nif_imports() {
    let binary = PathBuf::from(env!("CARGO_BIN_EXE_beam_rt"));
    let symbols = match dynamic_symbols(&binary) {
        Some(text) => text,
        None => return,
    };
    for symbol in NIF_IMPORTS {
        assert!(
            symbols.contains(symbol),
            "the dynamic symbol table of {} has no `{symbol}`",
            binary.display()
        );
    }
}

/// The dynamic symbol table of `binary`, or `None` (loudly) when no tool can read it.
fn dynamic_symbols(binary: &Path) -> Option<String> {
    let nm = Command::new("nm").arg("-D").arg(binary).output();
    if let Ok(output) = nm {
        if output.status.success() {
            return Some(String::from_utf8_lossy(&output.stdout).into_owned());
        }
    }
    let readelf = Command::new("readelf")
        .arg("--dyn-syms")
        .arg("-W")
        .arg(binary)
        .output();
    if let Ok(output) = readelf {
        if output.status.success() {
            return Some(String::from_utf8_lossy(&output.stdout).into_owned());
        }
    }
    skip("nif/symbols: neither `nm -D` nor `readelf --dyn-syms` could read the binary");
    None
}
