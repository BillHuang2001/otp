/// The `enif_is_port_alive`/`enif_port_command` C fixture (never committed — compiled at test time
/// under the stem/module `port_nif`).
///
/// `is_alive/1` turns a port **term** into an `ErlNifPort` with `enif_get_local_port` and answers
/// `enif_is_port_alive`'s `1`/`0` (or `-1` for a term that is not a local port). `command/2` sends
/// the message term to the port with `enif_port_command` and answers its `1`/`0`.
///
/// Both are the **port** half of the host's optional [`NifHostServices`](beam_rt) provider —
/// `NifHostImpl::is_port_alive`/`port_command` forward to `RuntimeNifServices` over the runtime's
/// real `PortRegistry` — so the fixture pins the whole path from a `dlopen`ed C library through the
/// `enif_*` ABI to the port table, which no unit test can reach (`beam_abi`'s own fixture, which
/// this crate may not edit, calls neither entry point).
const PORT_NIF_C: &str = r#"
#include <erl_nif.h>

static ERL_NIF_TERM is_alive(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    ErlNifPort p;
    (void) argc;
    if (!enif_get_local_port(env, argv[0], &p)) return enif_make_int(env, -1);
    return enif_make_int(env, enif_is_port_alive(env, &p));
}

static ERL_NIF_TERM command(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    ErlNifPort p;
    (void) argc;
    if (!enif_get_local_port(env, argv[0], &p)) return enif_make_int(env, -1);
    return enif_make_int(env, enif_port_command(env, &p, env, argv[1]));
}

static int load(ErlNifEnv* env, void** priv, ERL_NIF_TERM info) {
    (void) env; (void) info;
    *priv = NULL;
    return 0;
}

static ErlNifFunc port_nif_funcs[] = {
    {"is_alive", 1, is_alive, 0},
    {"command", 2, command, 0}
};

ERL_NIF_INIT(port_nif, port_nif_funcs, load, NULL, NULL, NULL)
"#;

