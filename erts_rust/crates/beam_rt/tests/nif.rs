/// The C compiler to use: `$CC` when set, else `cc`.
fn cc() -> String {
    std::env::var("CC").unwrap_or_else(|_| "cc".to_string())
}

/// Whether a C compiler is available.
fn cc_available() -> bool {
    Command::new(cc())
        .arg("--version")
        .output()
        .map(|output| output.status.success())
        .unwrap_or(false)
}

/// A compiled NIF module + its caller, in one scratch directory.
struct Fixture {
    /// The scratch directory holding the sources and the compiled artifacts.
    dir: PathBuf,
    /// The compiled `caller.beam` (the `run` file argument).
    caller: PathBuf,
    /// The NIF module name (the `.so` is `<dir>/<module>.so`).
    module: String,
}

impl Fixture {
    /// Removes the scratch directory (`cc`/`erlc` output is not source).
    fn cleanup(self) {
        match std::fs::remove_dir_all(&self.dir) {
            Ok(()) => {}
            // The directory is ours and disposable; a failure is reported, not hidden.
            Err(error) => println!("note: could not remove {}: {error}", self.dir.display()),
        }
    }

    /// The path handed to `erlang:load_nif/2` (the `.so` **without** its suffix — the loader
    /// appends `.so`).
    fn load_path(&self, stem: &str) -> PathBuf {
        self.dir.join(stem)
    }
}

/// Compiles the crate's shared NIF fixture (`test_nif`) and both Erlang modules, or `None` when a
/// host facility is missing (the caller then returns early — **loudly**).
fn build_fixture(label: &str) -> Option<Fixture> {
    build_nif_fixture(
        label,
        NIF_C,
        "test_nif",
        &[("test_nif", TEST_NIF_ERL), ("caller", CALLER_ERL)],
        "caller",
    )
}

