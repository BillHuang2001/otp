/// Every `BEAM_RT_TIER` selection, including the **unset** default (`None`), so a test can pin
/// that a result does not depend on the tier.
const TIERS: &[Option<&str>] = &[None, Some("auto"), Some("baseline"), Some("interpreter")];

/// **A callee whose module is already cached is still not entered in-machine.**
///
/// [`RuntimeContext::resolve_external_call`] (the engine's cross-module call seam) must be
/// **idempotent** — see `src/runner/tier.rs` for the soundness argument: the native baseline tier
/// resolves one `call_ext*` twice (its `jit_ext_call` arm asks the seam; a decline re-runs the
/// whole instruction through `Machine::step_instruction`, which asks the seam again). A seam that
/// answered `Ok(None)` on the first consultation and `Ok(Some(..))` on the second — because the
/// first had cached the callee's module — enters the callee in-machine under the **caller's**
/// module identity. For `test_nif`, whose own `init/1` calls `erlang:load_nif/2`, that identity is
/// what the loader validates `ErlNifEntry.name` against, so the load fails with `bad_lib`
/// ("Library module name 'test_nif' does not match calling module 'caller'").
///
/// `caller:precached/1` reaches the already-cached arm deterministically: its
/// `code:ensure_loaded(test_nif)` loads the callee's module into the code server *before* the
/// first `test_nif:init/1` call. (`caller:go/1` reaches the on-demand-load arm instead, which
/// carried the observer guard even before the fix.) Both must therefore answer the NIF's `5` on
/// **every** tier — the seam's routing may not depend on which tier is executing, and no tier may
/// enter the observer in-machine.
///
/// Oracle: the same `.so`/`.beam` under the real system `erl` answers `5` for both exports too
/// (the identity is always correct there, since every `call` sets it).
///
/// `precached` is checked first so that, when the seam regresses, the reported failure is its
/// **deterministic** all-tier one: on the pre-fix seam every tier answers `bad_lib` for
/// `precached` (`"Library module name 'test_nif' does not match calling module 'caller'"`),
/// whereas `go` diverges only where the JIT consults the seam twice.
#[test]
fn a_cached_observer_callee_is_not_entered_in_machine() {
    let Some(fixture) = build_fixture("cached_observer") else {
        return;
    };
    let load_path = fixture.load_path(&fixture.module);
    for function in ["precached", "go"] {
        for tier in TIERS {
            let run = invoke_tier(&fixture, function, &load_path, *tier);
            assert_eq!(
                run.stdout, "5\n",
                "caller:{function}/1 must print the NIF's 2 + 3 with BEAM_RT_TIER={tier:?}; \
                 status={} stderr={}",
                run.status, run.stderr
            );
            assert_eq!(
                run.status, 0,
                "caller:{function}/1 must exit 0 with BEAM_RT_TIER={tier:?}; stderr={}",
                run.stderr
            );
        }
    }

    fixture.cleanup();
}

/// `enif_alloc_env()` hands a NIF a **live** message environment, and `enif_free_env` releases it.
///
/// `enif_alloc_env` is the one `enif_*` entry point that takes **no argument**, so it cannot name a
/// host from its call: `beam_abi` reaches the host of the current NIF call through the thread-local
/// publication [`beam_abi::NifEnv::new`] installs, and forwards to
/// [`NifHost::alloc_env`](beam_abi::NifHost::alloc_env). [`NifHostImpl`](beam_rt) overrides that
/// hook, so the env it hands out is a live env whose atoms are the running runtime's — never a
/// fabricated one. The C `enif_alloc_env` never answers `NULL` (an allocation failure aborts the
/// emulator), so the fixture answers the atom `live` when the env was non-NULL and `null` otherwise.
///
/// Oracle: the very same `.so`/`.beam` under the real system `erl` prints `live` too
/// (`io:format("~w~n",[env_caller:go("…")])`).
#[test]
fn enif_alloc_env_returns_a_live_env() {
    let Some(fixture) = build_env_fixture("alloc_env") else {
        return;
    };
    let run = invoke_env(&fixture, "go", &fixture.load_path(&fixture.module));
    assert_eq!(
        run.stdout, "live\n",
        "enif_alloc_env must hand a NIF a live env; status={} stderr={}",
        run.status, run.stderr
    );
    assert_eq!(run.status, 0, "stderr={}", run.stderr);

    // --- the oracle cross-check: the real system `erl` answers `live` for the same artifacts -----
    if which_erl().is_none() {
        skip("nif/alloc_env: no `erl` on PATH for the oracle cross-check");
        fixture.cleanup();
        return;
    }
    let load_path = fixture.load_path(&fixture.module).display().to_string();
    let eval = format!("io:format(\"~w~n\",[env_caller:go(\"{load_path}\")]), halt(0).");
    let oracle = Command::new("erl")
        .args([
            "-noshell",
            "-pa",
            &fixture.dir.display().to_string(),
            "-eval",
            &eval,
        ])
        .output()
        .expect("the oracle `erl` runs");
    assert!(
        oracle.status.success(),
        "the oracle run failed: status={} stderr={}",
        oracle.status,
        String::from_utf8_lossy(&oracle.stderr)
    );
    assert_eq!(
        String::from_utf8_lossy(&oracle.stdout),
        "live\n",
        "the oracle's own answer is the reference; stderr={}",
        String::from_utf8_lossy(&oracle.stderr)
    );

    fixture.cleanup();
}

/// The **message-env round trip**: `enif_alloc_env` → `enif_make_atom` on the message env →
