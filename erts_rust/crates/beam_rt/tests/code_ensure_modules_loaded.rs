//! **`code:ensure_modules_loaded/1` on the `run` route** (contracts A.7/A.9): the cross-module-call
//! seam must serve the key from a **compiled module**, not only from the `-eval` route.
//!
//! [`RuntimeContext::try_native`](beam_rt::Runtime) serves `code:ensure_modules_loaded/1` from the
//! runtime-native floor, and the floor's key list ([`floor_keys`] in `src/native.rs`) is what makes
//! the cross-module-call seam (`resolve_external_call`) **refuse** to enter the call in-machine as
//! the `code.beam` body. When the key was absent from that list, the `-eval` route was already
//! correct — it never enters a module body — but a **compiled** module's `call_ext` ran
//! `lib/kernel/src/code.erl`'s own body, which reaches the *live* `code_server` process and its
//! second path store: a list naming a module that is nowhere on that store crashed the server
//! (`kernel_sup` reached its restart intensity and reported twice on stderr) and the call then
//! raised `error:badarg` — exit 1, where the oracle answers `{error,[{Name,nofile}]}` and exits 0.
//!
//! # What this suite pins
//!
//! | Case | Shape |
//! |---|---|
//! | `single/0` | one missing module ⇒ the oracle's `{error,[{no_such_mod_xyz,nofile}]}`, exit 0 |
//! | `available/0` | every name loadable ⇒ the bare atom `ok`, exit 0 |
//! | `preloaded/0` | the preloaded names are skipped ⇒ the bare atom `ok`, exit 0 |
//! | `many/0` | three missing modules ⇒ every failure listed, in the floor's documented order |
//!
//! Every value is compared on **stdout** and **exit code** against the **live system `erl`** (the
//! very same compiled fixture, reached through `-pa <scratch dir>`), so the expectations are the
//! oracle's own bytes rather than a recording. The single-failure cases are compared exactly; the
//! three-failure case is compared exactly against the **documented majority order** (the floor's
//! `lists:usort/1` order **reversed**, which is what the oracle's `do_par_recv/3` produces when its
//! concurrent per-module results arrive in order) and against the oracle as an order-insensitive
//! **set**, because the oracle's own list order is racy by construction.
//!
//! # Toolchain
//!
//! The probe module is compiled **at test time** by the system `erlc` into a private scratch
//! directory (nothing is committed, and `tests/fixtures/` — which holds a shadowing `lists.beam` —
//! is never handed to the oracle). The oracle is resolved from the filesystem and every probe is
//! bounded (`tests/support/mod.rs`); a missing `erl`/`erlc` is always a **loud skip**, never a
//! silent pass.

use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::OnceLock;

mod support;

/// The suite name every loud skip names.
const BANNER: &str = "code_ensure_modules_loaded";

/// The probe module, compiled **at test time** (nothing is committed).
///
/// Every exported function hands one list to `code:ensure_modules_loaded/1` from a *compiled*
/// `call_ext` — the route whose cross-module-call seam consults the floor's key list.
const PROBE_ERL: &str = r#"%% Generated by `beam_rt/tests/code_ensure_modules_loaded.rs` (never committed).
-module(cml_probe).
-export([single/0, available/0, preloaded/0, many/0]).

%% One module that is nowhere on the code path: the oracle's `{error,[{no_such_mod_xyz,nofile}]}`.
single() -> code:ensure_modules_loaded([lists, no_such_mod_xyz]).

%% Every named module is loadable (both need nothing of the code path): the bare atom `ok`.
available() -> code:ensure_modules_loaded([lists, maps]).

%% The preloaded names are skipped entirely (`prepare_ensure/2`, `code.erl:1319-1358`).
preloaded() -> code:ensure_modules_loaded([erlang, init]).

%% Three missing modules: every one is listed (the oracle's own list order is racy).
many() -> code:ensure_modules_loaded([lists, cml_missing_a, cml_missing_b, cml_missing_c]).
"#;

/// The live `erl` oracle, resolved **once** (so a missing toolchain is a single loud skip rather
/// than one banner per comparison).
fn oracle() -> Option<PathBuf> {
    static ORACLE: OnceLock<Option<PathBuf>> = OnceLock::new();
    ORACLE.get_or_init(|| support::require_oracle(BANNER)).clone()
}

/// One finished `beam_rt` invocation: its exit code and captured output.
struct Cli {
    code: i32,
    out: String,
    err: String,
}

/// Runs the built `beam_rt` binary with `args`, bounded so a probe that blocks cannot hang the
/// suite. `ERL_CRASH_DUMP_SECONDS=0` keeps a failing boot from littering the working directory.
///
/// The binary is this crate's own, so a child that cannot run to completion is a test failure
/// rather than a skip (the bounded runner kills and reaps it either way).
fn beam_rt(args: &[&str]) -> Cli {
    let output = support::run_bounded_with_env(
        Path::new(env!("CARGO_BIN_EXE_beam_rt")),
        args,
        &[("ERL_CRASH_DUMP_SECONDS", Some("0"))],
    )
    .unwrap_or_else(|| panic!("`beam_rt {}` did not run to completion", args.join(" ")));
    Cli {
        code: output.status.code().unwrap_or(-1),
        out: String::from_utf8_lossy(&output.stdout).trim_end().to_string(),
        err: String::from_utf8_lossy(&output.stderr).trim_end().to_string(),
    }
}

/// The `cml_probe` fixture: the compiled module and the private scratch directory it sits in.
struct Probe {
    dir: PathBuf,
    beam: PathBuf,
}

impl Probe {
    /// Writes and compiles [`PROBE_ERL`], or `None` — **loudly** — without `erlc`.
    ///
    /// The compiler is discovered on `$PATH` by **filesystem inspection only**
    /// ([`support::find_on_path`]), never by running it.
    fn build() -> Option<Probe> {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let unique = NEXT.fetch_add(1, Ordering::Relaxed);
        let dir = std::env::temp_dir().join(format!(
            "beam_rt_cml_probe_{}_{unique}",
            std::process::id()
        ));
        let Some(erlc) = support::find_on_path("erlc") else {
            support::skip_loudly(BANNER, "no `erlc` on $PATH");
            return None;
        };
        if let Err(error) = std::fs::create_dir_all(&dir) {
            eprintln!("SKIP {BANNER}: cannot create {}: {error}", dir.display());
            return None;
        }
        let source = dir.join("cml_probe.erl");
        if let Err(error) = std::fs::write(&source, PROBE_ERL) {
            eprintln!("SKIP {BANNER}: cannot write {}: {error}", source.display());
            let _ = std::fs::remove_dir_all(&dir);
            return None;
        }
        let dir_arg = dir.to_str().expect("an ASCII temporary path");
        let source_arg = source.to_str().expect("an ASCII temporary path");
        match support::run_bounded(&erlc, &["+deterministic", "-o", dir_arg, source_arg]) {
            Some(output) if output.status.success() => {}
            Some(output) => {
                eprintln!(
                    "SKIP {BANNER}: `erlc` exited with {}: {}",
                    output.status,
                    String::from_utf8_lossy(&output.stderr)
                );
                let _ = std::fs::remove_dir_all(&dir);
                return None;
            }
            None => {
                eprintln!("SKIP {BANNER}: `erlc` did not run to completion");
                let _ = std::fs::remove_dir_all(&dir);
                return None;
            }
        }
        let beam = dir.join("cml_probe.beam");
        if !beam.is_file() {
            eprintln!("SKIP {BANNER}: `erlc` produced no {}", beam.display());
            let _ = std::fs::remove_dir_all(&dir);
            return None;
        }
        Some(Probe { dir, beam })
    }

    /// The fixture's path as the CLI argument it is passed as.
    fn beam(&self) -> &str {
        self.beam.to_str().expect("an ASCII temporary path")
    }

    /// Runs `cml_probe:<function>/0` under the built runtime, through the **`run`** action.
    fn run(&self, function: &str) -> Cli {
        let target = format!("cml_probe:{function}/0");
        beam_rt(&["run", self.beam(), &target])
    }

    /// The oracle's own `~w` rendering of `cml_probe:<function>/0`, or `None` — loudly — when the
    /// oracle cannot answer.
    ///
    /// The oracle loads the **same** compiled fixture through `-pa <scratch dir>`, so the two sides
    /// differ only in the runtime under test.
    fn oracle_renders(&self, function: &str) -> Option<String> {
        let oracle = oracle()?;
        let expr = format!("io:format(\"~w~n\",[cml_probe:{function}()])");
        match support::oracle_eval(&oracle, Some(&self.dir), &expr) {
            Some(answer) => Some(answer),
            None => {
                eprintln!("warning: the oracle could not answer `cml_probe:{function}/0`");
                None
            }
        }
    }
}

impl Drop for Probe {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.dir);
    }
}

/// The `{Name,nofile}` pairs of a rendered `{error,[…]}` answer, **sorted** — the
/// order-insensitive view the multi-failure case compares, because the oracle builds its own list
/// concurrently.
fn failure_set(rendered: &str) -> Vec<String> {
    let mut names: Vec<String> = rendered
        .split('{')
        .filter_map(|chunk| chunk.split_once(",nofile}"))
        .map(|(name, _)| name.to_string())
        .collect();
    names.sort();
    names
}

/// The single-failure and success shapes on a **compiled** module: each is compared byte-for-byte
/// on stdout, and on the exit code, against the live oracle.
///
/// The pre-fix failure mode is pinned too: the bad key entered `code.beam`'s body, which crashed
/// the live `code_server` (`kernel_sup` SUPERVISOR REPORTs on stderr) and raised `badarg` — so an
/// exit code other than 0, a supervisor report, or the runtime's own error line would fail here.
#[test]
fn the_run_route_serves_code_ensure_modules_loaded_like_the_oracle() {
    let Some(probe) = Probe::build() else {
        return;
    };
    for (function, expected) in [
        ("single", "{error,[{no_such_mod_xyz,nofile}]}"),
        ("available", "ok"),
        ("preloaded", "ok"),
    ] {
        let cli = probe.run(function);
        assert_eq!(
            cli.code, 0,
            "`cml_probe:{function}/0` must exit 0 on the `run` route; stderr was: {}",
            cli.err
        );
        assert_eq!(cli.out, expected, "`cml_probe:{function}/0` stdout");
        assert!(
            !cli.err.contains("SUPERVISOR REPORT") && !cli.err.contains("badarg"),
            "`cml_probe:{function}/0` must not reach `code.beam`'s body (which crashes the live \
             code server); stderr was: {}",
            cli.err
        );
        if let Some(answer) = probe.oracle_renders(function) {
            assert_eq!(
                cli.out, answer,
                "the oracle renders `cml_probe:{function}/0` differently"
            );
        }
    }
}

/// The three-failure shape on a **compiled** module: every missing module is reported, and the
/// runtime emits the floor's documented order.
///
/// The oracle's list order is **racy by construction** (its `do_par_recv/3` prepends each
/// per-module result as it arrives), so the oracle is compared as a **set** while the runtime's
/// order is pinned to the documented majority order — the `lists:usort/1` order reversed — which
/// the oracle also produced on the observed runs (any run that answers with it is counted, and at
/// least one must, so the pinned order is never an invention).
#[test]
fn the_run_route_reports_the_missing_modules_in_the_documented_order() {
    let Some(probe) = Probe::build() else {
        return;
    };
    let cli = probe.run("many");
    assert_eq!(
        cli.code, 0,
        "`cml_probe:many/0` must exit 0 on the `run` route; stderr was: {}",
        cli.err
    );
    assert_eq!(
        cli.out,
        "{error,[{cml_missing_c,nofile},{cml_missing_b,nofile},{cml_missing_a,nofile}]}",
        "`cml_probe:many/0` must list every failure in the documented order"
    );
    assert_eq!(
        failure_set(&cli.out),
        vec!["cml_missing_a", "cml_missing_b", "cml_missing_c"],
        "`cml_probe:many/0` lists exactly the three missing modules"
    );

    // The oracle is asked a few times: every answer must list the same failures, and at least one
    // must carry the documented order the runtime emits (the rest may be racy permutations). No
    // answer at all is the loud skip `oracle_renders` already printed.
    let mut answers = Vec::new();
    for _ in 0..5 {
        match probe.oracle_renders("many") {
            Some(answer) => answers.push(answer),
            None => break,
        }
    }
    if answers.is_empty() {
        return;
    }
    for answer in &answers {
        assert_eq!(
            failure_set(answer),
            failure_set(&cli.out),
            "the oracle lists different failures: {answer}"
        );
    }
    let matching = answers
        .iter()
        .filter(|answer| answer.as_str() == cli.out)
        .count();
    assert!(
        matching >= 1,
        "the documented order must be one the oracle produces — it answered {answers:?}, none of \
         which is `{}`",
        cli.out
    );
    if matching < answers.len() {
        eprintln!(
            "note: the oracle's own multi-failure order was racy in this run ({matching} of {} \
             answers carried the documented order)",
            answers.len()
        );
    }
}
