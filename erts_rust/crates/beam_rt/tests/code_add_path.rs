//! The **code-path mutators** (contract A.7) end to end: `code:add_patha/1,2`,
//! `code:add_pathz/1,2`, `code:add_path/1,2` and `code:del_path/1`, driven through the built
//! `beam_rt` binary and cross-checked against the live system Erlang.
//!
//! # Why this suite exists
//!
//! Adding a directory to the code path is only meaningful if the **loader** sees it: the
//! observable contract is that `code:load_file/1` finds a `.beam` in the added directory
//! afterwards, and that `code:get_path/0` really contains it. A runtime that answered `true`
//! from `code:add_patha/1` while its loader kept searching the old path would pass a
//! shape-only test and fail the user. So every assertion here is the *consequence* — a loaded
//! module's return value, the position of the added directory, the untouched path after a
//! refusal — never "the call returned something".
//!
//! # The five observations
//!
//! | Probe | What it pins |
//! |---|---|
//! | the full `add_patha` route in **one** invocation | `true` / directory on the path / `{module,zzq}` / `zzq:answer()` = `42` |
//! | `add_pathz/1` (and the folding `add_path/1`) | the directory lands at the **END** of `code:get_path/0` |
//! | a **missing** directory | `{error,bad_directory}` and `code:get_path/0` **unchanged** |
//! | a **trailing separator** | `add_patha("<Dir>/")` puts `<Dir>` on the path, not `<Dir>/` |
//! | `del_path/1` | `true`, then `false` for the second call, and the directory is gone |
//!
//! The user module is compiled **at test time** with the system `erlc` into a scratch
//! directory (never committed, never inside the repository) and reached only through the
//! in-probe `code:add_patha/1` — so the load really exercises the mutator, not a `-pa` the
//! command line pre-installed. Only an explicit, oracle-verified literal is compared, and the
//! live oracle is asked the **same** probe: a missing toolchain is a **loud skip**, never a
//! silent pass (`support::require_oracle` / `support::skip_loudly`).
//!
//! # Cost
//!
//! Each probe is one `beam_rt -noshell -eval …` invocation plus one oracle invocation of the
//! same probe (~0.4 s and ~0.15 s on this host, whole-process start-up dominated); the bounded
//! fixture build (`erlc`) is shared by the test that needs it. The per-test figures in the doc
//! comments below are single-run figures on a lightly loaded host — a loaded host roughly
//! doubles them, so read them as an order of magnitude, never as a budget. The literal `/2`
//! arity of each mutator (the cache flag) and the `code:del_path(<app>)` by-name form are
//! covered in-crate (`src/native/code/path.rs`), which owns the parser.

// The shared harness is compiled in whole, but this suite uses only its bounded runner and its
// toolchain discovery; the unused remainder is expected here — the same shape `tests/io_scan.rs`
// uses.
#[allow(dead_code)]
mod support;

use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicUsize, Ordering};

/// The executable under test, exactly as the other contract suites drive it.
const BINARY: &str = env!("CARGO_BIN_EXE_beam_rt");

/// The fixture source: a module that is neither preloaded nor under a sticky directory, so
/// `code:load_file/1` loads it (see the sibling `code_load_file.rs` suite for the sticky rule).
const FIXTURE_ERL: &str = r#"%% Generated by `beam_rt/tests/code_add_path.rs` (never committed).
-module(zzq).
-export([answer/0]).

answer() -> 42.
"#;

// ---------------------------------------------------------------------------------------
// The probes
// ---------------------------------------------------------------------------------------

/// The full route in **one** invocation: add the directory, see it on the path, load the
/// module out of it, and call the loaded function. The four answers are the four steps, so a
/// mutator that is a no-op cannot pass.
fn full_route_expr(dir: &Path) -> String {
    format!(
        "D = {d},\n\
         A = code:add_patha(D),\n\
         M = lists:member(D, code:get_path()),\n\
         L = code:load_file(zzq),\n\
         R = zzq:answer(),\n\
         io:format(\"~p ~p ~p ~p~n\", [A, M, L, R]),\n\
         halt(0).",
        d = literal(dir)
    )
}
const FULL_ROUTE_EXPECTED: &str = "true true {module,zzq} 42";

/// `add_pathz/1` appends: the added directory is the **last** entry of the path.
fn add_pathz_expr(dir: &Path) -> String {
    format!(
        "D = {d},\n\
         R = code:add_pathz(D),\n\
         io:format(\"~p ~p ~p~n\", [R, lists:last(code:get_path()) =:= D, \
         lists:member(D, code:get_path())]),\n\
         halt(0).",
        d = literal(dir)
    )
}
const ADD_PATHZ_EXPECTED: &str = "true true true";

/// `add_path/1` is `add_pathz/1` (`code.erl:1075-1077`): it appends too.
fn add_path_expr(dir: &Path) -> String {
    format!(
        "D = {d},\n\
         R = code:add_path(D),\n\
         io:format(\"~p ~p~n\", [R, lists:last(code:get_path()) =:= D]),\n\
         halt(0).",
        d = literal(dir)
    )
}
const ADD_PATH_EXPECTED: &str = "true true";

/// A **missing** directory is `{error,bad_directory}` for both insertion ends, and the path is
/// left **unchanged** (the same `code:get_path/0` list, not merely the same length).
fn bad_directory_expr(missing: &Path) -> String {
    format!(
        "M = {m},\n\
         P0 = code:get_path(),\n\
         R1 = code:add_patha(M),\n\
         R2 = code:add_pathz(M),\n\
         io:format(\"~p ~p ~p ~p~n\", [R1, R2, P0 =:= code:get_path(), \
         lists:member(M, code:get_path())]),\n\
         halt(0).",
        m = literal(missing)
    )
}
const BAD_DIRECTORY_EXPECTED: &str = "{error,bad_directory} {error,bad_directory} true false";

/// A **trailing separator** is normalized away: the added directory is `Dir`, not `Dir/`.
fn trailing_separator_expr(dir: &Path) -> String {
    format!(
        "D = {d},\n\
         R = code:add_patha(D ++ \"/\"),\n\
         io:format(\"~p ~p ~p~n\", [R, lists:member(D, code:get_path()), \
         lists:member(D ++ \"/\", code:get_path())]),\n\
         halt(0).",
        d = literal(dir)
    )
}
const TRAILING_SEPARATOR_EXPECTED: &str = "true true false";

/// `del_path/1` removes the directory (`true`), is idempotent in the oracle's negative sense
/// (`false` for the second call), and really leaves the path.
fn del_path_expr(dir: &Path) -> String {
    format!(
        "D = {d},\n\
         A = code:add_patha(D),\n\
         R1 = code:del_path(D),\n\
         R2 = code:del_path(D),\n\
         io:format(\"~p ~p ~p ~p~n\", [A, R1, R2, lists:member(D, code:get_path())]),\n\
         halt(0).",
        d = literal(dir)
    )
}
const DEL_PATH_EXPECTED: &str = "true true false false";

// ---------------------------------------------------------------------------------------
// Running the two runtimes
// ---------------------------------------------------------------------------------------

/// One finished run: its exit code and trimmed output.
struct Ran {
    code: i32,
    out: String,
    err: String,
}

impl Ran {
    fn of(output: Output) -> Ran {
        Ran {
            code: output.status.code().unwrap_or(-1),
            out: String::from_utf8_lossy(&output.stdout).trim().to_string(),
            err: String::from_utf8_lossy(&output.stderr).trim().to_string(),
        }
    }
}

/// `<beam_rt> -noshell -eval expr`, bounded by [`support::PROBE_TIMEOUT`] so a probe that
/// blocks is killed and reaped rather than hanging the suite.
fn beam_rt_eval(expr: &str) -> Ran {
    let output = support::run_bounded(Path::new(BINARY), &["-noshell", "-eval", expr])
        .unwrap_or_else(|| panic!("`{BINARY} -noshell -eval …` could not be run to completion"));
    Ran::of(output)
}

/// The printer wraps a term longer than its line width onto continuation lines; joining the
/// wrapped lines back (dropping only the indentation the wrap introduced) makes the comparison
/// independent of the wrap point. It is safe because **no compared value contains a space** —
/// the probe formats four separate values, so the spaces in the expectation are *between* them
/// and live inside one line.
fn unwrapped(text: &str) -> String {
    text.lines().map(str::trim_start).collect()
}

/// Asserts the runtime answers exactly `expected` for `expr`, and that the live oracle answers
/// `expected` too (per line — the oracle's own refusal paths also log).
///
/// The runtime's answer is asserted **first**, so a divergence is reported even when no oracle
/// is installed; a missing — or unanswerable — oracle is then a loud note, never a silent pass.
fn assert_agrees(oracle: &Path, expr: &str, expected: &str, what: &str) {
    let ours = beam_rt_eval(expr);
    assert_eq!(
        ours.code, 0,
        "beam_rt: {what}: the run must exit 0 — stderr:\n{}",
        ours.err
    );
    assert!(
        ours.err.is_empty(),
        "beam_rt: {what}: a successful run must be silent on stderr — {}",
        ours.err
    );
    assert_eq!(
        unwrapped(&ours.out),
        expected,
        "beam_rt: {what} (stdout {:?})",
        ours.out
    );

    match support::oracle_eval(oracle, None, expr) {
        Some(theirs) => assert!(
            theirs.lines().any(|line| line.trim() == expected),
            "the system erl must print `{expected}` for {what}; it printed:\n{theirs}"
        ),
        None => eprintln!("warning: the oracle could not answer `{what}` — not compared"),
    }
}

// ---------------------------------------------------------------------------------------
// The compiled fixture
// ---------------------------------------------------------------------------------------

/// A private scratch directory, removed when the test ends.
///
/// It holds the compiled `zzq.beam` (built by the system `erlc`) and, for the
/// `add_path/1` probe, a second empty directory for a second entry.
struct Fixture {
    dir: PathBuf,
}

impl Drop for Fixture {
    fn drop(&mut self) {
        if let Err(error) = std::fs::remove_dir_all(&self.dir) {
            eprintln!(
                "warning: could not remove the fixture dir {}: {error}",
                self.dir.display()
            );
        }
    }
}

/// The compiler: a sibling of the resolved oracle first (the same installation), then `$PATH`.
fn resolve_erlc() -> Option<PathBuf> {
    if let Some(dir) = support::resolve_oracle().as_deref().and_then(Path::parent) {
        let candidate = dir.join("erlc");
        if support::is_executable(&candidate) {
            return Some(candidate);
        }
    }
    support::find_on_path("erlc")
}

/// Compiles [`FIXTURE_ERL`] into a fresh scratch directory, or `None` after a loud skip when
/// the toolchain cannot do it.
///
/// The directory is unique **per call**, not merely per process: cargo runs the tests of one
/// binary on parallel threads, and a shared directory would let one test's cleanup delete the
/// fixture another test is still using.
fn build_fixture(erlc: &Path) -> Option<Fixture> {
    static NEXT: AtomicUsize = AtomicUsize::new(0);
    let unique = NEXT.fetch_add(1, Ordering::Relaxed);
    let dir = std::env::temp_dir().join(format!(
        "beam_rt_code_add_path_{}_{unique}",
        std::process::id()
    ));
    if let Err(error) = std::fs::create_dir_all(&dir) {
        support::skip_loudly(
            "code_add_path",
            &format!("cannot prepare {}: {error}", dir.display()),
        );
        return None;
    }
    let source = dir.join("zzq.erl");
    if let Err(error) = std::fs::write(&source, FIXTURE_ERL) {
        support::skip_loudly(
            "code_add_path",
            &format!("cannot write {}: {error}", source.display()),
        );
        return None;
    }
    let output = match Command::new(erlc).arg("-o").arg(&dir).arg(&source).output() {
        Ok(output) => output,
        Err(error) => {
            support::skip_loudly("code_add_path", &format!("cannot run `erlc`: {error}"));
            return None;
        }
    };
    if !output.status.success() {
        support::skip_loudly(
            "code_add_path",
            &format!("`erlc` exited with {}", output.status),
        );
        return None;
    }
    if !dir.join("zzq.beam").is_file() {
        support::skip_loudly("code_add_path", "`erlc` produced no zzq.beam");
        return None;
    }
    Some(Fixture { dir })
}

/// The **Erlang string literal** for `path`: the temporary names this suite builds are ASCII,
/// which Rust's `Debug` and Erlang's string syntax quote identically.
fn literal(path: &Path) -> String {
    format!("{:?}", path.to_str().expect("an ASCII temporary path"))
}

/// The oracle plus the compiled fixture, or `None` after a loud skip.
fn fixture() -> Option<(PathBuf, Fixture)> {
    let oracle = support::require_oracle("code_add_path")?;
    let erlc = match resolve_erlc() {
        Some(erlc) => erlc,
        None => {
            support::skip_loudly("code_add_path", "no `erlc` on $PATH");
            return None;
        }
    };
    let fixture = build_fixture(&erlc)?;
    Some((oracle, fixture))
}

// ---------------------------------------------------------------------------------------
// The tests
// ---------------------------------------------------------------------------------------

/// The full route in **one** invocation: `code:add_patha/1` puts the directory on the path,
/// `code:load_file/1` loads the module from it, and the loaded function answers the value the
/// system `erlc` compiled. Measured wall time: ~1.5 s (the fixture build, the runtime
/// invocation and the oracle's).
#[test]
fn the_full_add_patha_route_agrees_with_the_oracle() {
    let Some((oracle, fixture)) = fixture() else {
        return;
    };
    assert_agrees(
        &oracle,
        &full_route_expr(&fixture.dir),
        FULL_ROUTE_EXPECTED,
        "the full code:add_patha/1 → code:load_file/1 → call route",
    );
}

/// `code:add_pathz/1` — and `code:add_path/1`, which `code.erl:1075-1077` folds into it —
/// **append**: the added directory is the last entry of `code:get_path/0`. Measured wall time:
/// ~2.7 s (five invocations on top of the fixture build).
#[test]
fn add_pathz_and_add_path_append_the_directory_to_the_end() {
    let Some((oracle, fixture)) = fixture() else {
        return;
    };
    assert_agrees(
        &oracle,
        &add_pathz_expr(&fixture.dir),
        ADD_PATHZ_EXPECTED,
        "code:add_pathz/1 appends",
    );

    // A second, empty directory: `add_path/1` must append it too (an entry already present
    // would be re-appended, so a fresh directory keeps the answer a plain `true`).
    let second = fixture.dir.join("second_entry");
    if let Err(error) = std::fs::create_dir_all(&second) {
        support::skip_loudly(
            "code_add_path",
            &format!("cannot prepare {}: {error}", second.display()),
        );
        return;
    }
    assert_agrees(
        &oracle,
        &add_path_expr(&second),
        ADD_PATH_EXPECTED,
        "code:add_path/1 appends",
    );
}

/// A missing directory is the code server's `{error,bad_directory}` for both insertion ends,
/// and the path is left **unchanged** — the same `code:get_path/0` list, not merely the same
/// length. Measured wall time: ~1.6 s.
#[test]
fn a_missing_directory_is_bad_directory_and_leaves_the_path_unchanged() {
    let Some((oracle, fixture)) = fixture() else {
        return;
    };
    // The fixture directory exists; a child of it does not.
    let missing = fixture.dir.join("no_such_dir");
    assert!(!missing.exists(), "the probe path must not exist");
    assert_agrees(
        &oracle,
        &bad_directory_expr(&missing),
        BAD_DIRECTORY_EXPECTED,
        "code:add_patha/1 and code:add_pathz/1 of a missing directory",
    );
}

/// A trailing separator is normalized away (`code_server`'s `get_name/1`): `add_patha("<Dir>/")`
/// puts `"<Dir>"` on the path, and the un-normalized spelling is **not** a path entry.
/// Measured wall time: ~1.6 s.
#[test]
fn a_trailing_separator_is_normalized_away() {
    let Some((oracle, fixture)) = fixture() else {
        return;
    };
    assert_agrees(
        &oracle,
        &trailing_separator_expr(&fixture.dir),
        TRAILING_SEPARATOR_EXPECTED,
        "code:add_patha/1 of a directory with a trailing separator",
    );
}

/// `code:del_path/1` removes the directory — `true` the first time, `false` the second (it is
/// already gone) — and the path really no longer holds it. Measured wall time: ~1.4 s.
#[test]
fn del_path_removes_the_directory_and_then_answers_false() {
    let Some((oracle, fixture)) = fixture() else {
        return;
    };
    assert_agrees(
        &oracle,
        &del_path_expr(&fixture.dir),
        DEL_PATH_EXPECTED,
        "code:del_path/1",
    );
}
