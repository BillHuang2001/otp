/// The `.so` imports exactly the `enif_*` symbols the runtime must publish, so a `dlopen`
/// failure is diagnosed instead of guessed at.
#[test]
fn the_binary_exports_the_enif_symbols_enif_send_imports() {
    // `nm` is not assumed; the real assertion is that each test's run loads the library at
    // all (a missing symbol means `dlopen` fails and `load_nif/2` reports `load_failed`).
    // This test documents the list and asserts the source actually imports them.
    for symbol in SEND_NIF_IMPORTS {
        assert!(
            SEND_NIF_C.contains(symbol),
            "the fixture must import {symbol}"
        );
    }
}

/// **The `msg_env == NULL` form delivers.** `enif_send(env, &to, NULL, msg)` to a process
/// parked in `receive` answers the C's `1` and the message really reaches the mailbox.
///
/// Oracle: `{1, delivered_by_the_nif}` (the same `.so`/`.beam` under the system `erl`).
#[test]
fn the_null_msg_env_form_delivers_to_a_waiting_process() {
    let Some(fixture) = build_fixture("null_env") else {
        return;
    };
    let oracle = run_oracle(&fixture, "null_env");
    let run = run_rust(&fixture, "null_env");
    assert_eq!(
        run.stdout.trim(),
        "{1,delivered_by_the_nif}",
        "send_caller:null_env/1 must report the send's 1 and the delivered message; \
         status={} stderr={}",
        run.status,
        run.stderr
    );
    assert_eq!(run.status, 0, "stderr={}", run.stderr);
    if let Some(oracle) = oracle {
        assert_eq!(
            run.stdout.trim(),
            oracle,
            "the oracle's own answer is the reference"
        );
    }
    fixture.cleanup();
}

