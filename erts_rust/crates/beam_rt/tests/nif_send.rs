/// The C compiler to use: `$CC` when set, else `cc`.
fn cc() -> String {
    std::env::var("CC").unwrap_or_else(|_| "cc".to_string())
}

/// Whether a C compiler is available.
fn cc_available() -> bool {
    Command::new(cc())
        .arg("--version")
        .output()
        .map(|output| output.status.success())
        .unwrap_or(false)
}

/// A compiled `send_nif` library + its caller module, in one scratch directory.
struct Fixture {
    /// The scratch directory holding the sources and the compiled artifacts.
    dir: PathBuf,
    /// The compiled `send_caller.beam` (the `run` file argument).
    caller: PathBuf,
}

impl Fixture {
    /// The path handed to `erlang:load_nif/2` (the `.so` **without** its suffix — the loader
    /// appends `.so`).
    fn load_path(&self) -> PathBuf {
        self.dir.join("send_nif")
    }

    /// Removes the scratch directory (`cc`/`erlc` output is not source).
    fn cleanup(self) {
        match std::fs::remove_dir_all(&self.dir) {
            Ok(()) => {}
            // The directory is ours and disposable; a failure is reported, not hidden.
            Err(error) => println!("note: could not remove {}: {error}", self.dir.display()),
        }
    }
}

/// Compiles the C fixture into `<scratch>/send_nif.so` and both Erlang modules into
/// `<scratch>/*.beam`, or `None` when a host facility is missing (the caller returns early —
/// **loudly**).
fn build_fixture(label: &str) -> Option<Fixture> {
    let Some(include) = erl_include_dir() else {
        skip(&format!("nif_send/{label}: no erl_nif.h include directory found"));
        return None;
    };
    if !cc_available() {
        skip(&format!(
            "nif_send/{label}: no C compiler ({} / $CC) available",
            cc()
        ));
        return None;
    }
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let dir = std::env::temp_dir().join(format!(
        "beam_rt_nif_send_{label}_{}_{n}",
        std::process::id()
    ));
    let c_src = dir.join("send_nif.c");
    if let Err(error) =
        std::fs::create_dir_all(&dir).and_then(|()| std::fs::write(&c_src, SEND_NIF_C))
    {
        skip(&format!(
            "nif_send/{label}: cannot prepare {}: {error}",
            dir.display()
        ));
        return None;
    }
    let erl_paths: Vec<PathBuf> = [("send_nif", SEND_NIF_ERL), ("send_caller", SEND_CALLER_ERL)]
        .iter()
        .map(|(stem, source)| {
            let path = dir.join(format!("{stem}.erl"));
            if let Err(error) = std::fs::write(&path, source) {
                skip(&format!(
                    "nif_send/{label}: cannot write {}: {error}",
                    path.display()
                ));
            }
            path
        })
        .collect();
    // The shared object: `cc -shared -fPIC -I<include> -o <dir>/send_nif.so <dir>/send_nif.c`.
    let output = Command::new(cc())
        .arg("-shared")
        .arg("-fPIC")
        .arg(format!("-I{}", include.display()))
        .arg("-o")
        .arg(dir.join("send_nif.so"))
        .arg(&c_src)
        .output();
    match output {
        Ok(output) if output.status.success() => {}
        Ok(output) => {
            skip(&format!(
                "nif_send/{label}: cc failed ({}):\n{}",
                output.status,
                String::from_utf8_lossy(&output.stderr)
            ));
            return None;
        }
        Err(error) => {
            skip(&format!(
                "nif_send/{label}: could not run the C compiler: {error}"
            ));
            return None;
        }
    }
    // The Erlang modules: `erlc -o <dir> <dir>/<stem>.erl …`.
    let output = Command::new("erlc")
        .arg("-o")
        .arg(&dir)
        .args(&erl_paths)
        .output();
    match output {
        Ok(output) if output.status.success() => {}
        Ok(output) => {
            skip(&format!(
                "nif_send/{label}: erlc failed ({}):\n{}",
                output.status,
                String::from_utf8_lossy(&output.stderr)
            ));
            return None;
        }
        Err(error) => {
            skip(&format!("nif_send/{label}: could not run `erlc`: {error}"));
            return None;
        }
    }
    let caller = dir.join("send_caller.beam");
    if !caller.is_file() {
        skip(&format!(
            "nif_send/{label}: erlc produced no {}",
            caller.display()
        ));
        return None;
    }
    Some(Fixture { dir, caller })
}

// ---------------------------------------------------------------------------------------------
// Running the fixture under both runtimes
// ---------------------------------------------------------------------------------------------
/// One run's outcome: its exit status and its stdout/stderr.
struct Run {
    /// The process exit code (`-1` when it was killed by a signal).
    status: i32,
    /// Everything the run wrote to stdout.
    stdout: String,
    /// Everything the run wrote to stderr.
    stderr: String,
}

/// Runs `program args…` to completion (bounded), capturing its streams; `None` on a spawn
/// error or a timeout.
fn run_bounded(program: &Path, args: &[String]) -> Option<Run> {
    let mut child = Command::new(program)
        .args(args)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .ok()?;
    let deadline = Instant::now() + Duration::from_secs(60);
    loop {
        match child.try_wait() {
            Ok(Some(status)) => {
                let output = child.wait_with_output().ok()?;
                return Some(Run {
                    status: status.code().unwrap_or(-1),
                    stdout: String::from_utf8_lossy(&output.stdout).into_owned(),
                    stderr: String::from_utf8_lossy(&output.stderr).into_owned(),
                });
            }
            Ok(None) => {
                if Instant::now() >= deadline {
                    let _ = child.kill();
                    let _ = child.wait();
                    return None;
                }
                std::thread::sleep(Duration::from_millis(10));
            }
            Err(_) => return None,
        }
    }
}

/// The `-noshell -pa <dir> run <send_caller.beam> send_caller:<function>/1 "<load-path>"`
/// invocation for `beam_rt`.
fn rust_args(fixture: &Fixture, function: &str) -> Vec<String> {
    vec![
        "-noshell".to_string(),
        "-pa".to_string(),
        fixture.dir.display().to_string(),
        "run".to_string(),
        fixture.caller.display().to_string(),
        format!("send_caller:{function}/1"),
        // The `run` argument grammar parses a bare token as an atom and only a quoted token as
        // an Erlang char list; `erlang:load_nif/2` requires a list or a binary.
        format!("\"{}\"", fixture.load_path().display()),
    ]
}

/// The oracle's `-noshell -pa <dir> -eval 'io:format("~p~n",[send_caller:<function>("/…")])'`
/// invocation — the same `.so` and `.beam`, under the system `erl`.
fn oracle_args(fixture: &Fixture, function: &str) -> Vec<String> {
    let path = fixture.load_path().display().to_string();
    vec![
        "-noshell".to_string(),
        "-pa".to_string(),
        fixture.dir.display().to_string(),
        "-eval".to_string(),
        format!("io:format(\"~p~n\",[send_caller:{function}(\"{path}\")])"),
        "-s".to_string(),
        "init".to_string(),
        "stop".to_string(),
    ]
}

/// Runs the fixture's `function/1` under `beam_rt`, asserting the binary is the one built.
fn run_rust(fixture: &Fixture, function: &str) -> Run {
    let program = PathBuf::from(env!("CARGO_BIN_EXE_beam_rt"));
    run_bounded(&program, &rust_args(fixture, function)).expect("beam_rt terminates")
}

/// Runs the fixture's `function/1` under the oracle; `None` when `erl` is not on `$PATH` or
/// the probe could not answer (the caller reports a loud skip).
fn run_oracle(fixture: &Fixture, function: &str) -> Option<String> {
    let Some(oracle) = which_erl() else {
        skip("nif_send: no `erl` on PATH for the oracle cross-check");
        return None;
    };
    let run = run_bounded(&oracle, &oracle_args(fixture, function))?;
    assert!(
        run.status == 0,
        "the oracle run of send_caller:{function}/1 failed: status={} stderr={}",
        run.status,
        run.stderr
    );
    Some(run.stdout.trim().to_string())
}

