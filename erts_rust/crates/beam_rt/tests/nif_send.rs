//! `enif_send` end to end (contract A.3): a real C NIF `.so` sends a message to **another
//! Erlang process**, under both of the C's forms, and the message really is delivered.
//!
//! Everything is real: the C source below is compiled at test time with the host C compiler
//! against the host `erl_nif.h`, the Erlang modules with the host `erlc`, and the run is the
//! **built binary** ([`CARGO_BIN_EXE_beam_rt`]) exactly as a user would drive it. The same
//! `.so`/`.beam` are run under the system `erl` as the oracle, so the pinned numbers are the
//! oracle's own.
//!
//! # The two forms, and the C's answers
//!
//! `enif_send(env, &to, NULL, term)` sends a term that belongs to the **calling** env; the
//! `msg_env` form (`enif_alloc_env` → build → `enif_send(env, &to, msg_env, copy)`) sends a
//! term owned by a **message** env. Both answer the C's `1` when the message was queued and
//! `0` when it was not — a receiver the runtime has no process for is the `0`
//! (`erl_nif.c:876-877`: `rp = erts_proc_lookup(receiver); if (!rp) return 0;`).
//!
//! # Skip policy
//!
//! Three host facilities are needed (a C compiler, the host `erl_nif.h`, the host `erlc`).
//! When one is missing — or the oracle `erl` is not on `$PATH` — the test prints a **loud**
//! banner and returns; it never silently passes.
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::{Duration, Instant};

/// The C fixture: the two `enif_send` forms plus the dead-pid probe.
///
/// `null_env/2` is the `msg_env == NULL` form — the message term belongs to the call env.
/// `msg_env/2` is the message-env form: the term is built on a fresh `enif_alloc_env` env and
/// copied into it with `enif_make_copy`, exactly the idiom the C documents.
/// `to_dead/1` sends to whatever pid it is given (a pid whose process is gone ⇒ the C's `0`).
const SEND_NIF_C: &str = r#"
#include <erl_nif.h>

static ERL_NIF_TERM null_env(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    ErlNifPid to;
    (void) argc;
    if (!enif_get_local_pid(env, argv[0], &to)) return enif_make_atom(env, "not_a_pid");
    return enif_make_int(env, enif_send(env, &to, NULL, argv[1]));
}

static ERL_NIF_TERM msg_env(ErlNifEnv* env, int argc, const ERL_NIF_TERM argv[]) {
    ErlNifPid to;
    ErlNifEnv* menv;
    ERL_NIF_TERM copy;
    int sent;
    (void) argc;
    if (!enif_get_local_pid(env, argv[0], &to)) return enif_make_atom(env, "not_a_pid");
    menv = enif_alloc_env();
    if (menv == NULL) return enif_make_atom(env, "unsupported_enif_alloc_env");
    copy = enif_make_copy(menv, argv[1]);
    sent = enif_send(env, &to, menv, copy);
    enif_free_env(menv);
    return enif_make_int(env, sent);
}

static int load(ErlNifEnv* env, void** priv, ERL_NIF_TERM info) {
    (void) env; (void) info;
    *priv = NULL;
    return 0;
}

static ErlNifFunc send_nif_funcs[] = {
    {"null_env", 2, null_env, 0},
    {"msg_env", 2, msg_env, 0}
};

ERL_NIF_INIT(send_nif, send_nif_funcs, load, NULL, NULL, NULL)
"#;

/// The NIF module: `init/1` loads the library, the two sends are NIF stubs.
const SEND_NIF_ERL: &str = r#"%% Generated by `beam_rt/tests/nif_send.rs` (never committed).
-module(send_nif).
-export([init/1, null_env/2, msg_env/2]).
init(Path) -> erlang:load_nif(Path, 0).
null_env(_To, _Msg) -> erlang:nif_error(not_loaded).
msg_env(_To, _Msg) -> erlang:nif_error(not_loaded).
"#;

/// The caller. Every `send_nif:*` call is an **external** call, which is where the runtime's
/// NIF dispatch lives (a local call is resolved in-machine and would run the stub).
///
/// `null_env/1` and `msg_env/1` build the same shape: a child parks in `receive`, the parent
/// sends to it through the NIF, and the child echoes what it got back to the parent — so the
/// answer is `{Sent, Delivered}`, where `Delivered` is `timeout` when nothing arrived.
/// `self_env/1` sends to the **calling** process itself and reads the message from its own
/// mailbox (the C's `c_p == rp` arm). `dead_pid/1` sends to a pid whose process has already
/// exited (the parent waits for the `{'EXIT', …}` so the death is complete, then sends).
const SEND_CALLER_ERL: &str = r#"%% Generated by `beam_rt/tests/nif_send.rs` (never committed).
-module(send_caller).
-export([null_env/1, msg_env/1, self_env/1, dead_pid/1]).

null_env(Path) -> roundtrip(Path, fun send_nif:null_env/2).
msg_env(Path) -> roundtrip(Path, fun send_nif:msg_env/2).

roundtrip(Path, Send) ->
    ok = send_nif:init(Path),
    Parent = self(),
    Waiter = spawn(fun() ->
        Parent ! {ready, self()},
        receive Msg -> Parent ! {echo, Msg} end
    end),
    receive {ready, Waiter} -> ok end,
    Sent = Send(Waiter, delivered_by_the_nif),
    Delivered =
        receive {echo, What} -> What
        after 5000 -> timeout
        end,
    {Sent, Delivered}.

self_env(Path) ->
    ok = send_nif:init(Path),
    Sent = send_nif:null_env(self(), loopback),
    Delivered =
        receive What -> What
        after 5000 -> timeout
        end,
    {Sent, Delivered}.

dead_pid(Path) ->
    ok = send_nif:init(Path),
    process_flag(trap_exit, true),
    Gone = spawn(fun() -> ok end),
    receive {'EXIT', Gone, _} -> ok after 5000 -> ok end,
    send_nif:null_env(Gone, nobody_home).
"#;

/// The `enif_*` symbols the fixture `.so` imports: the runtime must export them as dynamic
/// symbols for `dlopen(RTLD_NOW)` to bind the library.
const SEND_NIF_IMPORTS: &[&str] = &[
    "enif_get_local_pid",
    "enif_make_atom",
    "enif_make_copy",
    "enif_make_int",
    "enif_alloc_env",
    "enif_free_env",
    "enif_send",
];

/// Print a loud skip banner (never a silent pass).
fn skip(reason: &str) {
    println!("================================================================");
    println!("SKIP: {reason}");
    println!("================================================================");
}

// ---------------------------------------------------------------------------------------------
// Locating the host `erl_nif.h`
// ---------------------------------------------------------------------------------------------
/// The header the include-directory search keys on.
const HEADER: &str = "erl_nif.h";

/// Whether `dir` holds a readable `erl_nif.h`.
fn has_header(dir: &Path) -> bool {
    dir.join(HEADER).is_file()
}

/// The first `erl` executable on `PATH`.
fn which_erl() -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|dir| dir.join("erl"))
        .find(|candidate| candidate.is_file())
}

/// Canonicalize the `erl` on `PATH` and take the sibling `include` of its `erts-*` directory.
fn from_path_erl() -> Option<PathBuf> {
    let erl = which_erl()?.canonicalize().ok()?;
    let bin = erl.parent()?;
    let erts = bin.parent()?;
    if bin.file_name()? != "bin" || !erts.file_name()?.to_string_lossy().starts_with("erts-") {
        return None;
    }
    let include = erts.join("include");
    has_header(&include).then_some(include)
}

/// Search one installation root for an include directory holding `erl_nif.h`.
fn search_root(root: &Path) -> Option<PathBuf> {
    let direct = root.join("include");
    if has_header(&direct) {
        return Some(direct);
    }
    let lib_erlang = root.join("lib").join("erlang");
    for base in [root.to_path_buf(), lib_erlang.clone()] {
        let Ok(entries) = std::fs::read_dir(&base) else {
            continue;
        };
        for entry in entries.flatten() {
            if !entry.file_name().to_string_lossy().starts_with("erts-") {
                continue;
            }
            let include = entry.path().join("include");
            if has_header(&include) {
                return Some(include);
            }
        }
    }
    let include = lib_erlang.join("include");
    has_header(&include).then_some(include)
}

/// The standard installation roots to probe.
fn standard_roots() -> Vec<PathBuf> {
    let mut roots = Vec::new();
    if let Some(top) = std::env::var_os("ERL_TOP") {
        roots.push(PathBuf::from(top));
    }
    for base in [
        "/usr/lib/erlang",
        "/usr/local/lib/erlang",
        "/usr/lib64/erlang",
        "/opt/erlang",
    ] {
        roots.push(PathBuf::from(base));
    }
    roots
}

/// Locate the host `erl_nif.h` include directory; `None` when it is not installed.
fn erl_include_dir() -> Option<PathBuf> {
    from_path_erl().or_else(|| standard_roots().into_iter().find_map(|root| search_root(&root)))
}

// ---------------------------------------------------------------------------------------------
// The compiled fixture
