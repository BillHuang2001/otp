/// The atoms these cases resolve: the item names, the produced values and the fixture's
/// module/lambda names.
fn seeded_atoms() -> AtomTable {
    let mut atoms = AtomTable::new();
    atoms.seed([
        "true",
        "false",
        "ok",
        "undefined",
        "external",
        "local",
        "nonode@nohost",
        MODULE,
        NAME,
        "arity",
        "module",
        "name",
        "new_uniq",
        "index",
        "uniq",
        "type",
        "env",
        "pid",
    ]);
    atoms
}

fn make_ctx<'a>(heap: &'a mut Heap, atoms: &'a AtomTable) -> BifContext<'a> {
    BifContext::new(heap, atoms, ProcessId::new(1, 0))
}

fn call(
    reg: &BifRegistry,
    ctx: &mut BifContext<'_>,
    name: &str,
    args: &[Eterm],
) -> BeamResult<Eterm> {
    reg.call("erlang", name, args.len() as u32, ctx, args)
}

/// The `i`-th (1-based) element of a tuple, through the registered `erlang:element/2`.
fn elem(reg: &BifRegistry, ctx: &mut BifContext<'_>, tuple: Eterm, i: i64) -> Eterm {
    reg.call("erlang", "element", 2, ctx, &[make_small(i), tuple])
        .expect("element/2")
}

/// The name of an atom term, resolved through `atoms`.
fn atom_name<'a>(atoms: &'a AtomTable, term: Eterm) -> &'a str {
    atoms
        .name(atom_val(term))
        .unwrap_or_else(|| panic!("term {term:?} is not a seeded atom"))
}

/// `fun_info(F, Item)` → `(item-tag, value)`.
fn fun_info_pair(
    reg: &BifRegistry,
    ctx: &mut BifContext<'_>,
    fun: Eterm,
    item: &str,
) -> (Eterm, Eterm) {
    let item_term = ctx.atom(item).expect("seeded item atom");
    let info = call(reg, ctx, "fun_info", &[fun, item_term]).expect("fun_info/2");
    assert_eq!(
        reg.call("erlang", "tuple_size", 1, ctx, &[info])
            .expect("tuple_size/1"),
        make_small(2),
        "fun_info/2 must return a 2-tuple"
    );
    (elem(reg, ctx, info, 1), elem(reg, ctx, info, 2))
}

/// A `LocalFunIdentity` stub answering the wrapped identity for every term (what a
/// runtime supplies for a loaded module's `make_fun3` closure).
struct StubIdentity(beam_codec::FunIdentity);

impl beam_bifs::LocalFunIdentity for StubIdentity {
    fn local_fun_identity(
        &mut self,
        _term: Eterm,
    ) -> BeamResult<Option<beam_codec::FunIdentity>> {
        Ok(Some(self.0))
    }
}

/// A `LocalFunIdentity` stub answering `None` — the defining module is not loadable
/// here, i.e. the second oracle run's view of `fiprobe`.
struct StubNone;

impl beam_bifs::LocalFunIdentity for StubNone {
    fn local_fun_identity(
        &mut self,
        _term: Eterm,
    ) -> BeamResult<Option<beam_codec::FunIdentity>> {
        Ok(None)
    }
}

/// A `make_fun3` (`FunKind::Local`) fun term plus the storage owning its words
/// (`[header, uniq, index, env…]`, the frozen layout; `header = FUN_SUBTAG | arity << 8
/// | num_free << 16`).
fn local_fun(arity: u32, uniq: u64, index: u32, env: &[Eterm]) -> (Box<[Eterm]>, Eterm) {
    let header = beam_term::FUN_SUBTAG
        | ((arity as usize) << 8)
        | ((env.len() as usize) << beam_term::fun::FUN_HEADER_ENV_SIZE_OFFS);
    let mut words: Vec<Eterm> = vec![
        Eterm::from_raw(header),
        Eterm::from_raw(uniq as usize),
        Eterm::from_raw(index as usize),
    ];
    words.extend_from_slice(env);
    let words = words.into_boxed_slice();
    let term = beam_term::make_boxed(words.as_ptr());
    (words, term)
}

/// The creator pid every fixture fun carries (this node's own `<0.0.0>`).
fn creator(atoms: &AtomTable) -> FunPid {
    FunPid {
        node: atoms.lookup("nonode@nohost").expect("seeded node"),
        number: 0,
        serial: 0,
        creation: 0,
    }
}

