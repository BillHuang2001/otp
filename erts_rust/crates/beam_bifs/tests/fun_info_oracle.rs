//! Live-oracle cross-check for `erlang:fun_info_mfa/1` on the two fun kinds whose MFA
//! is *not* spelled out in the term — a compiled `make_fun3` closure and a
//! `NEW_FUN_EXT`-decoded fun — together with the `arity`/`name` items the same
//! closures report.
//!
//! A `fiprobe` module (`mk(X) -> fun(Y, Z) -> X + Y + Z end.`) is compiled with `erlc`
//! into a `$TMPDIR` scratch directory and driven under the **live system oracle**; this
//! crate then builds the equivalent frozen-layout terms (a `make_fun3` fun through
//! [`local_fun`], a `NEW_FUN_EXT` fun through `beam_codec::term::make_fun_imported`,
//! both from the oracle's own wire fields) and asks its **registry** for the same four
//! answers:
//!
//! * `erlang:fun_info_mfa(F)` ⇒ `{fiprobe,'-mk/1-fun-0-',2}` — the seam-attributed
//!   module and lambda name plus the *header's* arity (`beam_term::fun::fun_arity`), not
//!   the closure's `num_free` capture count;
//! * `erlang:fun_info(F, arity)` ⇒ `{arity,2}` — unchanged by the closure's one capture;
//! * `erlang:fun_info(F, name)` ⇒ `{name,'-mk/1-fun-0-'}`;
//! * `erlang:fun_info_mfa(I)` of the `NEW_FUN_EXT` round trip ⇒ `{fiprobe,[],2}`, the
//!   C's `mfa == NULL` arm — which the oracle only takes when the *reading* VM cannot
//!   load `fiprobe` (`erts_get_fun_mfa` resolves against the loaded modules), so the
//!   image is produced by the first oracle run and decoded by a **second** one started
//!   without the fixture on its code path. This side mirrors that with a
//!   `LocalFunIdentity` that answers `None`.
//!
//! Every expected value therefore has two independent sources: the oracle's transcript
//! (parsed as machine-readable `key=value` lines, with the two `fun_info_mfa/1` results
//! additionally pinned as literal strings) and this crate's own registry answer, which
//! the test asserts are the same. It never asserts a value against itself.
//!
//! It is **fail-loud in the crate's live-oracle style**: with no usable `erl`/`erlc` it
//! prints a loud banner and returns — which is *not* a pass — and once the toolchain
//! runs, any oracle/grep/compile failure panics with the transcript attached.
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use beam_alloc::Heap;
use beam_bifs::{default_registry, BifContext, BifRegistry};
use beam_common::Result as BeamResult;
use beam_process::ProcessId;
use beam_term::fun::FunPid;
use beam_term::{atom_val, make_small, signed_value, AtomTable, Eterm, NIL};

/// The fixture source, compiled into a scratch directory by `erlc`.
///
/// `mk/1` returns a two-parameter closure with one capture, so the `arity` item and
/// `fun_info_mfa/1`'s third element must both report `2` while `env` holds one term —
/// the split that distinguishes the header's **call** arity from `num_free`.
const FIPROBE_ERL: &str = r#"%% Generated by `beam_bifs/tests/fun_info_oracle.rs` (never committed).
-module(fiprobe).
-export([mk/1]).

mk(X) -> fun(Y, Z) -> X + Y + Z end.
"#;

/// The fixture module's name.
const MODULE: &str = "fiprobe";
/// The generated name of `mk/1`'s only lambda (the oracle's `{name,…}`).
const NAME: &str = "-mk/1-fun-0-";

// ---------------------------------------------------------------------------
// The oracle toolchain
// ---------------------------------------------------------------------------

/// Whether `path` is an executable file (`$ERTS_ORACLE` may point at one).
#[cfg(unix)]
fn is_executable(path: &Path) -> bool {
    use std::os::unix::fs::PermissionsExt;
    path.is_file()
        && path
            .metadata()
            .map(|m| m.permissions().mode() & 0o111 != 0)
            .unwrap_or(false)
}

#[cfg(not(unix))]
fn is_executable(path: &Path) -> bool {
    path.is_file()
}

/// `name` in the first `$PATH` directory that holds an executable of that name.
fn on_path(name: &str) -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .filter(|dir| !dir.as_os_str().is_empty())
        .map(|dir| dir.join(name))
        .find(|candidate| is_executable(candidate))
}

/// The system `erl`/`erlc` pair — `$ERTS_ORACLE` (then its directory) when that names
/// an executable, else `$PATH`. `None` when either is unusable, which the test reports
/// with the skip banner instead of guessing.
fn resolve_toolchain() -> Option<(PathBuf, PathBuf)> {
    let erl = match std::env::var_os("ERTS_ORACLE") {
        Some(value) => {
            let program = PathBuf::from(&value);
            if !is_executable(&program) {
                eprintln!(
                    "[beam_bifs fun_info_oracle] $ERTS_ORACLE='{}' is not an existing \
                     executable — treating it as no oracle.",
                    program.display()
                );
                return None;
            }
            program
        }
        None => on_path("erl")?,
    };
    let erlc = match erl.parent().map(|dir| dir.join("erlc")) {
        Some(sibling) if is_executable(&sibling) => sibling,
        _ => on_path("erlc")?,
    };
    Some((erl, erlc))
}

/// Prints the loud "no oracle, not a pass" banner.
fn skip_banner() {
    eprintln!();
    eprintln!("=========== beam_bifs fun_info_oracle: live oracle SKIPPED ===========");
    eprintln!("No usable `erl`/`erlc` pair found ($ERTS_ORACLE unset or not");
    eprintln!("executable, and no `erl`/`erlc` on $PATH).");
    eprintln!("This test is NOT a pass — set $ERTS_ORACLE (or install Erlang/OTP).");
    eprintln!("fun_info_mfa/1's seam-attributed arms and the C's `mfa == NULL` arm");
    eprintln!("are then UNVERIFIED against the oracle.");
    eprintln!("======================================================================");
    eprintln!();
}

/// Runs `erl -noshell [-pa <code_path>] -eval <eval>` and returns its stdout. Panics on
/// a spawn failure or a non-zero exit, so a broken oracle can never look like a pass.
fn run_erl(erl: &Path, code_path: Option<&Path>, eval: &str) -> String {
    let mut command = Command::new(erl);
    command.arg("-noshell");
    if let Some(dir) = code_path {
        command.arg("-pa").arg(dir);
    }
    let output = command
        .arg("-eval")
        .arg(eval)
        .stdin(Stdio::null())
        .output()
        .unwrap_or_else(|e| panic!("failed to spawn the oracle '{}': {e}", erl.display()));
    assert!(
        output.status.success(),
        "the oracle '{}' exited with {:?}\n--- stderr ---\n{}\n--- eval ---\n{eval}",
        erl.display(),
        output.status.code(),
        String::from_utf8_lossy(&output.stderr),
    );
    String::from_utf8(output.stdout)
        .unwrap_or_else(|e| panic!("the oracle printed non-UTF-8 to stdout: {e}"))
}

/// The value of the `key=value` line for `key` in an oracle transcript.
fn parse_field<'a>(output: &'a str, key: &str) -> &'a str {
    let prefix = format!("{key}=");
    output
        .lines()
        .find_map(|line| line.strip_prefix(&prefix))
        .unwrap_or_else(|| panic!("the oracle output has no `{key}=` line:\n{output}"))
}

/// Parses the `key=<integer>` line for `key`.
fn parse_int(output: &str, key: &str) -> i64 {
    parse_field(output, key)
        .parse()
        .unwrap_or_else(|e| panic!("`{key}` is not an integer: {e}\n{output}"))
}

/// The integer after the **last** `,` of a `key={Tag, Value}` line — how the probe's
/// `{arity,N}` and `{Module,Function,Arity}` renderings are read.
fn parse_trailing_int(output: &str, key: &str) -> i64 {
    let text = parse_field(output, key);
    let inner = text
        .strip_prefix('{')
        .and_then(|rest| rest.strip_suffix('}'))
        .unwrap_or_else(|| panic!("`{key}={text}` is not a tuple rendering"));
    let last = inner
        .rsplit(',')
        .next()
        .unwrap_or_else(|| panic!("`{key}={text}` has no elements"));
    last.trim()
        .parse()
        .unwrap_or_else(|e| panic!("`{key}={text}`'s last element is not an integer: {e}"))
}

/// Parses a `key={a,b,…}` line into its integers — the shape the probe renders the
/// `env` list in (`list_to_tuple/1`, so `~w` cannot turn it into a string).
fn parse_int_tuple(output: &str, key: &str) -> Vec<i64> {
    let text = parse_field(output, key);
    let inner = text
        .strip_prefix('{')
        .and_then(|rest| rest.strip_suffix('}'))
        .unwrap_or_else(|| panic!("`{key}={text}` is not a tuple rendering"));
    if inner.trim().is_empty() {
        return Vec::new();
    }
    inner
        .split(',')
        .map(|item| {
            item.trim()
                .parse::<i64>()
                .unwrap_or_else(|e| panic!("`{item}` in `{key}={text}` is not an integer: {e}"))
        })
        .collect()
}

/// Parses a `key={b,b,…}` line into its bytes (`binary_to_list/1` through a tuple).
fn parse_bytes(output: &str, key: &str) -> Vec<u8> {
    parse_int_tuple(output, key)
        .into_iter()
        .map(|n| u8::try_from(n).unwrap_or_else(|_| panic!("`{key}` holds {n}, not a byte")))
        .collect()
}

