/// `erlang:fun_info_mfa/1` (plus `fun_info/2`'s `arity` and `name`) of a compiled
/// `make_fun3` closure and of its `NEW_FUN_EXT` image, against the live oracle. See the
/// module docs for what each run of the oracle establishes and why the image is decoded
/// by a second VM.
#[test]
fn fun_info_mfa_of_a_local_fun_and_of_its_new_fun_ext_image_matches_the_oracle() {
    let Some((erl, erlc)) = resolve_toolchain() else {
        skip_banner();
        return;
    };
    let scratch = Scratch::build(&erlc, "mfa");
    let image = scratch.path().join("fun.bin");
    let image_literal = format!(
        "\"{}\"",
        image.to_string_lossy().replace('\\', "\\\\").replace('"', "\\\"")
    );

    // --- run 1: the closure's own MFA, and the image to decode -----------------
    //
    // `~w` for the graded answers (pinned as literals below) and `~s` over
    // `atom_to_list/1` for the module/lambda names, so they arrive unquoted and
    // machine-parseable; `env`/`new_uniq` go through `list_to_tuple/1` because `~w`
    // would render `[73]` as the string `"I"`.
    let local_eval = format!(
        r#"
F = {MODULE}:mk(73),
io:format("mfa=~w~n",[erlang:fun_info_mfa(F)]),
io:format("arity=~w~n",[erlang:fun_info(F,arity)]),
io:format("name=~w~n",[erlang:fun_info(F,name)]),
io:format("mod=~s~n",[atom_to_list(element(2,erlang:fun_info(F,module)))]),
io:format("lname=~s~n",[atom_to_list(element(2,erlang:fun_info(F,name)))]),
io:format("new_index=~w~n",[element(2,erlang:fun_info(F,new_index))]),
io:format("index=~w~n",[element(2,erlang:fun_info(F,index))]),
io:format("uniq=~w~n",[element(2,erlang:fun_info(F,uniq))]),
io:format("new_uniq=~w~n",[list_to_tuple(binary_to_list(element(2,erlang:fun_info(F,new_uniq))))]),
io:format("env=~w~n",[list_to_tuple(element(2,erlang:fun_info(F,env)))]),
ok = file:write_file({image_literal}, term_to_binary(F)),
halt().
"#
    );
    let local = run_erl(&erl, Some(scratch.path()), &local_eval);
    // The graded answers, pinned: a wrong oracle cannot make this test pass.
    assert_eq!(
        parse_field(&local, "mfa"),
        "{fiprobe,'-mk/1-fun-0-',2}",
        "the oracle's fun_info_mfa/1 of fiprobe:mk(73) — full transcript:\n{local}"
    );
    assert_eq!(parse_field(&local, "arity"), "{arity,2}", "transcript:\n{local}");
    assert_eq!(
        parse_field(&local, "name"),
        "{name,'-mk/1-fun-0-'}",
        "transcript:\n{local}"
    );
    assert_eq!(parse_field(&local, "mod"), MODULE, "transcript:\n{local}");
    assert_eq!(parse_field(&local, "lname"), NAME, "transcript:\n{local}");
    let oracle_arity = parse_trailing_int(&local, "arity");
    let oracle_new_index = parse_int(&local, "new_index");
    let oracle_old_index = parse_int(&local, "index");
    let oracle_old_uniq = parse_int(&local, "uniq");
    let oracle_uniq = parse_bytes(&local, "new_uniq");
    let oracle_env = parse_int_tuple(&local, "env");
    assert_eq!(oracle_uniq.len(), 16, "new_uniq is the 16-byte module MD5");
    assert_eq!(oracle_env, vec![73], "the closure's single capture");

    // --- run 2: the same image, decoded by a VM that cannot load `fiprobe` -----
    let image_eval = format!(
        r#"
{{ok,B}} = file:read_file({image_literal}),
I = binary_to_term(B),
io:format("imfa=~w~n",[erlang:fun_info_mfa(I)]),
io:format("iarity=~w~n",[erlang:fun_info(I,arity)]),
io:format("imod=~s~n",[atom_to_list(element(2,erlang:fun_info(I,module)))]),
io:format("ienv=~w~n",[list_to_tuple(element(2,erlang:fun_info(I,env)))]),
halt().
"#
    );
    let imported = run_erl(&erl, None, &image_eval);
    // The C's `mfa == NULL` arm, pinned: `erts_get_fun_mfa` resolves against the loaded
    // modules and this VM has no `fiprobe`, so the function element is `[]`.
    assert_eq!(
        parse_field(&imported, "imfa"),
        "{fiprobe,[],2}",
        "the oracle's fun_info_mfa/1 of an unloadable NEW_FUN_EXT image — full \
         transcript:\n{imported}"
    );
    assert_eq!(
        parse_field(&imported, "iarity"),
        "{arity,2}",
        "transcript:\n{imported}"
    );
    assert_eq!(parse_field(&imported, "imod"), MODULE, "transcript:\n{imported}");
    assert_eq!(
        parse_int_tuple(&imported, "ienv"),
        oracle_env,
        "the image round-trips the closure's environment"
    );

    // --- this crate, on the equivalent frozen-layout terms ---------------------
    let reg = default_registry();
    let atoms = seeded_atoms();
    let mut md5 = [0u8; 16];
    md5.copy_from_slice(&oracle_uniq);

    let mut heap = Heap::new(4096).expect("test heap");
    let mut stub = StubIdentity(beam_codec::FunIdentity::named(
        atoms.lookup(MODULE).expect("seeded module"),
        md5,
        oracle_old_index as u32,
        oracle_old_uniq as u32,
        creator(&atoms),
        atoms.lookup(NAME).expect("seeded lambda name"),
    ));
    let mut ctx = make_ctx(&mut heap, &atoms).with_local_fun_identity(&mut stub);
    let env: Vec<Eterm> = oracle_env
        .iter()
        .map(|value| ctx.int(*value).expect("an env value fits"))
        .collect();
    let (_storage, fun) = local_fun(
        2,
        0x0BAD_C0DE_1234_5678,
        oracle_new_index as u32,
        &env,
    );

    // `fun_info_mfa/1` ⇒ `{fiprobe,'-mk/1-fun-0-',2}` — module + lambda from the
    // `LocalFunIdentity` seam, arity from the frozen header.
    let mfa = call(&reg, &mut ctx, "fun_info_mfa", &[fun]).expect("fun_info_mfa/1");
    assert_eq!(
        reg.call("erlang", "tuple_size", 1, &mut ctx, &[mfa])
            .expect("tuple_size/1"),
        make_small(3),
        "fun_info_mfa/1 returns a 3-tuple"
    );
    assert_eq!(atom_name(&atoms, elem(&reg, &mut ctx, mfa, 1)), MODULE);
    assert_eq!(atom_name(&atoms, elem(&reg, &mut ctx, mfa, 2)), NAME);
    assert_eq!(
        signed_value(elem(&reg, &mut ctx, mfa, 3)),
        oracle_arity,
        "fun_info_mfa/1's arity element"
    );
    assert_eq!(
        signed_value(elem(&reg, &mut ctx, mfa, 3)),
        2,
        "a two-parameter closure reports 2, not its num_free capture count"
    );

    // `fun_info(F, arity)` ⇒ `{arity,2}` — unchanged by the one capture.
    let (tag, value) = fun_info_pair(&reg, &mut ctx, fun, "arity");
    assert_eq!(atom_name(&atoms, tag), "arity");
    assert_eq!(signed_value(value), oracle_arity);
    assert_eq!(signed_value(value), 2);

    // `fun_info(F, name)` ⇒ `{name,'-mk/1-fun-0-'}`.
    let (tag, value) = fun_info_pair(&reg, &mut ctx, fun, "name");
    assert_eq!(atom_name(&atoms, tag), "name");
    assert_eq!(atom_name(&atoms, value), NAME);

    // The `NEW_FUN_EXT` image: module from the wire, the C's `[]` function (the
    // defining module is not loadable — `StubNone`), arity from the header.
    let mut heap = Heap::new(4096).expect("test heap");
    let mut none = StubNone;
    let mut ctx = make_ctx(&mut heap, &atoms).with_local_fun_identity(&mut none);
    let env: Vec<Eterm> = oracle_env
        .iter()
        .map(|value| ctx.int(*value).expect("an env value fits"))
        .collect();
    let image_fun = beam_codec::term::make_fun_imported(
        ctx.heap(),
        2,
        atoms.lookup(MODULE).expect("seeded module"),
        &md5,
        oracle_new_index as u32,
        oracle_old_index as u32,
        oracle_old_uniq as u32,
        creator(&atoms),
        &env,
    )
    .expect("the imported fun fits");

    let mfa = call(&reg, &mut ctx, "fun_info_mfa", &[image_fun]).expect("imported mfa");
    assert_eq!(
        atom_name(&atoms, elem(&reg, &mut ctx, mfa, 1)),
        MODULE,
        "the wire image names the module"
    );
    assert_eq!(
        elem(&reg, &mut ctx, mfa, 2),
        NIL,
        "the C's `mfa == NULL` arm answers the empty list for the function"
    );
    assert_eq!(signed_value(elem(&reg, &mut ctx, mfa, 3)), 2);
    // ... and the object survives a `=:=` against the freshly built triple.
    let expected_module = ctx.atom(MODULE).expect("seeded module");
    let two = ctx.int(2).expect("2 fits");
    let expected = ctx.tuple(&[expected_module, NIL, two]).expect("fits");
    assert!(
        beam_term::compare::eq(mfa, expected, &atoms),
        "fun_info_mfa/1 of the NEW_FUN_EXT image is not `{{fiprobe,[],2}}`"
    );
}

