// The fun TEXT — `erlang:fun_to_list/1` and the `~w`/`~p` leaf
// ---------------------------------------------------------------------------

/// Flattens an `io_lib:format/2` result (a char list, possibly nested iodata) to its
/// text, walking it with the registered `erlang:hd/1`/`erlang:tl/1`.
fn flatten_text(reg: &BifRegistry, ctx: &mut BifContext<'_>, term: Eterm) -> String {
    let mut out = String::new();
    let mut cursor = term;
    while cursor != NIL {
        let head = reg
            .call("erlang", "hd", 1, ctx, &[cursor])
            .expect("hd/1 of a proper list");
        if beam_term::is_small(head) {
            let byte = u8::try_from(signed_value(head)).expect("a byte-sized character");
            out.push(byte as char);
        } else {
            out.push_str(&flatten_text(reg, ctx, head));
        }
        cursor = reg
            .call("erlang", "tl", 1, ctx, &[cursor])
            .expect("tl/1 of a proper list");
    }
    out
}

/// The text of an `erlang:fun_to_list/1` result.
fn fun_text_of(reg: &BifRegistry, ctx: &mut BifContext<'_>, fun: Eterm) -> String {
    let list = call(reg, ctx, "fun_to_list", &[fun]).expect("erlang:fun_to_list/1");
    flatten_text(reg, ctx, list)
}

/// A byte-aligned char list (a format string or an argument list) on `ctx`'s heap.
fn char_list(ctx: &mut BifContext<'_>, text: &str) -> Eterm {
    let items: Vec<Eterm> = text
        .bytes()
        .map(|byte| ctx.int(i64::from(byte)).expect("a byte fits"))
        .collect();
    ctx.list(&items).expect("a short list fits")
}

/// `io_lib:format(Directive, [Term])`'s text, flattened.
fn formatted(reg: &BifRegistry, ctx: &mut BifContext<'_>, directive: &str, term: Eterm) -> String {
    let format = char_list(ctx, directive);
    let args = ctx.list(&[term]).expect("a 1-element list fits");
    let rendered = reg
        .call("io_lib", "format", 2, ctx, &[format, args])
        .expect("io_lib:format/2");
    flatten_text(reg, ctx, rendered)
}

/// `#Fun<Module.OldIndex.OldUniq>` — the C local arm's three fields
/// (`erts/emulator/beam/erl_printf_term.c:678-690`), rendered from the oracle's own
/// `index`/`uniq` items.
fn expected_local_text(index: i64, uniq: i64) -> String {
    format!("#Fun<{MODULE}.{index}.{uniq}>")
}

/// The fun text of **every** kind against the live oracle: a 0-capture `make_fun3`
/// closure, two captured ones (1 and 2 parameters), an `EXPORT_EXT`
/// (`fun lists:reverse/1`), the same closure's `NEW_FUN_EXT` image — and, on our side
/// only, the `-eval` `erl_eval` template closure, which the oracle attributes to
/// `erl_eval` while our seam honestly answers `Ok(None)`.
///
/// The oracle's transcript carries no pinned literal for a compiled module (the module
/// MD5 — and therefore `uniq` — moves with the compiler), so each expectation is built
/// from the oracle's *own* `fun_info(F, index)`/`uniq` and the C rule above; the two
/// facts that a wrong implementation would break are asserted directly as well: a
/// capture adds **no** field (all three closures print three fields while their `env`
/// lengths are 0, 1 and 1) and `~w`/`~p` are the same single line as the BIF.
#[test]
fn fun_text_of_every_fun_kind_matches_the_oracle() {
    let Some((erl, erlc)) = resolve_toolchain() else {
        skip_banner();
        return;
    };
    let scratch = Scratch::build(&erlc, "text");
    let image = scratch.path().join("fun_text.bin");
    let image_literal = format!(
        "\"{}\"",
        image.to_string_lossy().replace('\\', "\\\\").replace('"', "\\\"")
    );

    // --- run 1: the compiled closures and the external fun ---------------------
    let text_eval = format!(
        r#"
F0 = {MODULE}:mk0(),
F1 = {MODULE}:mk1(7),
F2 = {MODULE}:mk3(5),
E  = fun lists:reverse/1,
io:format("t0=~s~n",[erlang:fun_to_list(F0)]),
io:format("t1=~s~n",[erlang:fun_to_list(F1)]),
io:format("t2=~s~n",[erlang:fun_to_list(F2)]),
io:format("w0=~s~n",[lists:flatten(io_lib:format("~w",[F0]))]),
io:format("p1=~s~n",[lists:flatten(io_lib:format("~p",[F1]))]),
io:format("w2=~s~n",[lists:flatten(io_lib:format("~w",[F2]))]),
io:format("nested0=~s~n",[lists:flatten(io_lib:format("~w",[[F0,F0]]))]),
io:format("te=~s~n",[erlang:fun_to_list(E)]),
io:format("we=~s~n",[lists:flatten(io_lib:format("~w",[E]))]),
io:format("i0=~w~n",[element(2,erlang:fun_info(F0,index))]),
io:format("u0=~w~n",[element(2,erlang:fun_info(F0,uniq))]),
io:format("i1=~w~n",[element(2,erlang:fun_info(F1,index))]),
io:format("u1=~w~n",[element(2,erlang:fun_info(F1,uniq))]),
io:format("i2=~w~n",[element(2,erlang:fun_info(F2,index))]),
io:format("u2=~w~n",[element(2,erlang:fun_info(F2,uniq))]),
io:format("a0=~w~n",[element(2,erlang:fun_info(F0,arity))]),
io:format("a2=~w~n",[element(2,erlang:fun_info(F2,arity))]),
io:format("e0=~w~n",[length(element(2,erlang:fun_info(F0,env)))]),
io:format("e1=~w~n",[length(element(2,erlang:fun_info(F1,env)))]),
io:format("e2=~w~n",[length(element(2,erlang:fun_info(F2,env)))]),
ok = file:write_file({image_literal}, term_to_binary(F1)),
halt().
"#
    );
    let local = run_erl(&erl, Some(scratch.path()), &text_eval);

    let (i0, u0) = (parse_int(&local, "i0"), parse_int(&local, "u0"));
    let (i1, u1) = (parse_int(&local, "i1"), parse_int(&local, "u1"));
    let (i2, u2) = (parse_int(&local, "i2"), parse_int(&local, "u2"));
    let t0 = expected_local_text(i0, u0);
    let t1 = expected_local_text(i1, u1);
    let t2 = expected_local_text(i2, u2);

    // The oracle's own text is the C's triple, field for field.
    assert_eq!(parse_field(&local, "t0"), t0, "transcript:\n{local}");
    assert_eq!(parse_field(&local, "t1"), t1, "transcript:\n{local}");
    assert_eq!(parse_field(&local, "t2"), t2, "transcript:\n{local}");
    // `~w` and `~p` splice the same leaf.
    assert_eq!(parse_field(&local, "w0"), t0, "transcript:\n{local}");
    assert_eq!(parse_field(&local, "p1"), t1, "transcript:\n{local}");
    assert_eq!(parse_field(&local, "w2"), t2, "transcript:\n{local}");
    // A fun nested in a list keeps its text, on one line.
    assert_eq!(
        parse_field(&local, "nested0"),
        format!("[{t0},{t0}]"),
        "transcript:\n{local}"
    );
    // An external fun is the OTHER C arm: `fun Module:Function/Arity`.
    assert_eq!(parse_field(&local, "te"), "fun lists:reverse/1", "transcript:\n{local}");
    assert_eq!(parse_field(&local, "we"), "fun lists:reverse/1", "transcript:\n{local}");
    // No env-length field: 0, 1 and 1 captures all print three fields.
    assert_eq!(
        (parse_int(&local, "e0"), parse_int(&local, "e1"), parse_int(&local, "e2")),
        (0, 1, 1),
        "the closures' capture counts — transcript:\n{local}"
    );
    assert_eq!(parse_int(&local, "a0"), 1, "transcript:\n{local}");
    assert_eq!(parse_int(&local, "a2"), 2, "transcript:\n{local}");

    // --- run 2: the `NEW_FUN_EXT` image, decoded by a VM without the module -----
    let image_eval = format!(
        r#"
{{ok,B}} = file:read_file({image_literal}),
I = binary_to_term(B),
io:format("it=~s~n",[erlang:fun_to_list(I)]),
io:format("iw=~s~n",[lists:flatten(io_lib:format("~w",[I]))]),
io:format("itype=~w~n",[erlang:fun_info(I,type)]),
halt().
"#
    );
    let imported = run_erl(&erl, None, &image_eval);
    assert_eq!(parse_field(&imported, "it"), t1, "transcript:\n{imported}");
    assert_eq!(parse_field(&imported, "iw"), t1, "transcript:\n{imported}");
    assert_eq!(parse_field(&imported, "itype"), "{type,local}", "transcript:\n{imported}");

    // --- run 3: the `-eval` `erl_eval` template closure -------------------------
    let eval_closure = run_erl(
        &erl,
        None,
        "F = fun(Y) -> Y + 1 end, io:format(\"ev=~s~n\",[erlang:fun_to_list(F)]), halt(0).",
    );
    let ev = parse_field(&eval_closure, "ev");
    assert!(
        ev.starts_with("#Fun<erl_eval.") && ev.ends_with('>') && ev.matches('.').count() == 2,
        "the oracle attributes its `-eval` closure to `erl_eval`, three fields: {ev}"
    );

    // --- this crate, on the equivalent frozen-layout terms ----------------------
    let reg = default_registry();
    let mut atoms = seeded_atoms();
    atoms.seed(["lists", "reverse"]);

    // The three `make_fun3` closures: the text comes from the seam's `(module,
    // old_index, old_uniq)`, never from the descriptor, which only carries
    // `(uniq, index)`.
    let closures = [
        (1usize, 0usize, i0, u0, t0.as_str()),
        (1, 1, i1, u1, t1.as_str()),
        (2, 1, i2, u2, t2.as_str()),
    ];
    for (arity, captures, index, uniq, expected) in closures {
        let mut heap = Heap::new(4096).expect("test heap");
        let mut stub = StubIdentity(beam_codec::FunIdentity::new(
            atoms.lookup(MODULE).expect("seeded module"),
            [0u8; 16],
            index as u32,
            uniq as u32,
            creator(&atoms),
        ));
        let mut ctx = make_ctx(&mut heap, &atoms).with_local_fun_identity(&mut stub);
        let env: Vec<Eterm> = (0..captures)
            .map(|_| ctx.int(7).expect("7 fits"))
            .collect();
        // The descriptor's own fields are deliberately unrelated to the text.
        let (_storage, fun) = local_fun(arity as u32, 0x0BAD_C0DE, 0, &env);
        assert_eq!(fun_text_of(&reg, &mut ctx, fun), expected, "our `fun_to_list/1`");
        assert_eq!(formatted(&reg, &mut ctx, "~w", fun), expected, "our `~w`");
        assert_eq!(formatted(&reg, &mut ctx, "~p", fun), expected, "our `~p`");
    }

    // The external fun, which never consults the seam.
    {
        let mut heap = Heap::new(4096).expect("test heap");
        let mut ctx = make_ctx(&mut heap, &atoms);
        let fun = beam_codec::term::make_fun_external(
            ctx.heap(),
            1,
            atoms.lookup("lists").expect("seeded module"),
            atoms.lookup("reverse").expect("seeded function"),
        )
        .expect("the external fun fits");
        assert_eq!(fun_text_of(&reg, &mut ctx, fun), "fun lists:reverse/1");
        assert_eq!(formatted(&reg, &mut ctx, "~w", fun), "fun lists:reverse/1");
    }

    // The decoded `NEW_FUN_EXT` image carries the same three fields on the wire.
    {
        let mut heap = Heap::new(4096).expect("test heap");
        let mut none = StubNone;
        let mut ctx = make_ctx(&mut heap, &atoms).with_local_fun_identity(&mut none);
        let seven = ctx.int(7).expect("7 fits");
        let image_fun = beam_codec::term::make_fun_imported(
            ctx.heap(),
            1,
            atoms.lookup(MODULE).expect("seeded module"),
            &[0u8; 16],
            0,
            i1 as u32,
            u1 as u32,
            creator(&atoms),
            &[seven],
        )
        .expect("the imported fun fits");
        assert_eq!(fun_text_of(&reg, &mut ctx, image_fun), t1);
        assert_eq!(formatted(&reg, &mut ctx, "~w", image_fun), t1);
    }

    // The `-eval` template closure: our seam has no identity to give — the answer is
    // the typed capability gap on both routes, never a fabricated `#Fun<…>` (in
    // particular never the oracle's `erl_eval` attribution, which needs erl_eval's
    // own lambda table).
    {
        let mut heap = Heap::new(4096).expect("test heap");
        let mut none = StubNone;
        let mut ctx = make_ctx(&mut heap, &atoms).with_local_fun_identity(&mut none);
        let (_storage, fun) = local_fun(1, 0x1234, 42, &[]);
        for got in [
            call(&reg, &mut ctx, "fun_to_list", &[fun]),
            {
                let format = char_list(&mut ctx, "~w");
                let args = ctx.list(&[fun]).expect("a 1-element list fits");
                reg.call("io_lib", "format", 2, &mut ctx, &[format, args])
            },
        ] {
            assert!(
                matches!(
                    got,
                    Err(beam_common::BeamError::Raise(ref r))
                        if r.reason.as_atom() == Some("unsupported_bif")
                ),
                "an unattributable Local fun must be the typed unsupported_bif gap, got {got:?}"
            );
        }
    }
}
