/// A `$TMPDIR` scratch directory holding `fiprobe.erl`/`fiprobe.beam` and the
/// `term_to_binary/1` image the second oracle run decodes.
struct Scratch {
    dir: PathBuf,
}

impl Scratch {
    /// Creates the directory, writes the fixture source and compiles it.
    fn build(erlc: &Path) -> Scratch {
        let dir = std::env::temp_dir().join(format!(
            "beam_bifs_fun_info_oracle_{}",
            std::process::id()
        ));
        // A previous run of this binary in the same pid cannot exist, but be idempotent.
        std::fs::create_dir_all(&dir)
            .unwrap_or_else(|e| panic!("cannot create {}: {e}", dir.display()));
        let source = dir.join("fiprobe.erl");
        std::fs::write(&source, FIPROBE_ERL)
            .unwrap_or_else(|e| panic!("cannot write {}: {e}", source.display()));
        let output = Command::new(erlc)
            .arg("-o")
            .arg(&dir)
            .arg(&source)
            .output()
            .unwrap_or_else(|e| panic!("cannot run `{}`: {e}", erlc.display()));
        assert!(
            output.status.success(),
            "`{}` exited with {:?}\n--- stderr ---\n{}",
            erlc.display(),
            output.status.code(),
            String::from_utf8_lossy(&output.stderr),
        );
        assert!(
            dir.join("fiprobe.beam").is_file(),
            "`erlc` produced no fiprobe.beam in {}",
            dir.display()
        );
        Scratch { dir }
    }

    /// The scratch directory (the fixture's code path).
    fn path(&self) -> &Path {
        &self.dir
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        match std::fs::remove_dir_all(&self.dir) {
            Ok(()) => {}
            // The directory is ours and disposable; a failure is reported, not hidden.
            Err(error) => println!("note: could not remove {}: {error}", self.dir.display()),
        }
    }
}

