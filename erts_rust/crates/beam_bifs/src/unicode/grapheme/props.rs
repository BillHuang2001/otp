/// `is_extend/1`'s three-valued result (`false | true | zwj`).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(crate) enum Extend {
    /// `false`
    No,
    /// `true`
    Yes,
    /// `zwj` — the single code point of the `zwj` class.
    Zwj,
}

/// `is_extend(CP)` — `zwj` for U+200D, `true` for `extend ∪ spacingmark`.
#[inline]
pub(crate) fn is_extend(cp: u32) -> Extend {
    if cp == ZWJ_CP {
        Extend::Zwj
    } else if in_ranges(IS_EXTEND_TRUE, cp) {
        Extend::Yes
    } else {
        Extend::No
    }
}

