//! `unicode_util:cp/1` and its `cpl*` / `cp_no_bin*` helpers — the code-point
//! **normalisation front end** of the oracle's generated grapheme-cluster walk.
//!
//! Ground truth (read-only): the oracle's dumped `unicode_util.erl`
//! (`cp/1` @417, `cpl/2` @424-431 and the `cpl_cont*` / `cpl_1_cont*` /
//! `cp_no_bin*` helpers below it) as generated by
//! `../../../../../lib/stdlib/uc_spec/gen_unicode_mod.escript` (`gen_cp/1`
//! @708) and the hand-written tail in `lib/stdlib/src/unicode_util.erl`.
//!
//! `cp/1` flattens just enough of the front of a chardata term to expose one
//! code point, **preserving the tail representation verbatim** — a binary tail
//! stays a binary, an improper list tail stays improper. The oracle returns
//! three shapes and this port returns the same three as a single [`Eterm`]:
//!
//! * `[CP | Rest]` — the head is the first code point, the tail the remainder;
//! * `[]` (`NIL`) — the (empty) remainder;
//! * `{error, Rest}` — a binary whose first byte is not a valid UTF-8 sequence
//!   start (or, from `cpl/2`, `{error, [Bin | Rest]}`).
//!
//! Everything here is heap-agnostic term work: the caller's [`BifContext`]
//! supplies the heap. `cp/1` has no clause for a non-list, non-binary term (a
//! non-byte-aligned bitstring included), so such an argument is the oracle's
//! `error:function_clause` — returned as a typed [`BeamError`].

use beam_term::Eterm;

use crate::access;
use crate::bits::make_binary;
use crate::context::BifContext;
use crate::error::function_clause;
use crate::unicode::{decode_one, Decode};

use super::{binary_opt, error_atom, head_tail, is_cp};

/// The internal `binary_found` marker of `cp_no_bin/1` / `cp_no_binl/2`.
///
/// The oracle's `cp_no_bin*` walks a list looking for an embedded binary; when
/// it finds one (or is handed anything that is not a list) it bails out with
/// the sentinel atom `binary_found`, which `gc/1` then turns into the
/// "consume the byte tail" route. It is never a user-visible value.
pub(super) enum NoBin {
    /// The flattened list (or tail) `cp_no_bin*` produced.
    Term(Eterm),
    /// The `binary_found` sentinel.
    BinaryFound,
}

/// `cp(X)` — see the module docs for the three result shapes.
///
/// # Errors
///
/// `error:function_clause` when `term` matches none of `cp/1`'s clauses (a
/// float, tuple, pid, … or a **non-byte-aligned** bitstring); otherwise
/// propagates the heap's allocation failure.
pub(super) fn cp(ctx: &mut BifContext<'_>, term: Eterm) -> beam_common::Result<Eterm> {
    if let Some((c, rest)) = head_tail(term) {
        // cp([C|_]=L) when ?IS_CP(C) -> L
        if is_cp(c) {
            return Ok(term);
        }
        // cp([List]) -> cp(List)
        if access::is_nil(rest) {
            return cp(ctx, c);
        }
        // cp([List|R]) -> cpl(List, R)
        return cpl(ctx, c, rest);
    }
    // cp([]) -> []
    if access::is_nil(term) {
        return Ok(beam_term::NIL);
    }
    if let Some(bytes) = binary_opt(term) {
        // cp(<<C/utf8, R/binary>>) -> [C|R]
        if !bytes.is_empty() {
            if let Decode::Ok(value, n) = decode_one(&bytes) {
                let head = ctx.int(i64::from(value))?;
                let tail = make_binary(ctx.heap(), &bytes[n..])?;
                return ctx.cons(head, tail);
            }
        }
        // cp(<<>>) -> []  /  cp(<<R/binary>>) -> {error, R}
        if bytes.is_empty() {
            return Ok(beam_term::NIL);
        }
        let tag = error_atom(ctx)?;
        return ctx.tuple(&[tag, term]);
    }
    Err(function_clause())
}

/// `cpl(List, R)` — the "flatten a nested head list with a known remainder
/// `R`" workhorse. Returns the same three shapes as [`cp`].
fn cpl(ctx: &mut BifContext<'_>, list: Eterm, r: Eterm) -> beam_common::Result<Eterm> {
    if let Some((c, t)) = head_tail(list) {
        // cpl([C], R) when ?IS_CP(C) -> [C|cpl_1_cont(R)]
        if is_cp(c) {
            if access::is_nil(t) {
                let tail = cpl_1_cont(ctx, r)?;
                return ctx.cons(c, tail);
            }
            // cpl([C|T], R) when ?IS_CP(C) -> [C|cpl_cont(T, R)]
            let tail = cpl_cont(ctx, t, r)?;
            return ctx.cons(c, tail);
        }
        // cpl([List], R) -> cpl(List, R)
        if access::is_nil(t) {
            return cpl(ctx, c, r);
        }
        // cpl([List|T], R) -> cpl(List, [T|R])
        let new_r = ctx.cons(t, r)?;
        return cpl(ctx, c, new_r);
    }
    // cpl([], R) -> cp(R)
    if access::is_nil(list) {
        return cp(ctx, r);
    }
    if let Some(bytes) = binary_opt(list) {
        if bytes.is_empty() {
            // cpl(<<>>, R) -> cp(R)
            return cp(ctx, r);
        }
        // cpl(<<C/utf8, T/binary>>, R) -> [C,T|R]  ==  [C | [T|R]]
        if let Decode::Ok(value, n) = decode_one(&bytes) {
            let head = ctx.int(i64::from(value))?;
            let mid = make_binary(ctx.heap(), &bytes[n..])?;
            let inner = ctx.cons(mid, r)?;
            return ctx.cons(head, inner);
        }
        // cpl(<<B/binary>>, R) -> {error, [B|R]}
        let tag = error_atom(ctx)?;
        let inner = ctx.cons(list, r)?;
        return ctx.tuple(&[tag, inner]);
    }
    Err(function_clause())
}

/// `cpl_1_cont(T)` — the oracle's arity-1 continuation used when `cpl/2` has
/// consumed the last code point of its head list.
fn cpl_1_cont(ctx: &mut BifContext<'_>, t: Eterm) -> beam_common::Result<Eterm> {
    if let Some((c, tl)) = head_tail(t) {
        // cpl_1_cont([C|T]) when is_integer(C) -> [C|cpl_1_cont2(T)]
        if access::is_integer(c) {
            let tail = cpl_1_cont2(ctx, tl)?;
            return ctx.cons(c, tail);
        }
        // cpl_1_cont([L]) -> cpl_1_cont(L)
        if access::is_nil(tl) {
            return cpl_1_cont(ctx, c);
        }
        // cpl_1_cont([L|T]) -> cpl_cont(L, T)
        return cpl_cont(ctx, c, tl);
    }
    // cpl_1_cont(T) -> T
    Ok(t)
}

/// `cpl_1_cont2(T)`.
fn cpl_1_cont2(ctx: &mut BifContext<'_>, t: Eterm) -> beam_common::Result<Eterm> {
    if let Some((c, tl)) = head_tail(t) {
        if access::is_integer(c) {
            let tail = cpl_1_cont3(ctx, tl)?;
            return ctx.cons(c, tail);
        }
        if access::is_nil(tl) {
            return cpl_1_cont2(ctx, c);
        }
        return cpl_cont2(ctx, c, tl);
    }
    Ok(t)
}

/// `cpl_1_cont3(T)` — note the first clause returns its argument **verbatim**
/// (`[C|_]=T when is_integer(C) -> T`).
fn cpl_1_cont3(ctx: &mut BifContext<'_>, t: Eterm) -> beam_common::Result<Eterm> {
    if let Some((c, tl)) = head_tail(t) {
        if access::is_integer(c) {
            return Ok(t);
        }
        if access::is_nil(tl) {
            return cpl_1_cont3(ctx, c);
        }
        return cpl_cont3(ctx, c, tl);
    }
    Ok(t)
}

/// `cpl_cont(T, R)`.
fn cpl_cont(ctx: &mut BifContext<'_>, t: Eterm, r: Eterm) -> beam_common::Result<Eterm> {
    if let Some((c, tl)) = head_tail(t) {
        // cpl_cont([C|T], R) when is_integer(C) -> [C|cpl_cont2(T, R)]
        if access::is_integer(c) {
            let tail = cpl_cont2(ctx, tl, r)?;
            return ctx.cons(c, tail);
        }
        // cpl_cont([L], R) -> cpl_cont(L, R)
        if access::is_nil(tl) {
            return cpl_cont(ctx, c, r);
        }
        // cpl_cont([L|T], R) -> cpl_cont(L, [T|R])
        let new_r = ctx.cons(tl, r)?;
        return cpl_cont(ctx, c, new_r);
    }
    // cpl_cont([], R) -> cpl_1_cont(R)
    if access::is_nil(t) {
        return cpl_1_cont(ctx, r);
    }
    // cpl_cont(T, R) -> [T|R]
    ctx.cons(t, r)
}

/// `cpl_cont2(T, R)`.
fn cpl_cont2(ctx: &mut BifContext<'_>, t: Eterm, r: Eterm) -> beam_common::Result<Eterm> {
    if let Some((c, tl)) = head_tail(t) {
        if access::is_integer(c) {
            let tail = cpl_cont3(ctx, tl, r)?;
            return ctx.cons(c, tail);
        }
        if access::is_nil(tl) {
            return cpl_cont2(ctx, c, r);
        }
        let new_r = ctx.cons(tl, r)?;
        return cpl_cont2(ctx, c, new_r);
    }
    if access::is_nil(t) {
        return cpl_1_cont2(ctx, r);
    }
    ctx.cons(t, r)
}

/// `cpl_cont3(T, R)` — a one-element `[C]` head yields `[C|R]` while a longer
/// `[C|T]` yields `[C,T|R]` (`[C | [T|R]]`).
fn cpl_cont3(ctx: &mut BifContext<'_>, t: Eterm, r: Eterm) -> beam_common::Result<Eterm> {
    if let Some((c, tl)) = head_tail(t) {
        if access::is_integer(c) {
            if access::is_nil(tl) {
                return ctx.cons(c, r);
            }
            let inner = ctx.cons(tl, r)?;
            return ctx.cons(c, inner);
        }
        if access::is_nil(tl) {
            return cpl_cont3(ctx, c, r);
        }
        let new_r = ctx.cons(tl, r)?;
        return cpl_cont3(ctx, c, new_r);
    }
    if access::is_nil(t) {
        return cpl_1_cont3(ctx, r);
    }
    ctx.cons(t, r)
}

/// `cp_no_bin(X)` — like [`cp`] but **refuses** to cross a binary: an embedded
/// binary (or a non-list) short-circuits to [`NoBin::BinaryFound`].
pub(super) fn cp_no_bin(ctx: &mut BifContext<'_>, term: Eterm) -> beam_common::Result<NoBin> {
    if let Some((c, tl)) = head_tail(term) {
        // cp_no_bin([C|_]=L) when is_integer(C) -> L
        if access::is_integer(c) {
            return Ok(NoBin::Term(term));
        }
        // cp_no_bin([List]) -> cp_no_bin(List)
        if access::is_nil(tl) {
            return cp_no_bin(ctx, c);
        }
        // cp_no_bin([List|R]) -> cp_no_binl(List, R)
        return cp_no_binl(ctx, c, tl);
    }
    // cp_no_bin([]) -> []
    if access::is_nil(term) {
        return Ok(NoBin::Term(beam_term::NIL));
    }
    // cp_no_bin(_) -> binary_found
    Ok(NoBin::BinaryFound)
}

/// `cp_no_binl(List, R)`.
fn cp_no_binl(
    ctx: &mut BifContext<'_>,
    list: Eterm,
    r: Eterm,
) -> beam_common::Result<NoBin> {
    if let Some((c, t)) = head_tail(list) {
        if access::is_integer(c) {
            // cp_no_binl([C], R) when is_integer(C) -> [C|cpl_1_cont(R)]
            if access::is_nil(t) {
                let tail = cpl_1_cont(ctx, r)?;
                return Ok(NoBin::Term(ctx.cons(c, tail)?));
            }
            // cp_no_binl([C|T], R) when is_integer(C) -> [C|cpl_cont(T, R)]
            let tail = cpl_cont(ctx, t, r)?;
            return Ok(NoBin::Term(ctx.cons(c, tail)?));
        }
        // cp_no_binl([List], R) -> cp_no_binl(List, R)
        if access::is_nil(t) {
            return cp_no_binl(ctx, c, r);
        }
        // cp_no_binl([List|T], R) -> cp_no_binl(List, [T|R])
        let new_r = ctx.cons(t, r)?;
        return cp_no_binl(ctx, c, new_r);
    }
    // cp_no_binl([], R) -> cp_no_bin(R)
    if access::is_nil(list) {
        return cp_no_bin(ctx, r);
    }
    // cp_no_binl(_, _) -> binary_found
    Ok(NoBin::BinaryFound)
}
