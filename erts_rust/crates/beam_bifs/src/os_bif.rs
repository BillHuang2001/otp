/// `os:getenv/1` — the value as a string, or the atom `false` when unset.
fn getenv_1(ctx: &mut BifContext<'_>, args: &[Eterm]) -> Result<Eterm> {
    let key = key_from_term(args[0], ctx.atoms()).ok_or_else(badarg)?;
    let value = env_lock().get(&key).cloned();
    match value {
        None => ctx.intern_atom("false"),
        Some(bytes) => native_to_filename(ctx, &bytes),
    }
}

/// `os:putenv/2` — set or overwrite one variable; always `true`.
fn putenv_2(ctx: &mut BifContext<'_>, args: &[Eterm]) -> Result<Eterm> {
    let key = key_from_term(args[0], ctx.atoms()).ok_or_else(badarg)?;
    let value = value_from_term(args[1], ctx.atoms()).ok_or_else(badarg)?;
    env_lock().insert(key, value);
    ctx.intern_atom("true")
}

/// `os:unsetenv/1` — remove one variable; always `true`.
fn unsetenv_1(ctx: &mut BifContext<'_>, args: &[Eterm]) -> Result<Eterm> {
    let key = key_from_term(args[0], ctx.atoms()).ok_or_else(badarg)?;
    env_lock().remove(&key);
    ctx.intern_atom("true")
}

/// `os:env/0` — the whole environment as `{KeyString, ValueString}` 2-tuples,
/// sorted by key bytes (see the module docs).
fn os_env_0(ctx: &mut BifContext<'_>, _args: &[Eterm]) -> Result<Eterm> {
    let entries: Vec<(Vec<u8>, Vec<u8>)> = {
        let table = env_lock();
        table.iter().map(|(k, v)| (k.clone(), v.clone())).collect()
    };

    let mut elems = Vec::with_capacity(entries.len());
    for (key, value) in entries {
        let key_term = native_to_filename(ctx, &key)?;
        let value_term = native_to_filename(ctx, &value)?;
        elems.push(ctx.tuple(&[key_term, value_term])?);
    }
    ctx.list(&elems)
}

/// `os:getpid/0` — the OS process id as a string.
fn getpid_0(ctx: &mut BifContext<'_>, _args: &[Eterm]) -> Result<Eterm> {
    string_list(ctx, &std::process::id().to_string())
}

/// `os:system_time/0` — nanoseconds since the UNIX epoch.
fn os_system_time_0(ctx: &mut BifContext<'_>, _args: &[Eterm]) -> Result<Eterm> {
    arith::int_from_i64(ctx, system_native()?)
}

/// `os:system_time/1` — `os:system_time/0` expressed in the given unit.
///
/// The unit's ratio is a machine integer for every atom and for a small positive
/// integer ([`convert_per_second`]), and arbitrary precision for a **positive
/// bignum** ([`crate::time::convert_unit_big`]).
fn os_system_time_1(ctx: &mut BifContext<'_>, args: &[Eterm]) -> Result<Eterm> {
    let native = system_native()?;
    match os_unit(ctx, args[0])? {
        OsUnit::PerSecond(per_second) => {
            crate::time::int_from_i128(ctx, convert_per_second(native, per_second))
        }
        OsUnit::PerSecondBig(per_second) => crate::time::convert_unit_big(ctx, native, &per_second),
    }
}

/// `os:timestamp/0` — the deprecated `{MegaSecs, Secs, MicroSecs}`
/// (`get_sys_now`: microseconds since the epoch, split as
/// `make_timestamp_value` does).
fn os_timestamp_0(ctx: &mut BifContext<'_>, _args: &[Eterm]) -> Result<Eterm> {
    let micros = system_native()?.div_euclid(1_000);
    let mega_secs = micros.div_euclid(1_000_000_000_000);
    let total_secs = micros.div_euclid(1_000_000);
    let secs = total_secs - mega_secs * 1_000_000;
    let micro_secs = micros - total_secs * 1_000_000;

    let mega = ctx.int(mega_secs)?;
    let sec = ctx.int(secs)?;
    let micro = ctx.int(micro_secs)?;
    ctx.tuple(&[mega, sec, micro])
}

/// `os:perf_counter/0` — a monotonically increasing integer in the
/// `perf_counter` unit (nanoseconds on this host). Its origin is opaque.
fn os_perf_counter_0(ctx: &mut BifContext<'_>, _args: &[Eterm]) -> Result<Eterm> {
    arith::int_from_i64(ctx, perf_counter_native())
}

/// `file:native_name_encoding/0` — `utf8` on this host.
fn native_name_encoding_0(ctx: &mut BifContext<'_>, _args: &[Eterm]) -> Result<Eterm> {
    ctx.intern_atom("utf8")
}

/// `prim_file:internal_name2native/1` — the raw, NUL-terminated native name.
///
/// An atom is `badarg` (the C explicitly refuses it). A binary is copied
/// verbatim — any NUL byte in it is `badarg` — with a NUL appended; anything
/// else goes through the iolist walk, and a walk that fails is `badarg`.
fn internal_name2native_1(ctx: &mut BifContext<'_>, args: &[Eterm]) -> Result<Eterm> {
    let term = args[0];
    if is_atom(term) {
        return Err(badarg());
    }
    if access::is_bitstring(term) {
        let bytes = bits::bytes(term)?;
        if bytes.contains(&0) {
            return Err(badarg());
        }
        let mut out = bytes;
        out.push(0);
        return bits::make_binary(ctx.heap(), &out);
    }
    let need = native_need(term, ctx.atoms()).ok_or_else(badarg)?;
    let mut out = Vec::with_capacity(need + 1);
    native_put(term, ctx.atoms(), &mut out).ok_or_else(badarg)?;
    out.push(0);
    bits::make_binary(ctx.heap(), &out)
}

/// `prim_file:internal_native2name/1` — the native name decoded for Erlang.
///
/// A non-bitstring is `badarg`; an empty binary is `NIL`; valid UTF-8 becomes a
/// code point list; anything else is `{error, warning}`.
fn internal_native2name_1(ctx: &mut BifContext<'_>, args: &[Eterm]) -> Result<Eterm> {
    let bytes = bits::bytes(args[0])?;
    if bytes.is_empty() {
        return Ok(NIL);
    }
    match core::str::from_utf8(&bytes) {
        Ok(text) => codepoint_list(ctx, text),
        Err(_) => error_warning(ctx),
    }
}

/// `prim_file:is_translatable/1` — true iff the native name is valid UTF-8 (the
/// empty binary is trivially translatable); a non-bitstring is `badarg`, and an
/// atom has no special case.
fn is_translatable_1(ctx: &mut BifContext<'_>, args: &[Eterm]) -> Result<Eterm> {
    let bytes = bits::bytes(args[0])?;
    if bytes.is_empty() {
        return ctx.boolean(true);
    }
    ctx.boolean(is_valid_utf8(&bytes))
}

