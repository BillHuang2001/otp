//! Operating-system and filename BIFs: the `os`, `file` and `prim_file`
//! surfaces (`getenv/1`, `putenv/2`, `unsetenv/1`, `env/0`, `getpid/0`,
//! `system_time/0,1`, `timestamp/0`, `perf_counter/0`;
//! `file:native_name_encoding/0`; the `prim_file` name-conversion helpers).
//!
//! Ground truth (read-only): the `os`, `file` and `prim_file` entries in
//! `../../erts/emulator/beam/bif.tab` and the C implementations
//! `../../erts/emulator/beam/erl_bif_os.c` (`os_getenv_1`, `os_putenv_2`,
//! `os_unsetenv_1`, `os_env_0`, `os_getpid_0`),
//! `../../erts/emulator/beam/erl_time_sup.c` (`os_system_time_0,1`,
//! `os_perf_counter_0`, `time_unit_conversion`, `make_timestamp_value`,
//! `get_sys_now`), `../../erts/emulator/sys/common/erl_osenv.c`
//! (`convert_key_to_native`, `convert_value_to_native`,
//! `erts_osenv_{get,put,unset}_term`) and
//! `../../erts/emulator/beam/erl_unicode.c` (`erts_native_filename_need`,
//! `erts_native_filename_put`, `erts_convert_native_to_filename`,
//! `analyze_utf8`, `prim_file_internal_name2native_1`,
//! `prim_file_internal_native2name_1`, `prim_file_is_translatable_1`,
//! `file_native_name_encoding_0`). Every value below is pinned against the
//! OTP 29.1.1 / erts-17.1 oracle.
//!
//! # Roster (13 keys)
//!
//! `os:getenv/1`, `os:putenv/2`, `os:unsetenv/1`, `os:env/0`, `os:getpid/0`,
//! `os:system_time/0`, `os:system_time/1`, `os:timestamp/0`,
//! `os:perf_counter/0`; `file:native_name_encoding/0`;
//! `prim_file:internal_name2native/1`, `prim_file:internal_native2name/1`
//! and `prim_file:is_translatable/1`.
//!
//! `os:set_signal/2` is deliberately **not** registered (it needs signal
//! handling, which is out of scope) and `prim_file:internal_normalize_utf8/1`
//! is **not** registered either: its NFC normalizer is generated by `dec.erl`
//! into `../../erts/emulator/beam/erl_unicode_normalize.h` (the generator is not
//! present in the tree), so no faithful transcription is possible — an
//! approximation would risk *wrong* results.
//!
//! # `os:system_time/1`'s unit
//!
//! `os:system_time/1` runs the same `time_unit_conversion` as
//! `erlang:system_time/1` (`erl_time_sup.c:2268-2356`): the atoms
//! `native`/`perf_counter` (both 1e9/s on this host), `second|seconds`,
//! `millisecond|milli_seconds`, `microsecond|micro_seconds` and
//! `nanosecond|nano_seconds`, or any **positive integer** naming that many units
//! per second — so the value is `native * per_second div 1_000_000_000` with
//! `native` in nanoseconds. A ratio that fits a small integer converts in `i128`;
//! a **positive bignum** is the C's `default` arm, handed to
//! `erlang:convert_time_unit/3` and converted in arbitrary precision
//! ([`crate::time::convert_unit_big`]) — `os:system_time(1 bsl 200)` is the oracle's
//! bignum, never a capability gap. A zero or negative small integer, a **negative**
//! bignum (the C's `big_sign`), a float or any other term is `badarg`.
//!
//! # Environment model
//!
//! Real ERTS keeps its **own** copy of the environment (`sysenv_global_env`,
//! imported from `environ` at startup) — `os:putenv/2` updates that copy and
//! never calls the C library's `setenv`. M1 does the same ([`env_table`]): the
//! table is imported from the process environment on first use and mutated by
//! `putenv`/`unsetenv`. This reproduces the whole observable contract (the
//! round-trip, the `badarg` shapes, the iolist/Unicode-char-list keys and
//! values) and additionally lets an **empty** key be stored, exactly as the C
//! tree does (`os:putenv("","V")` ⇒ `true`), which the C library's `setenv`
//! cannot represent.
//!
//! **Documented deviation — `os:env/0` order.** The C walks an `erl_rbtree`, so
//! its order is the balancing-dependent insertion order and is not derivable
//! from the sources (nor stable across hosts). M1 returns the entries **sorted
//! by key bytes**; the element shape (`{KeyString, ValueString}` 2-tuples — the
//! C's `foreach_term_wrapper` converts *both* key and value through
//! `erts_convert_native_to_filename`) and the key/value set agree with the
//! oracle.
//!
//! # Native name encoding
//!
//! `file:native_name_encoding/0` is `utf8` on this host, so the `prim_file`
//! conversions implement exactly the `ERL_FILENAME_UTF8` arms: a key/value is
//! an atom (never for `internal_name2native/1`) or a *flattened* list of
//! Unicode code points encoded as UTF-8 — a NUL code point, a surrogate, a code
//! point past `U+10FFFF`, a non-integer leaf or an improper tail is `badarg`
//! (`erts_native_filename_need` returning `-1`). Note the C's empty-key check in
//! `convert_key_to_native` is `length == 0` **on a pointer**, hence dead code:
//! an empty key is accepted, which the oracle confirms (`os:getenv("")` ⇒
//! `false`). A key containing `=` is `badarg`.
//!
//! The off-heap/`UTF8_MAC`/`WIN_WCHAR` arms are not reachable on this host. A
//! value read back from the environment is validated as UTF-8 (`analyze_utf8`,
//! whose rules are exactly [`std::str::from_utf8`]'s) and rendered as a code
//! point list, or byte-for-byte as a list of bytes when invalid
//! (`erts_convert_native_to_filename`'s `noconvert` arm).

