/// True for a non-empty cons cell (`NIL` is never a cons).
fn is_cons(term: Eterm) -> bool {
    !is_nil(term) && access::is_list(term)
}

/// Walks `term` exactly as `erts_native_filename_need`/
/// `erts_native_filename_put` do for the UTF-8 native encoding, calling `emit`
/// with every code point in order.
///
/// Returns `None` where the C returns `-1`: an atom whose name holds a NUL (the
/// C's post-check), a NUL/non-character small integer, a surrogate, a code
/// point past `U+10FFFF`, a non-integer list leaf or an improper list tail.
/// An atom is walked as the code points of its (always UTF-8) name, which is
/// byte-identical to the C's `sys_memcpy` of the name.
///
/// The walk is bounded by the term's size (terms are trees), so the explicit
/// stack cannot grow without bound.
fn walk_native(term: Eterm, atoms: &AtomTable, emit: &mut dyn FnMut(u32)) -> Option<()> {
    if is_atom(term) {
        let name = atoms.name(atom_val(term))?;
        if name.as_bytes().contains(&0) {
            return None;
        }
        for ch in name.chars() {
            emit(ch as u32);
        }
        return Some(());
    }
    if is_nil(term) {
        return Some(());
    }
    if !is_cons(term) {
        return None;
    }

    // The C's explicit stack: nested lists are flattened in order, an empty
    // sublist contributes nothing.
    let mut stack: Vec<Eterm> = vec![term];
    while let Some(mut node) = stack.pop() {
        while is_cons(node) {
            let head = access::car(node);
            let tail = access::cdr(node);
            if is_nil(head) {
                // An empty sublist is skipped, like `is_nil(obj)` in the C.
            } else if is_cons(head) {
                stack.push(tail);
                node = head;
                continue;
            } else if is_small(head) {
                // `unsigned_val` of a small int: a non-positive value is either
                // the forbidden NUL or a huge unsigned value (>= 0x110000).
                let value = signed_value(head);
                if value <= 0 {
                    return None;
                }
                let x = value as u64;
                if x >= 0x11_0000 || (0xD800..=0xDFFF).contains(&x) {
                    return None;
                }
                emit(x as u32);
            } else {
                return None;
            }
            node = tail;
        }
        if is_nil(node) {
            continue;
        }
        // An improper tail: neither `NIL` nor a cons.
        return None;
    }
    Some(())
}

/// `erts_native_filename_need(term, UTF8)` — the byte length of the UTF-8
/// expansion of `term`, or `None` for the C's `-1`.
fn native_need(term: Eterm, atoms: &AtomTable) -> Option<usize> {
    let mut need = 0usize;
    walk_native(term, atoms, &mut |cp| {
        need += match cp {
            0x0000..=0x007F => 1,
            0x0080..=0x07FF => 2,
            0x0800..=0xFFFF => 3,
            _ => 4,
        };
    })?;
    Some(need)
}

/// `erts_native_filename_put(term, UTF8, p)` — appends the UTF-8 expansion of
/// `term` to `out`.
fn native_put(term: Eterm, atoms: &AtomTable, out: &mut Vec<u8>) -> Option<()> {
    walk_native(term, atoms, &mut |cp| {
        let ch = char::from_u32(cp).unwrap_or(char::REPLACEMENT_CHARACTER);
        let mut buf = [0u8; 4];
        out.extend_from_slice(ch.encode_utf8(&mut buf).as_bytes());
    })
}

/// `convert_value_to_native` — the UTF-8 bytes of a *value* (an atom is
/// `badarg`, i.e. the C's `NULL`). An empty value is valid (the C's dead
/// `length == 0` check).
fn value_from_term(term: Eterm, atoms: &AtomTable) -> Option<Vec<u8>> {
    if is_atom(term) {
        return None;
    }
    let need = native_need(term, atoms)?;
    let mut out = Vec::with_capacity(need);
    native_put(term, atoms, &mut out)?;
    Some(out)
}

/// `convert_key_to_native` — as [`value_from_term`], additionally rejecting a
/// key containing `=`.
fn key_from_term(term: Eterm, atoms: &AtomTable) -> Option<Vec<u8>> {
    let bytes = value_from_term(term, atoms)?;
    if bytes.contains(&b'=') {
        return None;
    }
    Some(bytes)
}

