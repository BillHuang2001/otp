/// The raw bytes of `s` (the environment is byte-oriented; on Unix an `OsStr`
/// *is* its bytes, elsewhere a lossy UTF-8 view is used).
#[cfg(unix)]
fn os_str_bytes(s: &std::ffi::OsStr) -> Vec<u8> {
    use std::os::unix::ffi::OsStrExt;
    s.as_bytes().to_vec()
}

#[cfg(not(unix))]
fn os_str_bytes(s: &std::ffi::OsStr) -> Vec<u8> {
    s.to_string_lossy().into_owned().into_bytes()
}

/// The emulator-side environment table (`sysenv_global_env`), imported from the
/// process environment on first use — see the module docs.
///
/// A [`BTreeMap`] keeps the entries in key order ([`os_env_0`]'s documented
/// deviation). The mutex cannot be poisoned in a way that matters here (no
/// invariant outlives a panic), so a poisoned lock is recovered rather than
/// propagated.
fn env_table() -> &'static Mutex<BTreeMap<Vec<u8>, Vec<u8>>> {
    static ENV: OnceLock<Mutex<BTreeMap<Vec<u8>, Vec<u8>>>> = OnceLock::new();
    ENV.get_or_init(|| {
        let mut map = BTreeMap::new();
        for (key, value) in std::env::vars_os() {
            map.insert(os_str_bytes(&key), os_str_bytes(&value));
        }
        Mutex::new(map)
    })
}

/// Locks [`env_table`], recovering a poisoned lock instead of panicking.
fn env_lock() -> std::sync::MutexGuard<'static, BTreeMap<Vec<u8>, Vec<u8>>> {
    env_table().lock().unwrap_or_else(|poisoned| poisoned.into_inner())
}

