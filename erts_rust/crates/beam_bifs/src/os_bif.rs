/// `analyze_utf8`'s validity verdict: `std::str::from_utf8` enforces exactly the
/// same rules (no overlongs, no surrogates, nothing past `U+10FFFF`).
fn is_valid_utf8(bytes: &[u8]) -> bool {
    core::str::from_utf8(bytes).is_ok()
}

/// A char list of `bytes`' code points.
fn codepoint_list(ctx: &mut BifContext<'_>, text: &str) -> Result<Eterm> {
    let mut elems = Vec::new();
    for ch in text.chars() {
        elems.push(ctx.int(i64::from(ch as u32))?);
    }
    ctx.list(&elems)
}

/// A char list of `bytes`' individual bytes (`erts_bin_bytes_to_list`).
fn byte_list(ctx: &mut BifContext<'_>, bytes: &[u8]) -> Result<Eterm> {
    let mut elems = Vec::new();
    for byte in bytes {
        elems.push(ctx.int(i64::from(*byte))?);
    }
    ctx.list(&elems)
}

/// `erts_convert_native_to_filename` for the UTF-8 native encoding: `NIL` for
/// an empty value, a code point list when the bytes are valid UTF-8, else the
/// `noconvert` byte-for-byte list.
fn native_to_filename(ctx: &mut BifContext<'_>, bytes: &[u8]) -> Result<Eterm> {
    if bytes.is_empty() {
        return Ok(NIL);
    }
    match core::str::from_utf8(bytes) {
        Ok(text) => codepoint_list(ctx, text),
        Err(_) => byte_list(ctx, bytes),
    }
}

/// A char list of `s`' bytes (`os_getpid_0`'s `buf_to_intlist`).
fn string_list(ctx: &mut BifContext<'_>, s: &str) -> Result<Eterm> {
    byte_list(ctx, s.as_bytes())
}

/// `{error, warning}` — the shape `prim_file:internal_native2name/1` returns for
/// bytes that are not valid UTF-8 (`erts_get_filename_warning_type/0` is
/// `warning` on this host). Both atoms are *produced* here, so both are interned
/// on demand rather than looked up.
fn error_warning(ctx: &mut BifContext<'_>) -> Result<Eterm> {
    let error = ctx.intern_atom("error")?;
    let warning = ctx.intern_atom("warning")?;
    ctx.tuple(&[error, warning])
}

