//! `plb` — the Programming-Language-Benchmarks ("Benchmarks Game") compute kernels.
//!
//! Stages the checkout into a private scratch copy under `$TMPDIR` (the source repo is
//! configured **read-only**) and drives the repo's `dotnet`-based tool there
//! (`dotnet run -c Release --project tool -- --task bench --langs elixir`), reading the
//! machine-readable results it emits under `bench/build/_results/**/*.json` (`timeMS`,
//! `memBytes`) — from the **scratch** copy, so nothing is written back to the source.
//!
//! Repo: `$BENCH_PLB_REPO`, else `/home/bill/Source/Programming-Language-Benchmarks`.
//! `dotnet` is a hard prerequisite — when it is absent the workload is `skipped`
//! (`dotnet-absent`), never a fabricated number. As an **opt-in** fallback,
//! `$BENCH_TRY_NIX` (set to any non-empty value, with `nix` on `PATH`) makes the workload
//! try `nix shell nixpkgs#dotnet-sdk --command dotnet …` instead; that shim is validated
//! with a bounded `--version` probe and, if it fails, the honest `dotnet-absent` skip is
//! kept.

use std::path::{Path, PathBuf};
use std::process::Command;

use serde_json::Value;

use crate::metrics::{Category, Metric, Probe, Runtimes};
use crate::proc;
use crate::report::WorkloadResult;
use crate::scratch::{self, ScratchDir};
use crate::workload::{RunContext, Workload};
use crate::workloads::{collect_files, resolve_repo};

/// The documented default checkout path.
const DEFAULT_REPO: &str = "/home/bill/Source/Programming-Language-Benchmarks";

/// The external tool this workload drives.
const TOOL: &str = "dotnet";

/// The `nixpkgs` attribute that supplies [`TOOL`] for the opt-in `nix` fallback.
const TOOL_NIX_ATTR: &str = "dotnet-sdk";

/// The honest skip reason reported when [`TOOL`] cannot be resolved.
const TOOL_ABSENT: &str = "dotnet-absent";

/// Names of entries (VCS metadata, build output, generated files) that are **never**
/// staged into the scratch copy — they are regenerated by the build and would otherwise
/// bloat or poison the copy. Matched at every depth by [`crate::scratch::copy_tree`].
const SKIP_NAMES: &[&str] = &[
    ".git",
    "_build",
    "deps",
    "build",
    "_rel",
    "ebin",
    ".erlang.mk",
];

/// The PLB compute-kernel workload.
pub struct Plb;

fn repo() -> PathBuf {
    resolve_repo("plb", DEFAULT_REPO)
}

/// Whether the opt-in `nix` fallback is enabled: `$BENCH_TRY_NIX` set to a non-empty
/// value *and* `nix` resolvable on `PATH`. Deliberately cheap (no subprocess), so it is
/// safe to call from `probe()` / `bench list`.
fn nix_opt_in() -> bool {
    std::env::var("BENCH_TRY_NIX").is_ok_and(|v| !v.trim().is_empty())
        && proc::which("nix").is_some()
}

/// A `nix shell nixpkgs#<attr> --command <tool>` command line, with no tool arguments yet
/// (callers append the tool's own argv after it).
fn nix_shell(nix: &Path) -> Command {
    let mut cmd = Command::new(nix);
    cmd.args([
        "shell",
        &format!("nixpkgs#{TOOL_NIX_ATTR}"),
        "--command",
        TOOL,
    ]);
    cmd
}

/// Resolves `dotnet` to a ready-to-configure command: directly when it is on `PATH`,
/// else — only when `$BENCH_TRY_NIX` is set — through a `nix shell` shim that is first
/// validated with a bounded `--version` probe. `None` means the tool is genuinely
/// unavailable, so the caller keeps the honest `skipped(dotnet-absent)`.
fn tool_command() -> Option<Command> {
    if let Some(program) = proc::which(TOOL) {
        return Some(Command::new(program));
    }
    if !nix_opt_in() {
        return None;
    }
    let nix = proc::which("nix")?;
    let mut probe = nix_shell(&nix);
    probe.arg("--version");
    match proc::run(&mut probe) {
        Ok(out) if out.success => Some(nix_shell(&nix)),
        _ => None,
    }
}

impl Workload for Plb {
    fn id(&self) -> &'static str {
        "plb"
    }

    fn description(&self) -> &'static str {
        "Programming-Language-Benchmarks kernels via the dotnet tool"
    }

    fn category(&self) -> Category {
        Category::Compute
    }

    fn contracts(&self) -> &'static [&'static str] {
        &["A.1", "A.6"]
    }

    fn runtimes(&self) -> Runtimes {
        Runtimes::SysOnly
    }

    fn probe(&self) -> Probe {
        if !repo().is_dir() {
            return Probe::skipped("repo-missing");
        }
        if proc::which(TOOL).is_none() && !nix_opt_in() {
            return Probe::skipped(TOOL_ABSENT);
        }
        Probe::Ready
    }

    fn run(&self, ctx: &RunContext) -> WorkloadResult {
        let kind = ctx.runtime.kind;
        let r = repo();
        if !r.is_dir() {
            return WorkloadResult::skipped(
                self.id(),
                kind,
                self.category(),
                self.description(),
                "repo-missing",
            );
        }
        let Some(mut cmd) = tool_command() else {
            return WorkloadResult::skipped(
                self.id(),
                kind,
                self.category(),
                self.description(),
                TOOL_ABSENT,
            );
        };

        // Stage the read-only checkout into a private scratch copy and run there, so the
        // `dotnet` build never writes build artifacts (or `_results`) into the source repo.
        let scratch = match ScratchDir::new(self.id()) {
            Ok(dir) => dir,
            Err(e) => {
                return WorkloadResult::failed(
                    self.id(),
                    kind,
                    self.category(),
                    self.description(),
                    format!("scratch-dir-failed: {e}"),
                )
            }
        };
        let work = scratch.path().join(self.id());
        if let Err(e) = scratch::copy_tree(&r, &work, SKIP_NAMES) {
            return WorkloadResult::failed(
                self.id(),
                kind,
                self.category(),
                self.description(),
                format!("scratch-copy-failed: {e}"),
            );
        }

        let bench_dir = work.join("bench");
        if !bench_dir.is_dir() {
            return WorkloadResult::failed(
                self.id(),
                kind,
                self.category(),
                self.description(),
                "bench-dir-missing",
            );
        }

        cmd.current_dir(&bench_dir)
            .args(["run", "-c", "Release", "--project", "tool", "--"])
            .args(["--task", "bench", "--langs", "elixir"]);

        let out = match proc::run(&mut cmd) {
            Ok(o) => o,
            Err(e) => {
                return WorkloadResult::failed(
                    self.id(),
                    kind,
                    self.category(),
                    self.description(),
                    format!("dotnet-spawn-failed: {e}"),
                )
            }
        };

        let mut result = WorkloadResult::new(self.id(), kind, self.category(), self.description());
        result
            .metrics
            .push(Metric::scalar("wall_ms", "ms", out.wall_ms));
        result.peak_memory_bytes = out.peak_memory_bytes;

        // Read the result JSON from the *scratch* copy, never the (read-only) source repo.
        let (times, mems) = read_results(&bench_dir.join("build/_results"));
        if times.is_empty() {
            result.notes.push(format!(
                "no result JSON found (dotnet exit {:?})",
                out.exit_code
            ));
            if !out.success {
                result.notes.push(format!("stderr: {}", out.stderr.trim()));
            }
        } else {
            result
                .metrics
                .push(Metric::samples("test_time_ms", "ms", &times));
            if let Some(max_mem) = mems.iter().copied().fold(None, |a: Option<f64>, b| {
                Some(match a {
                    Some(a) => a.max(b),
                    None => b,
                })
            }) {
                result
                    .metrics
                    .push(Metric::scalar("test_mem_bytes", "bytes", max_mem));
            }
        }
        result
    }
}

/// Reads `timeMS`/`memBytes` fields from every result JSON under `dir`.
fn read_results(dir: &std::path::Path) -> (Vec<f64>, Vec<f64>) {
    let mut times = Vec::new();
    let mut mems = Vec::new();
    for path in collect_files(dir, "json") {
        let Ok(text) = std::fs::read_to_string(&path) else {
            continue;
        };
        let Ok(value) = serde_json::from_str::<Value>(&text) else {
            continue;
        };
        collect_number(&value, "timeMS", &mut times);
        collect_number(&value, "memBytes", &mut mems);
    }
    (times, mems)
}

/// Recursively collects numeric values stored under `key`.
fn collect_number(value: &Value, key: &str, out: &mut Vec<f64>) {
    match value {
        Value::Object(map) => {
            for (k, v) in map {
                if k == key {
                    if let Some(n) = v.as_f64() {
                        out.push(n);
                    }
                }
                collect_number(v, key, out);
            }
        }
        Value::Array(items) => {
            for item in items {
                collect_number(item, key, out);
            }
        }
        _ => {}
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn metadata_is_stable() {
        let w = Plb;
        assert_eq!(w.id(), "plb");
        assert_eq!(w.category(), Category::Compute);
        assert!(matches!(w.runtimes(), Runtimes::SysOnly));
    }

    #[test]
    fn probe_reports_dotnet_absence() {
        let p = Plb.probe();
        if proc::which(TOOL).is_none() && repo().is_dir() && !nix_opt_in() {
            assert_eq!(p.reason(), Some(TOOL_ABSENT));
        }
    }

    #[test]
    fn tool_command_is_none_when_absent_and_nix_is_not_opted_in() {
        // A `PATH`-only lookup when the fallback is off: absent ⇒ no command, so `run`
        // reports the honest skip rather than attempting anything.
        if proc::which(TOOL).is_none() && !nix_opt_in() {
            assert!(tool_command().is_none());
        }
    }

    #[test]
    fn nix_shell_wraps_the_tool_with_the_dotnet_sdk_attr() {
        let cmd = nix_shell(Path::new("/usr/bin/nix"));
        assert_eq!(cmd.get_program().to_string_lossy(), "/usr/bin/nix");
        let args: Vec<String> = cmd
            .get_args()
            .map(|a| a.to_string_lossy().into_owned())
            .collect();
        assert_eq!(
            args,
            vec!["shell", "nixpkgs#dotnet-sdk", "--command", "dotnet"]
        );
    }

    #[test]
    fn skip_names_cover_vcs_and_build_output() {
        for name in [
            ".git",
            "_build",
            "deps",
            "build",
            "_rel",
            "ebin",
            ".erlang.mk",
        ] {
            assert!(
                SKIP_NAMES.contains(&name),
                "{name} must be skipped when staging"
            );
        }
    }

    #[test]
    fn extracts_numbers_recursively() {
        let v: Value = serde_json::from_str(
            r#"{"results":[{"timeMS":12.5,"memBytes":100},{"timeMS":7.5,"nested":{"timeMS":3.0}}]}"#,
        )
        .unwrap();
        let mut times = Vec::new();
        collect_number(&v, "timeMS", &mut times);
        times.sort_by(|a, b| a.partial_cmp(b).unwrap());
        assert_eq!(times, vec![3.0, 7.5, 12.5]);
        let mut mems = Vec::new();
        collect_number(&v, "memBytes", &mut mems);
        assert_eq!(mems, vec![100.0]);
    }

    #[test]
    fn read_results_handles_missing_dir() {
        let (t, m) = read_results(std::path::Path::new("/nonexistent/xyzzy"));
        assert!(t.is_empty() && m.is_empty());
    }
}
