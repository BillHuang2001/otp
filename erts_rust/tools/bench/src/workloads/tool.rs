//! Shared resolution of the external command-line tools that the repo-driven workloads
//! shell out to (`rebar3` for `khepri`/`emqx`, `dotnet` for `plb`).
//!
//! All of them follow one policy, implemented here exactly once:
//!
//! * prefer the tool as found on `PATH`;
//! * otherwise — and **only** when the developer opts in — wrap it in a
//!   `nix shell nixpkgs#<attr> --command <tool>` shim that is first validated with a
//!   bounded `--version` probe;
//! * otherwise the caller keeps its own honest `skipped(<tool>-absent)` reason — never a
//!   fabricated number.
//!
//! The single opt-in for that fallback is the environment variable **`BENCH_TRY_NIX`**:
//! set it to any non-empty value, with `nix` on `PATH`, to enable the `nix shell` shim for
//! every workload that uses this module. It is off by default, so the default behavior is
//! a plain `PATH` lookup, and it is the only place this variable is read.

use std::path::Path;
use std::process::Command;

use crate::proc;

/// Names of entries (VCS metadata, build output, generated files) that are **never**
/// staged into a workload's scratch copy — they are regenerated by the build and would
/// otherwise bloat or poison the copy. Matched at every depth by
/// [`crate::scratch::copy_tree`].
pub const REPO_SKIP_NAMES: &[&str] = &[
    ".git",
    "_build",
    "deps",
    "build",
    "_rel",
    "ebin",
    ".erlang.mk",
];

/// Whether the opt-in `nix` fallback is enabled: `$BENCH_TRY_NIX` set to a non-empty
/// value *and* `nix` resolvable on `PATH`. Deliberately cheap (no subprocess), so it is
/// safe to call from `probe()` / `bench list`.
pub fn nix_opt_in() -> bool {
    std::env::var("BENCH_TRY_NIX").is_ok_and(|v| !v.trim().is_empty())
        && proc::which("nix").is_some()
}

/// Whether `tool` is *plausibly* resolvable: found on `PATH`, or the opt-in `nix` fallback
/// is enabled.
///
/// Cheap (no subprocess), so `probe()` can call it; the `nix shell` shim itself is only
/// validated — and may still turn out unusable — inside [`command_for`], which is why
/// `run()` must keep reporting the honest skip when that happens.
pub fn available(tool: &str) -> bool {
    proc::which(tool).is_some() || nix_opt_in()
}

/// A `nix shell nixpkgs#<nix_attr> --command <tool>` command line, with no tool arguments
/// yet (callers append the tool's own argv after it).
pub fn nix_shell(nix: &Path, tool: &str, nix_attr: &str) -> Command {
    let mut cmd = Command::new(nix);
    cmd.args(["shell", &format!("nixpkgs#{nix_attr}"), "--command", tool]);
    cmd
}

/// Resolves `tool` to a ready-to-configure command: directly when it is on `PATH`, else —
/// only when `$BENCH_TRY_NIX` is set — through a `nix shell nixpkgs#<nix_attr>` shim that
/// is first validated with a bounded `--version` probe. `None` means the tool is genuinely
/// unavailable, so the caller keeps its honest `skipped(<tool>-absent)`.
pub fn command_for(tool: &str, nix_attr: &str) -> Option<Command> {
    if let Some(program) = proc::which(tool) {
        return Some(Command::new(program));
    }
    if !nix_opt_in() {
        return None;
    }
    let nix = proc::which("nix")?;
    let mut probe = nix_shell(&nix, tool, nix_attr);
    probe.arg("--version");
    match proc::run(&mut probe) {
        Ok(out) if out.success => Some(nix_shell(&nix, tool, nix_attr)),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The arguments of `cmd`, as owned strings.
    fn args_of(cmd: &Command) -> Vec<String> {
        cmd.get_args()
            .map(|a| a.to_string_lossy().into_owned())
            .collect()
    }

    #[test]
    fn nix_shell_wraps_the_tool_and_the_nixpkgs_attr() {
        let rebar3 = nix_shell(Path::new("/usr/bin/nix"), "rebar3", "rebar3");
        assert_eq!(rebar3.get_program().to_string_lossy(), "/usr/bin/nix");
        assert_eq!(args_of(&rebar3), vec!["shell", "nixpkgs#rebar3", "--command", "rebar3"]);

        let dotnet = nix_shell(Path::new("/usr/bin/nix"), "dotnet", "dotnet-sdk");
        assert_eq!(dotnet.get_program().to_string_lossy(), "/usr/bin/nix");
        assert_eq!(
            args_of(&dotnet),
            vec!["shell", "nixpkgs#dotnet-sdk", "--command", "dotnet"]
        );
    }

    #[test]
    fn command_for_is_none_when_absent_and_nix_is_not_opted_in() {
        // A `PATH`-only lookup when the fallback is off: absent ⇒ no command, so the
        // caller reports the honest skip rather than attempting anything.
        if !nix_opt_in() {
            assert!(command_for("definitely-not-a-real-tool-xyzzy", "xyzzy").is_none());
            if proc::which("rebar3").is_none() {
                assert!(command_for("rebar3", "rebar3").is_none());
            }
            if proc::which("dotnet").is_none() {
                assert!(command_for("dotnet", "dotnet-sdk").is_none());
            }
        }
    }

    #[test]
    fn command_for_prefers_the_path_binary_over_any_shim() {
        // `sh` is present on every POSIX test host; resolved on `PATH`, it must come back
        // as a bare command (no `nix shell` wrapper, no arguments).
        if let Some(sh) = proc::which("sh") {
            let cmd = command_for("sh", "sh").expect("sh is on PATH");
            assert_eq!(cmd.get_program(), sh);
            assert!(cmd.get_args().next().is_none());
        }
    }

    #[test]
    fn available_follows_the_path_lookup_and_the_nix_opt_in() {
        // An unknown tool is available exactly when the (cheap) nix opt-in is enabled.
        assert_eq!(available("definitely-not-a-real-tool-xyzzy"), nix_opt_in());
        if proc::which("sh").is_some() {
            assert!(available("sh"));
        }
    }

    #[test]
    fn repo_skip_names_cover_vcs_and_build_output() {
        for name in [
            ".git",
            "_build",
            "deps",
            "build",
            "_rel",
            "ebin",
            ".erlang.mk",
        ] {
            assert!(
                REPO_SKIP_NAMES.contains(&name),
                "{name} must be skipped when staging"
            );
        }
    }
}
